using System.Text;

namespace OcctGen;

/// <summary>Writes one extern "C" shim source file per bound class.</summary>
static class CppEmitter
{
    public static void Emit(Model model, string dir)
    {
        foreach (var cls in model.Classes.Values)
            Writer.WriteIfChanged(Path.Combine(dir, cls.Name + ".cpp"), EmitClass(cls, model));
        foreach (var c in model.Collections.Values.Distinct())
            Writer.WriteIfChanged(Path.Combine(dir, c.Name + ".cpp"), CollectionEmitter.EmitCpp(c.Collection!, model.HeadersOf));
    }

    static string EmitClass(ClassInfo cls, Model model)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> by tools/OcctGen from bindings/occt.txt. Do not edit. </auto-generated>");
        sb.AppendLine("#include \"b3d_shim.h\"");
        var headers = new SortedSet<string>(cls.Referenced.SelectMany(model.HeadersOf)) { cls.Name + ".hxx" };
        foreach (var m in cls.Members)
            headers.Add(m.DeclaringClass + ".hxx");
        foreach (var h in headers)
            sb.AppendLine($"#include <{h}>");
        sb.AppendLine();

        var self = cls.Name;
        if (cls.CanDelete)
        {
            sb.AppendLine(cls.IsTransient
                ? $"B3D_API void b3d_{self}_delete(void* p) {{ b3d_release(static_cast<{self}*>(p)); }}"
                : $"B3D_API void b3d_{self}_delete(void* p) {{ delete static_cast<{self}*>(p); }}");
        }
        if (cls.CanCopy)
        {
            sb.AppendLine($"B3D_API void* b3d_{self}_copy(const void* p, b3d_error** err)");
            sb.AppendLine("{");
            sb.AppendLine("  *err = nullptr;");
            sb.AppendLine($"  if constexpr (std::is_copy_constructible_v<{self}>)");
            sb.AppendLine("  {");
            sb.AppendLine($"    try {{ return new {self}(*static_cast<const {self}*>(p)); }}");
            sb.AppendLine("    B3D_CATCH(err)");
            sb.AppendLine("  }");
            sb.AppendLine("  else");
            sb.AppendLine($"    *err = b3d_make_error(\"std::logic_error\", \"{self} cannot be copied\");");
            sb.AppendLine("  return nullptr;");
            sb.AppendLine("}");
        }
        foreach (var a in cls.Ancestors())
            sb.AppendLine($"B3D_API void* b3d_{self}_as_{a.Name}(void* p) {{ return static_cast<{a.Name}*>(static_cast<{self}*>(p)); }}");
        if (cls.IsTransient)
        {
            sb.AppendLine($"B3D_API void* b3d_{self}_as_Standard_Transient(void* p) {{ return static_cast<Standard_Transient*>(static_cast<{self}*>(p)); }}");
            sb.AppendLine($"B3D_API void* b3d_{self}_downcast(void* t) {{ return b3d_retain(dynamic_cast<{self}*>(static_cast<Standard_Transient*>(t))); }}");
        }

        foreach (var m in cls.Members)
        {
            sb.AppendLine();
            EmitMember(sb, cls, m);
        }
        return sb.ToString();
    }

    static void EmitMember(StringBuilder sb, ClassInfo cls, Member m)
    {
        var ps = new List<string>();
        if (!m.IsCtor && !m.IsStatic)
            ps.Add("void* self");
        ps.AddRange(m.Params.Select(p => $"{CParam(p.Type)} {Id(p.Name)}"));
        ps.Add("b3d_error** err");

        var ret = m.IsCtor ? "void*" : CReturn(m.Return);
        sb.AppendLine($"B3D_API {ret} {m.Export}({string.Join(", ", ps)})");
        sb.AppendLine("{");
        sb.AppendLine("  *err = nullptr;");
        if (m.IsImplicitDefault)
        {
            sb.AppendLine($"  if constexpr (std::is_default_constructible_v<{cls.Name}>)");
            sb.AppendLine("  {");
            sb.AppendLine($"    try {{ return {(cls.IsTransient ? "b3d_retain(" : "")}new {cls.Name}(){(cls.IsTransient ? ")" : "")}; }}");
            sb.AppendLine("    B3D_CATCH(err)");
            sb.AppendLine("  }");
            sb.AppendLine("  else");
            sb.AppendLine($"    *err = b3d_make_error(\"std::logic_error\", \"{cls.Name} cannot be default-constructed\");");
            sb.AppendLine("  return nullptr;");
            sb.AppendLine("}");
            return;
        }
        sb.AppendLine("  try");
        sb.AppendLine("  {");

        foreach (var p in m.Params.Where(p => p.Type.Kind == Kind.RefBool))
            sb.AppendLine($"    bool {Id(p.Name)}_b = *{Id(p.Name)} != 0;");

        var args = string.Join(", ", m.Params.Select(p => CArg(p)));
        string call;
        if (m.IsCtor)
            call = $"new {cls.Name}({args})";
        else if (m.IsStatic)
            call = $"{m.DeclaringClass}::{m.Name}({args})";
        else
        {
            var recv = m.DeclaringClass == cls.Name
                ? $"static_cast<{cls.Name}*>(self)"
                : $"static_cast<{m.DeclaringClass}*>(static_cast<{cls.Name}*>(self))";
            call = $"{recv}->{m.Name}({args})";
        }

        bool isVoid = !m.IsCtor && m.Return.Kind == Kind.Void;
        sb.AppendLine(isVoid ? $"    {call};" : $"    auto&& r = {call};");
        foreach (var p in m.Params.Where(p => p.Type.Kind == Kind.RefBool))
            sb.AppendLine($"    *{Id(p.Name)} = {Id(p.Name)}_b ? 1 : 0;");
        if (m.IsCtor)
            sb.AppendLine(cls.IsTransient ? "    return b3d_retain(r);" : "    return r;");
        else if (!isVoid)
            sb.AppendLine($"    return {CConvertReturn(m.Return, "r")};");
        else
            sb.AppendLine("    return;");

        sb.AppendLine("  }");
        sb.AppendLine("  B3D_CATCH(err)");
        if (!isVoid)
            sb.AppendLine("  return {};");
        sb.AppendLine("}");
    }

    static string CParam(Mapped t) => t.Kind switch
    {
        Kind.Prim => t.Name,
        Kind.Bool => "uint8_t",
        Kind.Enum => "int32_t",
        Kind.CString => "const char*",
        Kind.Value => $"const {t.CppName}*",
        Kind.MutValue => $"{t.CppName}*",
        Kind.Handle => $"{t.CppName}*",
        Kind.TransRef => $"{t.CppName}*",
        Kind.RefPrim => $"{t.Name}*",
        Kind.RefBool => "uint8_t*",
        _ => throw new ArgumentException(t.ToString()),
    };

    static string CReturn(Mapped t) => t.Kind switch
    {
        Kind.Void => "void",
        Kind.Prim => t.Name,
        Kind.Bool => "uint8_t",
        Kind.Enum => "int32_t",
        Kind.CString => "const char*",
        Kind.Value or Kind.Handle => "void*",
        _ => throw new ArgumentException(t.ToString()),
    };

    static string CArg(Param p)
    {
        var n = Id(p.Name);
        return p.Type.Kind switch
        {
            Kind.Prim or Kind.CString => n,
            Kind.Bool => $"{n} != 0",
            Kind.Enum => $"static_cast<{p.Type.Name}>({n})",
            Kind.Value or Kind.MutValue or Kind.RefPrim or Kind.TransRef => $"*{n}",
            Kind.Handle => $"occ::handle<{p.Type.CppName}>({n})",
            Kind.RefBool => $"{n}_b",
            _ => throw new ArgumentException(p.ToString()),
        };
    }

    static string CConvertReturn(Mapped t, string r) => t.Kind switch
    {
        Kind.Prim or Kind.CString => r,
        Kind.Bool => $"{r} ? 1 : 0",
        Kind.Enum => $"static_cast<int32_t>({r})",
        Kind.Value => $"new {t.CppName}({r})",
        Kind.Handle => $"b3d_retain(occ::handle<{t.CppName}>({r}).get())",
        _ => throw new ArgumentException(t.ToString()),
    };

    // Parameter names that collide with the shim's own locals
    static string Id(string name) => name is "self" or "err" or "r" ? name + "_" : name;
}
