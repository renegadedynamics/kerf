using System.Text;

namespace OcctGen;

/// <summary>Writes one C# wrapper file per bound class, plus the enums.</summary>
static class CsEmitter
{
    const string Header = "// <auto-generated> by tools/OcctGen from bindings/occt.txt. Do not edit. </auto-generated>";
    const string Lib = "b3docct";

    static readonly HashSet<string> Keywords =
    [
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
        "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override",
        "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    ];

    // Members of object/OcctObject that a bound method must not collide with
    static readonly HashSet<string> Reserved =
        ["GetType", "Equals", "GetHashCode", "ToString", "Finalize", "MemberwiseClone", "Dispose", "Ptr", "ReleaseNative"];

    public static IEnumerable<string> Emit(Model model, string dir)
    {
        var written = new List<string>();
        foreach (var cls in model.Classes.Values)
        {
            var path = Path.Combine(dir, cls.Name + ".g.cs");
            Writer.WriteIfChanged(path, EmitClass(cls));
            written.Add(path);
        }
        var enums = Path.Combine(dir, "Enums.g.cs");
        Writer.WriteIfChanged(enums, EmitEnums(model));
        written.Add(enums);
        return written;
    }

    static string EmitEnums(Model model)
    {
        var sb = new StringBuilder();
        sb.AppendLine(Header).AppendLine("namespace Build123d.Occt;");
        foreach (var e in model.Enums.Values)
        {
            sb.AppendLine().AppendLine($"public enum {e.Name}").AppendLine("{");
            foreach (var c in e.Enumerators)
                sb.AppendLine($"    {c.Name} = {c.InitVal},");
            sb.AppendLine("}");
        }
        return sb.ToString();
    }

    static string EmitClass(ClassInfo cls)
    {
        var sb = new StringBuilder();
        sb.AppendLine(Header);
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine();
        sb.AppendLine("namespace Build123d.Occt;");
        sb.AppendLine();

        var n = cls.Name;
        if (cls.IsStatic)
        {
            sb.AppendLine($"public static partial class {n}");
            sb.AppendLine("{");
        }
        else
        {
            var baseName = cls.Base?.Name ?? (cls.IsTransient ? "OcctTransient" : "OcctObject");
            sb.AppendLine($"public partial class {n} : {baseName}");
            sb.AppendLine("{");
            sb.AppendLine($"    internal {n}(IntPtr ptr) : base(ptr) {{ }}");
            sb.AppendLine();
            if (cls.CanDelete)
                sb.AppendLine($"    protected override void ReleaseNative(IntPtr ptr) => __N.b3d_{n}_delete(ptr);");
            sb.AppendLine($"    internal virtual IntPtr PtrAs_{n}() => Ptr;");
            foreach (var a in cls.Ancestors())
                sb.AppendLine($"    internal override IntPtr PtrAs_{a.Name}() => __N.b3d_{n}_as_{a.Name}(Ptr);");
            if (cls.IsTransient)
            {
                sb.AppendLine($"    internal override IntPtr PtrAs_Standard_Transient() => __N.b3d_{n}_as_Standard_Transient(Ptr);");
                sb.AppendLine();
                sb.AppendLine($"    /// <summary>The object as a {n}, or null if it is not one.</summary>");
                sb.AppendLine($"    public static {(cls.Base is null ? "" : "new ")}{n}? DownCast(OcctTransient? obj)");
                sb.AppendLine("    {");
                sb.AppendLine("        if (obj is null) return null;");
                sb.AppendLine($"        var p = __N.b3d_{n}_downcast(obj.PtrAs_Standard_Transient());");
                sb.AppendLine("        GC.KeepAlive(obj);");
                sb.AppendLine($"        return p == IntPtr.Zero ? null : new {n}(p);");
                sb.AppendLine("    }");
            }
        }

        int ctorIndex = 0;
        foreach (var m in cls.Members)
        {
            sb.AppendLine();
            if (m.IsCtor)
                EmitCtor(sb, cls, m, ctorIndex++);
            else
                EmitMethod(sb, cls, m);
        }

        EmitNative(sb, cls);
        sb.AppendLine("}");
        return sb.ToString();
    }

    static void EmitCtor(StringBuilder sb, ClassInfo cls, Member m, int index)
    {
        var ps = string.Join(", ", m.Params.Select(CsParam));
        var fwd = string.Join(", ", m.Params.Select(p => (IsRef(p.Type) ? "ref " : "") + Id(p.Name)));
        sb.AppendLine($"    public {cls.Name}({ps}) : this(__New{index}({fwd})) {{ }}");
        sb.AppendLine();
        sb.AppendLine($"    private static IntPtr __New{index}({ps})");
        sb.AppendLine("    {");
        EmitBody(sb, m, receiver: null, retConv: "__r");
        sb.AppendLine("    }");
    }

    static void EmitMethod(StringBuilder sb, ClassInfo cls, Member m)
    {
        var name = MemberName(cls, m.Name);
        var mods = "public " + (m.IsStatic ? "static " : "") + (m.HidesBase ? "new " : "");
        sb.AppendLine($"    {mods}{CsReturn(m.Return)} {name}({string.Join(", ", m.Params.Select(CsParam))})");
        sb.AppendLine("    {");
        EmitBody(sb, m, receiver: m.IsStatic ? null : $"PtrAs_{cls.Name}()", retConv: CsConvertReturn(m.Return, "__r"));
        sb.AppendLine("    }");
    }

    static void EmitBody(StringBuilder sb, Member m, string? receiver, string retConv)
    {
        foreach (var p in m.Params)
        {
            if (p.Type.Kind is Kind.Value or Kind.MutValue)
                sb.AppendLine($"        ArgumentNullException.ThrowIfNull({Id(p.Name)});");
            if (p.Type.Kind == Kind.RefBool)
                sb.AppendLine($"        byte __{p.Name} = {Id(p.Name)} ? (byte)1 : (byte)0;");
        }

        var args = new List<string>();
        if (receiver != null)
            args.Add(receiver);
        args.AddRange(m.Params.Select(CsArg));
        args.Add("out var __err");

        bool isVoid = !m.IsCtor && m.Return.Kind == Kind.Void;
        sb.AppendLine($"        {(isVoid ? "" : "var __r = ")}__N.{m.Export}({string.Join(", ", args)});");
        if (receiver != null)
            sb.AppendLine("        GC.KeepAlive(this);");
        foreach (var p in m.Params.Where(p => p.Type.Kind is Kind.Value or Kind.MutValue or Kind.Handle))
            sb.AppendLine($"        GC.KeepAlive({Id(p.Name)});");
        foreach (var p in m.Params.Where(p => p.Type.Kind == Kind.RefBool))
            sb.AppendLine($"        {Id(p.Name)} = __{p.Name} != 0;");
        sb.AppendLine("        OcctException.ThrowIfError(__err);");
        if (!isVoid)
            sb.AppendLine($"        return {retConv};");
    }

    static void EmitNative(StringBuilder sb, ClassInfo cls)
    {
        var n = cls.Name;
        sb.AppendLine();
        sb.AppendLine("    private static partial class __N");
        sb.AppendLine("    {");
        if (cls.CanDelete)
            Import(sb, $"b3d_{n}_delete", "void", ["IntPtr p"]);
        foreach (var a in cls.Ancestors())
            Import(sb, $"b3d_{n}_as_{a.Name}", "IntPtr", ["IntPtr p"]);
        if (cls.IsTransient)
        {
            Import(sb, $"b3d_{n}_as_Standard_Transient", "IntPtr", ["IntPtr p"]);
            Import(sb, $"b3d_{n}_downcast", "IntPtr", ["IntPtr t"]);
        }
        foreach (var m in cls.Members)
        {
            var ps = new List<string>();
            if (!m.IsCtor && !m.IsStatic)
                ps.Add("IntPtr self");
            ps.AddRange(m.Params.Select(p => $"{NativeParam(p.Type)} {Id(p.Name)}"));
            ps.Add("out IntPtr err");
            Import(sb, m.Export, m.IsCtor ? "IntPtr" : NativeReturn(m.Return), ps);
        }
        sb.AppendLine("    }");
    }

    static void Import(StringBuilder sb, string entry, string ret, List<string> ps)
    {
        sb.AppendLine($"        [LibraryImport(\"{Lib}\", StringMarshalling = StringMarshalling.Utf8)]");
        sb.AppendLine($"        internal static partial {ret} {entry}({string.Join(", ", ps)});");
    }

    static bool IsRef(Mapped t) => t.Kind is Kind.RefPrim or Kind.RefBool;

    static string CsParam(Param p) => $"{CsType(p.Type)} {Id(p.Name)}";

    static string CsType(Mapped t) => t.Kind switch
    {
        Kind.Prim => Mapped.CsPrim(t.Name),
        Kind.Bool => "bool",
        Kind.Enum => t.Name,
        Kind.CString => "string",
        Kind.Value or Kind.MutValue => t.Name,
        Kind.Handle => t.Name + "?",
        Kind.RefPrim => "ref " + Mapped.CsPrim(t.Name),
        Kind.RefBool => "ref bool",
        _ => throw new ArgumentException(t.ToString()),
    };

    static string CsReturn(Mapped t) => t.Kind switch
    {
        Kind.Void => "void",
        Kind.CString => "string?",
        _ => CsType(t),
    };

    static string CsArg(Param p)
    {
        var n = Id(p.Name);
        return p.Type.Kind switch
        {
            Kind.Prim or Kind.CString => n,
            Kind.Bool => $"{n} ? (byte)1 : (byte)0",
            Kind.Enum => $"(int){n}",
            Kind.Value or Kind.MutValue => $"{n}.PtrAs_{p.Type.Name}()",
            Kind.Handle => $"{n}?.PtrAs_{p.Type.Name}() ?? IntPtr.Zero",
            Kind.RefPrim => $"ref {n}",
            Kind.RefBool => $"ref __{p.Name}",
            _ => throw new ArgumentException(p.ToString()),
        };
    }

    static string CsConvertReturn(Mapped t, string r) => t.Kind switch
    {
        Kind.Void => "",
        Kind.Prim => r,
        Kind.Bool => $"{r} != 0",
        Kind.Enum => $"({t.Name}){r}",
        Kind.CString => $"Marshal.PtrToStringUTF8({r})",
        Kind.Value => $"new {t.Name}({r})",
        Kind.Handle => $"{r} == IntPtr.Zero ? null : new {t.Name}({r})",
        _ => throw new ArgumentException(t.ToString()),
    };

    static string NativeParam(Mapped t) => t.Kind switch
    {
        Kind.Prim => Mapped.CsPrim(t.Name),
        Kind.Bool => "byte",
        Kind.Enum => "int",
        Kind.CString => "string",
        Kind.Value or Kind.MutValue or Kind.Handle => "IntPtr",
        Kind.RefPrim => "ref " + Mapped.CsPrim(t.Name),
        Kind.RefBool => "ref byte",
        _ => throw new ArgumentException(t.ToString()),
    };

    static string NativeReturn(Mapped t) => t.Kind switch
    {
        Kind.Void => "void",
        Kind.Prim => Mapped.CsPrim(t.Name),
        Kind.Bool => "byte",
        Kind.Enum => "int",
        Kind.CString or Kind.Value or Kind.Handle => "IntPtr",
        _ => throw new ArgumentException(t.ToString()),
    };

    static string MemberName(ClassInfo cls, string name) =>
        name == cls.Name || Reserved.Contains(name) ? name + "_" : name;

    static string Id(string name) => Keywords.Contains(name) ? "@" + name : name;
}
