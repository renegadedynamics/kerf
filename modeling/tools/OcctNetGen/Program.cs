using System.Reflection;
using System.Runtime.Loader;
using OcctNetGen;

// OcctNetGen <Build123d.Occt.dll> <OCCT.NET bin dir> <cs-out-dir> <handwritten list> <report> [probe dir...]
//
// Writes src/Build123d.OcctNet/Generated: Build123d.Occt's public API, type for type and member for member, forwarding
// to OCCT.NET. Both assemblies are read by reflection; nothing in either runs.
if (args.Length < 5)
{
    Console.Error.WriteLine("usage: OcctNetGen <Build123d.Occt.dll> <occtnet-bin-dir> <cs-out-dir> <handwritten.txt> <report.txt> [probe-dir...]");
    return 2;
}
var (nativePath, occtDir, outDir, handPath, reportPath) = (args[0], args[1], args[2], args[3], args[4]);
var probes = args.Skip(5).Prepend(occtDir).Prepend(Path.GetDirectoryName(Path.GetFullPath(nativePath))!).ToList();

var context = new AssemblyLoadContext("OcctNetGen");
context.Resolving += (c, name) =>
{
    foreach (var dir in probes)
    {
        var path = Path.Combine(dir, name.Name + ".dll");
        if (File.Exists(path))
            return c.LoadFromAssemblyPath(Path.GetFullPath(path));
    }
    return null;
};
var native = context.LoadFromAssemblyPath(Path.GetFullPath(nativePath));
var occt = Directory.GetFiles(occtDir, "OcctNet.*.dll").Select(p => context.LoadFromAssemblyPath(Path.GetFullPath(p))).ToList();

var model = new Model(native, occt, Handwritten.Load(handPath));
var files = Emitter.Emit(model, outDir);
Writer.Prune(outDir, "*.g.cs", files);
Writer.WriteIfChanged(reportPath,
    "# Build123d.Occt members that the OCCT.NET backend can't forward, and why. Generated by tools/OcctNetGen; do not edit.\n"
    + "# A whole class not in OCCT.NET throws \"not yet ported to OCCT.NET\"; a member with no public counterpart throws\n"
    + "# \"not available through OCCT.NET's public API\". Hand-written members (bindings/occtnet.handwritten.txt) aren't listed.\n"
    + string.Concat(model.Report.Distinct().Order(StringComparer.Ordinal).Select(s => s + "\n")));
Console.WriteLine($"{model.Types.Count} types: {model.Forwarded} members forwarded, {model.Report.Count} not");
return 0;
