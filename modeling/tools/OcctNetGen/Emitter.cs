using System.Reflection;
using System.Text;

namespace OcctNetGen;

/// <summary>Writes one file per Build123d.Occt type: its public API, forwarding to OCCT.NET.</summary>
internal static class Emitter
{
    private const BindingFlags Declared = BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;

    public static IEnumerable<string> Emit(Model model, string outDir)
    {
        Directory.CreateDirectory(outDir);
        foreach (var info in model.Types.Values.OrderBy(i => i.Name, StringComparer.Ordinal))
        {
            if (info.Kind == Kind.Enum || model.Hand.Type(info.Name))
                continue;
            var path = Path.Combine(outDir, info.Name + ".g.cs");
            Writer.WriteIfChanged(path, EmitType(model, info));
            yield return path;
        }
    }

    private static string EmitType(Model model, TypeInfo info)
    {
        var t = info.Native;
        var sb = new StringBuilder();
        sb.Append("// <auto-generated> by tools/OcctNetGen from Build123d.Occt's public API. Do not edit. </auto-generated>\n");
        sb.Append("#nullable enable\n\nnamespace Build123d.Occt;\n\n");
        if (info.Kind == Kind.Missing)
            sb.Append($"/// <summary>Not yet ported to OCCT.NET: every member throws <see cref=\"NotSupportedException\"/>.</summary>\n");

        var isStatic = t.IsAbstract && t.IsSealed;
        var baseType = isStatic ? null : t.BaseType!;
        var interfaces = t.GetInterfaces()
            .Where(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IEnumerable<>))
            .Where(i => baseType is null || !baseType.GetInterfaces().Contains(i))
            .Select(Cs.Native);
        var heritage = string.Join(", ", (baseType is null ? [] : new[] { Cs.Native(baseType) }).Concat(interfaces));
        var modifiers = isStatic ? "static " : t.IsSealed ? "sealed " : "";
        sb.Append($"public {modifiers}partial class {t.Name}{(heritage.Length > 0 ? " : " + heritage : "")}\n{{\n");

        if (!isStatic)
            EmitStorage(model, info, sb);

        var members = t.GetMembers(Declared).OfType<MethodBase>()
            .Where(m => m is ConstructorInfo || !((MethodInfo)m).IsSpecialName)
            .OrderBy(m => m is ConstructorInfo ? 0 : 1).ThenBy(m => m.MetadataToken).ToList();
        int ctor = 0;
        foreach (var m in members)
        {
            if (model.Hand.Member(t.Name, m))
                continue;
            sb.Append('\n');
            if (m is ConstructorInfo c)
                EmitConstructor(model, info, c, ctor++, sb);
            else if (m.Name == "DownCast" && m.IsStatic)
                EmitDownCast(model, info, (MethodInfo)m, sb);
            else
                EmitMethod(model, info, (MethodInfo)m, sb);
        }
        sb.Append("}\n");
        return sb.ToString();
    }

    private static void EmitStorage(Model model, TypeInfo info, StringBuilder sb)
    {
        var name = info.Name;
        var baseInfo = model.Info(info.Native.BaseType!);
        var inner = info.Native.IsSealed ? "private" : "private protected";
        switch (info.Kind)
        {
            case Kind.Class:
                var occt = Cs.Occt(info.Occt!);
                sb.Append($"    internal {name}({occt} impl) : base(impl, true) {{ }}\n");
                sb.Append($"    {inner} {name}(object raw, bool _) : base(raw, _) {{ }}\n");
                sb.Append($"    internal {(baseInfo?.Kind == Kind.Class ? "new " : "")}{occt} Impl => ({occt})RawImpl;\n");
                break;
            case Kind.StructRoot:
                var v = Cs.Occt(info.Occt!);
                // TopoDS_Shape's V is a property, hand-written: a shape being built is frozen when first read
                if (name != "TopoDS_Shape")
                    sb.Append($"    internal {v} V;\n");
                sb.Append($"    internal {name}({v} v) {{ V = v; }}\n");
                break;
            case Kind.StructSub:
                sb.Append($"    internal {name}({model.Storage(info)} v) : base(v) {{ }}\n");
                var narrow = info.Occt!.Name["TopoDS_".Length..];
                sb.Append($"    internal {Cs.Occt(info.Occt)} S => global::Occt.TopoDS.{narrow}(V);\n");
                break;
            default:
                sb.Append($"    {inner} {name}(object raw, bool _) : base(raw, _) {{ }}\n");
                break;
        }
        sb.Append($"    {inner} {name}(Unported u) : base(u) {{ }}\n");
    }

    private static string Params(MethodBase m)
    {
        var ctx = new NullabilityInfoContext();
        return string.Join(", ", m.GetParameters().Select(p =>
        {
            var mod = p.ParameterType.IsByRef ? (p.IsOut ? "out " : p.IsIn ? "in " : "ref ") : "";
            return $"{mod}{Cs.Nullable(p.ParameterType, ctx.Create(p))} {Cs.Id(p.Name!)}";
        }));
    }

    private static string ArgNames(MethodBase m) => string.Join(", ", m.GetParameters().Select(p => Cs.Id(p.Name!)));

    private static IEnumerable<string> NullChecks(Model model, MethodBase m)
    {
        var ctx = new NullabilityInfoContext();
        foreach (var p in m.GetParameters())
            if (!p.ParameterType.IsByRef && model.Info(p.ParameterType) is { Kind: not Kind.Enum }
                && ctx.Create(p).ReadState != NullabilityState.Nullable)
                yield return $"ArgumentNullException.ThrowIfNull({Cs.Id(p.Name!)});";
    }

    private static string Unported(TypeInfo info, MethodBase m, string why, Model model)
    {
        model.Report.Add($"{info.Name}::{Cs.Key(m)}: {why}");
        return info.Kind == Kind.Missing
            ? $"Unported.Class(\"{info.Name}\")"
            : $"Unported.Member(\"{info.Name}::{Cs.Key(m)}\")";
    }

    private static bool Hides(Type t, MethodInfo m)
    {
        var types = m.GetParameters().Select(p => p.ParameterType).ToArray();
        for (var b = t.BaseType; b is not null && b.Namespace == "Build123d.Occt"; b = b.BaseType)
            if (b.GetMethod(m.Name, BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly, types) is not null)
                return true;
        return false;
    }

    private static void EmitConstructor(Model model, TypeInfo info, ConstructorInfo c, int index, StringBuilder sb)
    {
        var name = info.Name;
        var ps = c.GetParameters();
        // A copy of a struct-backed wrapper copies the struct
        if (info.Kind is Kind.StructRoot or Kind.StructSub && ps is [var only] && only.ParameterType == info.Native)
        {
            sb.Append($"    public {name}({Params(c)}) : this(__Copy({ArgNames(c)})) {{ }}\n\n");
            sb.Append($"    private static {model.Storage(info)} __Copy({name} {Cs.Id(only.Name!)})\n    {{\n");
            sb.Append($"        ArgumentNullException.ThrowIfNull({Cs.Id(only.Name!)});\n");
            sb.Append($"        return {Cs.Id(only.Name!)}.V;\n    }}\n");
            model.Forwarded++;
            return;
        }
        Match? match = null;
        var why = "";
        if (info.Kind is Kind.Class or Kind.StructRoot or Kind.StructSub)
        {
            match = model.Find(info, c, out why);
            if (match is null && ps.Length == 0 && info.Occt!.IsValueType)
                match = new Match(c, [], "", 0, 0);
            if (match is not null && match.Args.Any(a => a.Pre is not null))
                (match, why) = (null, "fills an argument");
        }
        else
            why = info.Kind == Kind.Missing ? "class not in OCCT.NET" : "OCCT.NET's class is static";
        if (match is null)
        {
            sb.Append($"    public {name}({Params(c)}) : this(Unported.Throw({Unported(info, c, why, model)})) {{ }}\n");
            return;
        }
        model.Forwarded++;
        var storage = model.Storage(info);
        sb.Append($"    public {name}({Params(c)}) : this(__New{index}({ArgNames(c)})) {{ }}\n\n");
        sb.Append($"    private static {storage} __New{index}({Params(c)})\n    {{\n");
        foreach (var check in NullChecks(model, c))
            sb.Append($"        {check}\n");
        sb.Append("        try\n        {\n");
        sb.Append($"            return new {Cs.Occt(info.Occt!)}({string.Join(", ", match.Args.Select(a => a.Expr))});\n");
        sb.Append("        }\n");
        sb.Append("        catch (global::Occt.Standard_Failure __e)\n        {\n            throw OcctException.From(__e);\n        }\n    }\n");
    }

    private static void EmitDownCast(Model model, TypeInfo info, MethodInfo m, StringBuilder sb)
    {
        var mods = $"public static {(Hides(info.Native, m) ? "new " : "")}";
        var p = Cs.Id(m.GetParameters()[0].Name!);
        if (info.Kind == Kind.Class)
        {
            sb.Append($"    {mods}{info.Name}? DownCast(OcctTransient? {p}) =>\n");
            sb.Append($"        {p}?.RawImpl is {Cs.Occt(info.Occt!)} __x ? new {info.Name}(__x) : null;\n");
            model.Forwarded++;
        }
        else
        {
            // Nothing of a class OCCT.NET doesn't have can exist
            sb.Append($"    {mods}{info.Name}? DownCast(OcctTransient? {p}) => null;\n");
        }
    }

    private static void EmitMethod(Model model, TypeInfo info, MethodInfo m, StringBuilder sb)
    {
        var ctx = new NullabilityInfoContext();
        var ret = Cs.Nullable(m.ReturnType, ctx.Create(m.ReturnParameter));
        var mods = $"public {(m.IsStatic ? "static " : "")}{(Hides(info.Native, m) ? "new " : "")}";
        var sig = $"    {mods}{ret} {m.Name}({Params(m)})";

        Match? match = null;
        string why;
        if (info.Kind is Kind.Missing)
            why = "class not in OCCT.NET";
        else if (!m.IsStatic && info.Kind is Kind.Static or Kind.StaticOnly)
            why = "OCCT.NET's class is static";
        else
            match = model.Find(info, m, out why);
        if (match is null)
        {
            sb.Append($"{sig} => throw {Unported(info, m, why, model)};\n");
            return;
        }
        model.Forwarded++;

        var args = string.Join(", ", match.Args.Select(a => a.Expr));
        var owner = m.IsStatic ? Cs.Occt(info.Occt!) : Model.Receiver(info, "this");
        var call = match.Target is PropertyInfo ? $"{owner}.{match.Target.Name}" : $"{owner}.{match.Target.Name}({args})";
        sb.Append($"{sig}\n    {{\n");
        foreach (var check in NullChecks(model, m))
            sb.Append($"        {check}\n");
        sb.Append("        try\n        {\n");
        foreach (var a in match.Args.Where(a => a.Pre is not null))
            sb.Append($"            {a.Pre}\n");
        var returns = m.ReturnType != typeof(void);
        if (match.Twin)
            sb.Append($"            this.V = {call};\n");
        else
            sb.Append(returns ? $"            var __r = {call};\n" : $"            {call};\n");
        foreach (var a in match.Args.Where(a => a.Post is not null))
            sb.Append($"            {a.Post}\n");
        if (returns)
            sb.Append($"            return {match.Result};\n");
        sb.Append("        }\n");
        sb.Append("        catch (global::Occt.Standard_Failure __e)\n        {\n            throw OcctException.From(__e);\n        }\n    }\n");
    }
}
