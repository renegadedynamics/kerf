// Generates src/Kerf.Kernel.ModelingData/TopoDS/TopoDS_{Vertex,Edge,Wire,Face,Shell,Solid,CompSolid,Compound}.cs from
// TopoDS_Shape.cs (docs/phase3-design.md, section 2). C# structs can't inherit, so each subtype is a struct with
// TopoDS_Shape's three fields and a copy of its members: the text between the "<generated-members>" and
// "</generated-members>" markers of TopoDS_Shape.cs, verbatim, plus the type's own constructors, equality and the
// (Since unit 10Q the checked-in subtypes' Reversed() returns the subtype: keep that if this tool is run again.)
// implicit conversion to TopoDS_Shape. The members keep OCCT's types: Reversed() of an edge returns a TopoDS_Shape,
// as in C++.
//
//   dotnet run tools/gen-topods-subtypes.cs          (writes the files)
//   dotnet run tools/gen-topods-subtypes.cs --check  (fails if a file differs from what would be written)

using System.Text;

string aRoot = FindRoot(Directory.GetCurrentDirectory())
               ?? throw new InvalidOperationException("Run from inside the Kerf repository.");
string aDir = Path.Combine(aRoot, "src", "Kerf.Kernel.ModelingData", "TopoDS");
bool isCheck = args.Contains("--check");

string aShapeText = File.ReadAllText(Path.Combine(aDir, "TopoDS_Shape.cs")).Replace("\r\n", "\n");
const string BeginMarker = "    // <generated-members>";
const string EndMarker = "    // </generated-members>";
int aBegin = aShapeText.IndexOf(BeginMarker, StringComparison.Ordinal);
int anEnd = aShapeText.IndexOf(EndMarker, StringComparison.Ordinal);
if (aBegin < 0 || anEnd < aBegin)
{
    Console.Error.WriteLine("TopoDS_Shape.cs has no <generated-members> region.");
    return 1;
}

// From the line after the begin marker to the end marker (exclusive)
int aRegionStart = aShapeText.IndexOf('\n', aBegin) + 1;
string aMembers = aShapeText[aRegionStart..anEnd].TrimStart('\n').TrimEnd('\n', ' ') + "\n";

(string Name, string Kind, string Doc)[] aTypes =
[
    ("Vertex", "vertex", "a vertex"),
    ("Edge", "edge", "an edge"),
    ("Wire", "wire", "a wire"),
    ("Face", "face", "a face"),
    ("Shell", "shell", "a shell"),
    ("Solid", "solid", "a solid"),
    ("CompSolid", "composite solid", "a composite solid"),
    ("Compound", "compound", "a compound"),
];

int aDiffers = 0;
foreach ((string aName, string aKind, string aDoc) in aTypes)
{
    string aType = "TopoDS_" + aName;
    var aText = new StringBuilder();
    aText.Append($$"""
        // Generated by tools/gen-topods-subtypes.cs from TopoDS_Shape.cs: do not edit, regenerate.
        // Port of: src/ModelingData/TKBRep/TopoDS/{{aType}}.hxx
        // Open CASCADE Technology V8_0_1 (b8f597c6). Copyright (c) 1990-1999 Matra Datavision; 1999-2026 OPEN CASCADE SAS.
        // Copyright (c) 2026 The Kerf Contributors. LGPL 2.1 with the Open CASCADE exception (see LICENSE).

        namespace Kerf.Engine;

        /// <summary>
        /// Describes {{aDoc}}: a reference to an underlying {{aKind}}, a location for it and an orientation. A
        /// <see cref="TopoDS_Shape"/> known to be {{aDoc}}, with the same fields and members; it converts implicitly to
        /// TopoDS_Shape, and <c>TopoDS.{{aName}}(S)</c> narrows a shape to it.
        /// </summary>
        /// <remarks><c>new {{aType}}()</c> is a null shape with orientation EXTERNAL, as OCCT's.</remarks>
        public partial struct {{aType}} : IEquatable<{{aType}}>
        {
            private TopoDS_TShape? myTShape;
            private TopLoc_Location myLocation;
            private TopAbs_Orientation myOrient;

            /// <summary>A null {{aKind}} (orientation EXTERNAL, as OCCT's).</summary>
            public {{aType}}()
            {
                myTShape = null;
                myLocation = new TopLoc_Location();
                myOrient = TopAbs_Orientation.TopAbs_EXTERNAL;
            }

            /// <summary>A shape with the given fields: the conversions between the shape types.</summary>
            internal {{aType}}(TopoDS_TShape? theTShape, in TopLoc_Location theLocation, TopAbs_Orientation theOrient)
            {
                myTShape = theTShape;
                myLocation = theLocation;
                myOrient = theOrient;
            }


        """.Replace("\r\n", "\n"));
    aText.Append(aMembers);
    aText.Append($$"""

            /// <summary>OCCT's <c>operator==</c>: <see cref="IsEqual"/>.</summary>
            public readonly bool Equals({{aType}} other) => IsEqual(other);

            /// <summary><see cref="IsEqual"/> with any of the nine shape types.</summary>
            public override readonly bool Equals(object? obj) => TopoDS_Shape.EqualsObject(this, obj);

            /// <summary>As <see cref="TopoDS_Shape.GetHashCode"/>: the same value as the TopoDS_Shape it converts to.</summary>
            public override readonly int GetHashCode() => TopoDS_Shape.HashCodeOf(myTShape, myLocation);

            public static bool operator ==(in {{aType}} theLeft, in {{aType}} theRight) => theLeft.IsEqual(theRight);

            public static bool operator !=(in {{aType}} theLeft, in {{aType}} theRight) => !theLeft.IsEqual(theRight);

            /// <summary>The type and orientation, or "NULL".</summary>
            public override readonly string ToString() => TopoDS_Shape.ToStringOf(this);

            /// <summary>The C++ upcast: the same three fields as a TopoDS_Shape.</summary>
            public static implicit operator TopoDS_Shape(in {{aType}} theShape)
                => new TopoDS_Shape(theShape.myTShape, theShape.myLocation, theShape.myOrient);
        }

        """.Replace("\r\n", "\n"));

    string aPath = Path.Combine(aDir, aType + ".cs");
    string aNew = aText.ToString();
    if (isCheck)
    {
        string anOld = File.Exists(aPath) ? File.ReadAllText(aPath).Replace("\r\n", "\n") : "";
        if (anOld != aNew)
        {
            Console.Error.WriteLine($"{aType}.cs is out of date: run dotnet run tools/gen-topods-subtypes.cs");
            aDiffers++;
        }
    }
    else
    {
        File.WriteAllText(aPath, aNew);
        Console.WriteLine($"Wrote {aPath}");
    }
}

return aDiffers == 0 ? 0 : 1;

static string? FindRoot(string theDir)
{
    for (DirectoryInfo? aDir = new(theDir); aDir is not null; aDir = aDir.Parent)
    {
        if (File.Exists(Path.Combine(aDir.FullName, "Kerf.Kernel.slnx")))
        {
            return aDir.FullName;
        }
    }

    return null;
}
