// Writes docs/port-status.md: for each OCCT toolkit and package, how many of its source files have been ported,
// read from the "// Port of:" lines at the top of the C# files (docs/translation-rules.md).
//
//   dotnet run tools/port-status.cs

using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

string aRoot = FindRoot(AppContext.BaseDirectory) ?? FindRoot(Directory.GetCurrentDirectory())
               ?? throw new InvalidOperationException("Run from inside the Kerf repository.");
string anOcctSrc = Path.Combine(aRoot, ".deps", "occt-src", "src");
if (!Directory.Exists(anOcctSrc))
{
    Console.Error.WriteLine($"No OCCT source at {anOcctSrc}: run tools/get-occt.ps1");
    return 1;
}

string[] aSourceExtensions = [".hxx", ".cxx", ".lxx", ".gxx", ".pxx", ".c", ".h"];

// Every OCCT file the port says it covers
var aPorted = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
var aPortOf = new Regex(@"^// Port of: (\S+)", RegexOptions.Multiline);
foreach (string aFile in Directory.EnumerateFiles(Path.Combine(aRoot, "src"), "*.cs", SearchOption.AllDirectories))
{
    using var aReader = new StreamReader(aFile);
    var aHeader = new StringBuilder();
    for (int i = 0; i < 20 && aReader.ReadLine() is { } aLine; i++)
    {
        aHeader.AppendLine(aLine);
    }

    foreach (Match aMatch in aPortOf.Matches(aHeader.ToString()))
    {
        aPorted.Add(aMatch.Groups[1].Value.Replace('\\', '/'));
    }
}

var aReport = new StringBuilder();
aReport.AppendLine("# Port status");
aReport.AppendLine();
aReport.AppendLine("Generated by `dotnet run tools/port-status.cs` from the `// Port of:` lines of the C# sources. Lines are");
aReport.AppendLine("physical lines of OCCT source (comments included), excluding GTests. Only toolkits with ported files are");
aReport.AppendLine("broken down by package.");
aReport.AppendLine();
aReport.AppendLine("| Module | Toolkit | Files ported | Lines ported | % of lines |");
aReport.AppendLine("|---|---|---:|---:|---:|");

var aDetails = new StringBuilder();
long aTotalLines = 0, aTotalPortedLines = 0;
foreach (string aModule in Directory.EnumerateDirectories(anOcctSrc).Order(StringComparer.Ordinal))
{
    foreach (string aToolkit in Directory.EnumerateDirectories(aModule).Order(StringComparer.Ordinal))
    {
        var aPackages = new List<(string Name, int Files, int PortedFiles, long Lines, long PortedLines)>();
        foreach (string aPackage in Directory.EnumerateDirectories(aToolkit).Where(d => Path.GetFileName(d) != "GTests").Order(StringComparer.Ordinal))
        {
            int aFiles = 0, aPortedFiles = 0;
            long aLines = 0, aPortedLines = 0;
            foreach (string aFile in Directory.EnumerateFiles(aPackage).Where(f => aSourceExtensions.Contains(Path.GetExtension(f))))
            {
                long aCount = File.ReadLines(aFile).LongCount();
                string aRelative = "src/" + Path.GetRelativePath(anOcctSrc, aFile).Replace('\\', '/');
                aFiles++;
                aLines += aCount;
                if (aPorted.Contains(aRelative))
                {
                    aPortedFiles++;
                    aPortedLines += aCount;
                }
            }

            aPackages.Add((Path.GetFileName(aPackage), aFiles, aPortedFiles, aLines, aPortedLines));
        }

        int aTkFiles = aPackages.Sum(p => p.Files), aTkPortedFiles = aPackages.Sum(p => p.PortedFiles);
        long aTkLines = aPackages.Sum(p => p.Lines), aTkPortedLines = aPackages.Sum(p => p.PortedLines);
        aTotalLines += aTkLines;
        aTotalPortedLines += aTkPortedLines;
        aReport.AppendLine(Row(Path.GetFileName(aModule), Path.GetFileName(aToolkit), aTkPortedFiles, aTkFiles, aTkPortedLines, aTkLines));

        if (aTkPortedFiles > 0)
        {
            aDetails.AppendLine($"## {Path.GetFileName(aToolkit)}");
            aDetails.AppendLine();
            aDetails.AppendLine("| Package | Files ported | Lines ported | % of lines |");
            aDetails.AppendLine("|---|---:|---:|---:|");
            foreach (var p in aPackages.Where(p => p.Files > 0))
            {
                aDetails.AppendLine(Row(null, p.Name, p.PortedFiles, p.Files, p.PortedLines, p.Lines));
            }

            aDetails.AppendLine();
        }
    }
}

aReport.AppendLine(Row("**All**", "", aPorted.Count, 0, aTotalPortedLines, aTotalLines));
aReport.AppendLine();
aReport.Append(aDetails);

string anOutput = Path.Combine(aRoot, "docs", "port-status.md");
File.WriteAllText(anOutput, aReport.ToString().Replace("\r\n", "\n"));
Console.WriteLine(string.Create(CultureInfo.InvariantCulture,
                                $"{aPorted.Count} OCCT files ported, {aTotalPortedLines:N0} of {aTotalLines:N0} lines ({100.0 * aTotalPortedLines / aTotalLines:F2}%). Wrote {anOutput}"));
return 0;

static string Row(string? theModule, string theName, int thePortedFiles, int theFiles, long thePortedLines, long theLines)
{
    string aFiles = theFiles > 0 ? $"{thePortedFiles} / {theFiles}" : $"{thePortedFiles}";
    string aPercent = theLines > 0 ? (100.0 * thePortedLines / theLines).ToString("F1", CultureInfo.InvariantCulture) : "";
    string aLines = string.Create(CultureInfo.InvariantCulture, $"{thePortedLines:N0} / {theLines:N0}");
    return theModule is null
               ? $"| {theName} | {aFiles} | {aLines} | {aPercent} |"
               : $"| {theModule} | {theName} | {aFiles} | {aLines} | {aPercent} |";
}

static string? FindRoot(string theStart)
{
    for (var aDir = new DirectoryInfo(theStart); aDir is not null; aDir = aDir.Parent)
    {
        if (File.Exists(Path.Combine(aDir.FullName, "occt-version.json")))
        {
            return aDir.FullName;
        }
    }

    return null;
}
