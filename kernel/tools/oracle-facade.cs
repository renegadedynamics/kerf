    {
        throw new NotSupportedException($"{aType.FullName}: the facade has classes and enums only");
    }
    bool isStatic = aType.IsAbstract && aType.IsSealed;
    string aBase = aType.BaseType is { } b && b != typeof(object) ? b.Name : "NativeHandle";
    Type[] anEnumerated = [.. Enumerated(aType)];
    string anInterfaces = string.Concat(anEnumerated.Select(e => $", System.Collections.Generic.IEnumerable<{Facade(e, null)}>"));
    aFacade.Append(isStatic ? $"public static class {aType.Name}\n{{\n" : $"public class {aType.Name} : {aBase}{anInterfaces}\n{{\n");
