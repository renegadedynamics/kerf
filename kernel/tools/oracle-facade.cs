static Type Core(Type theType)
{
    while (true)
    {
        if (theType.IsByRef || theType.IsArray)
        {
            theType = theType.GetElementType()!;
        }
        else if (theType.IsGenericType && theType.GetGenericArguments() is [Type anArg])
        {
            theType = anArg;
        }
        else
        {
            return theType;
        }
    }
}

static IEnumerable<Type> SignatureTypes(MemberInfo theMember) => theMember switch
{
    MethodInfo m => m.GetParameters().Select(p => p.ParameterType).Append(m.ReturnType),
    ConstructorInfo c => c.GetParameters().Select(p => p.ParameterType),
    _ => [],
};

static IEnumerable<Type> Enumerated(Type theType)
    => theType.GetInterfaces().Where(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(IEnumerable<>)
                                          && theType.GetInterfaces().Count(j => j.IsGenericType && j.GetGenericTypeDefinition() == typeof(IEnumerable<>)) == 1)
                     .Select(i => i.GetGenericArguments()[0]);

static string? Keyword(Type theType) => theType == typeof(void) ? "void"
    : theType == typeof(bool) ? "bool" : theType == typeof(int) ? "int" : theType == typeof(long) ? "long"
    : theType == typeof(ulong) ? "ulong" : theType == typeof(uint) ? "uint" : theType == typeof(short) ? "short"
    : theType == typeof(byte) ? "byte" : theType == typeof(double) ? "double" : theType == typeof(float) ? "float"
    : theType == typeof(string) ? "string" : theType == typeof(object) ? "object" : null;

// The type as the facade names it (W types by name), with its nullability
string Facade(Type theType, NullabilityInfo? theInfo) => Name(theType, theInfo, false);

string RealName(Type theType) => Name(theType, null, true);

string Name(Type theType, NullabilityInfo? theInfo, bool isReal)
{
    if (theType.IsByRef)
    {
        return Name(theType.GetElementType()!, theInfo, isReal);
    }
    string aNullable = theInfo is { ReadState: NullabilityState.Nullable } && !theType.IsValueType ? "?" : "";
    if (Keyword(theType) is string aKeyword)
    {
        return aKeyword + aNullable;
    }
    if (theType.IsArray)
    {
        return Name(theType.GetElementType()!, theInfo?.ElementType, isReal) + "[]" + aNullable;
    }
    if (Nullable.GetUnderlyingType(theType) is Type anUnderlying)
    {
        return Name(anUnderlying, null, isReal) + "?";
    }
    if (theType.IsGenericType)
    {
        string aDef = theType.GetGenericTypeDefinition().FullName!;
        aDef = aDef[..aDef.IndexOf('`')];
        string anArgs = string.Join(", ", theType.GetGenericArguments().Select((a, i) => Name(a, theInfo?.GenericTypeArguments.ElementAtOrDefault(i), isReal)));
        return $"{aDef}<{anArgs}>{aNullable}";
    }
    if (theType.Namespace == W)
    {
        return (isReal ? "W." : "") + theType.Name + aNullable;
    }
    return theType.FullName + aNullable;
}

string Signature(Type theType, string theName, ParameterInfo[] theParams)
    => $"{theType.Name}.{theName}({string.Join(",", theParams.Select(p => (p.IsOut ? "out " : p.ParameterType.IsByRef ? "ref " : "") + Name(p.ParameterType, null, false)))})";

string Params(ParameterInfo[] theParams) => string.Join(", ", theParams.Select(p =>
{
    string aModifier = p.IsOut ? "out " : p.ParameterType.IsByRef ? (p.IsIn ? "in " : "ref ") : p.IsDefined(typeof(ParamArrayAttribute)) ? "params " : "";
    string aDefault = p.HasDefaultValue ? " = " + Literal(p.ParameterType, p.DefaultValue) : "";
    return $"{aModifier}{Facade(p.ParameterType, aNull.Create(p))} {Id(p.Name!)}{aDefault}";
}));

static string Id(string theName) => theName is "object" or "string" or "base" or "params" or "in" or "out" or "ref" or "event" or "operator" or "checked" or "fixed" or "lock" or "default" ? "@" + theName : theName;

string Literal(Type theType, object? theValue)
{
    if (theValue is null)
    {
        return theType.IsValueType && Nullable.GetUnderlyingType(theType) is null ? "default" : "null";
    }
    if (theType.IsEnum)
    {
        return $"({Facade(theType, null)}){Convert.ToInt64(theValue, CultureInfo.InvariantCulture)}";
    }
    return theValue switch
    {
        bool b => b ? "true" : "false",
        double d => double.IsPositiveInfinity(d) ? "double.PositiveInfinity" : double.IsNegativeInfinity(d) ? "double.NegativeInfinity" : d.ToString("R", CultureInfo.InvariantCulture) + "d",
        float f => f.ToString("R", CultureInfo.InvariantCulture) + "f",
        string s => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"",
        int or long or short or byte => Convert.ToString(theValue, CultureInfo.InvariantCulture)!,
        _ => throw new NotSupportedException($"default value {theValue}"),
    };
}

// The facade's argument for a parameter: its value (or null for out), spans as arrays
static string Arg(ParameterInfo theParam)
    => theParam.IsOut ? "null"
     : theParam.ParameterType.IsGenericType && theParam.ParameterType.GetGenericTypeDefinition() == typeof(ReadOnlySpan<>) ? Id(theParam.Name!) + ".ToArray()"
     : Id(theParam.Name!);

// A recorded result as the facade's type
string FromTape(Type theType, NullabilityInfo? theInfo, string theExpr)
{
    theType = theType.IsByRef ? theType.GetElementType()! : theType;
    bool isNullable = theInfo is { ReadState: NullabilityState.Nullable };
    if (theType.IsEnum)
    {
        return $"Tape.Enum<{theType.Name}>({theExpr})";
    }
    if (theType.IsValueType)
    {
        return Nullable.GetUnderlyingType(theType) is null ? $"({Facade(theType, null)}){theExpr}!" : $"({Facade(theType, null)}){theExpr}";
    }
    if (theType.IsArray)
    {
        Type anElement = theType.GetElementType()!;
        return anElement.IsPrimitive ? $"({Facade(theType, null)}){theExpr}{(isNullable ? "" : "!")}" : $"Tape.Array<{Facade(anElement, null)}>({theExpr})";
    }
    if (theType.IsGenericType)
    {
        Type anElement = theType.GetGenericArguments()[0];
        Type aDef = theType.GetGenericTypeDefinition();
        string anArray = $"Tape.Array<{Facade(anElement, null)}>({theExpr})";
        if (aDef == typeof(IEnumerator<>))
        {
            return $"((System.Collections.Generic.IEnumerable<{Facade(anElement, null)}>){anArray}).GetEnumerator()";
        }
        if (aDef == typeof(IReadOnlyList<>) || aDef == typeof(IEnumerable<>) || aDef == typeof(IReadOnlyCollection<>))
        {
            return anArray;
        }
        throw new NotSupportedException($"result type {theType}");
    }
    return $"({Facade(theType, theInfo)}){theExpr}{(isNullable ? "" : "!")}";
}

// An argument as native's type, in the recorder
string ToReal(Type theType, string theExpr)
{
    theType = theType.IsByRef ? theType.GetElementType()! : theType;
    if (theType.IsEnum)
    {
        return $"({RealName(theType)})System.Convert.ToInt64({theExpr})";
    }
    if (Nullable.GetUnderlyingType(theType) is Type anUnderlying && anUnderlying.IsEnum)
    {
        return $"({theExpr} is null ? null : ({RealName(anUnderlying)}?)System.Convert.ToInt64({theExpr}))";
    }
    if (theType.IsValueType && !(theType.IsGenericType && theType.GetGenericTypeDefinition() == typeof(ReadOnlySpan<>)))
    {
        return Nullable.GetUnderlyingType(theType) is null ? $"({RealName(theType)}){theExpr}" : $"({RealName(theType)}){theExpr}";
    }
    if (theType.IsGenericType && theType.GetGenericTypeDefinition() == typeof(ReadOnlySpan<>))
    {
        return $"({RealName(theType.GetGenericArguments()[0])}[]){theExpr}";
    }
    if (theType.IsArray || theType.IsGenericType)
    {
        Type anElement = theType.IsArray ? theType.GetElementType()! : theType.GetGenericArguments()[0];
        return anElement.Assembly == aWrappers ? $"Reals<{RealName(anElement)}>({theExpr})" : $"({RealName(theType)}){theExpr}";
    }
    if (theType.Assembly == aWrappers)
    {
        return $"Real<{RealName(theType)}>({theExpr})";
    }
    return $"({RealName(theType)}){theExpr}";
}

// Whether a facade base type has a member of the same name and parameters (so this one hides it: `new`)
bool Hides(Type theType, string theName, ParameterInfo[]? theParams)
{
    for (Type? aBase = theType.BaseType; aBase is not null && aBase != typeof(object); aBase = aBase.BaseType)
    {
        foreach (MemberInfo aMember in aMembers.Where(m => m.DeclaringType == aBase))
        {
            string aName = aMember is MethodInfo { IsSpecialName: true } mi ? mi.Name[4..] : aMember.Name;
            if (aName != theName)
            {
                continue;
            }
            if (theParams is null || aMember is not MethodBase aMethod
                || aMethod.GetParameters().Select(p => p.ParameterType).SequenceEqual(theParams.Select(p => p.ParameterType)))
            {
                return true;
            }
        }
    }
    return false;
}

// The recorder's call of the native member, with its out and ref parameters as locals; returns [result?, outs...]
(string Prologue, string Call, string Outs) RealCall(ParameterInfo[] theParams)
{
    var aPrologue = new StringBuilder();
    var anArgs = new List<string>();
    var anOuts = new List<string>();
    for (int i = 0; i < theParams.Length; i++)
    {
        ParameterInfo p = theParams[i];
        if (p.IsOut)
        {
            anArgs.Add($"out var o{i}");
            anOuts.Add($"o{i}");
        }
        else if (p.ParameterType.IsByRef && !p.IsIn)
        {
            aPrologue.Append(CultureInfo.InvariantCulture, $"var o{i} = {ToReal(p.ParameterType, $"a[{i}]")}; ");
            anArgs.Add($"ref o{i}");
            anOuts.Add($"o{i}");
        }
        else
        {
            anArgs.Add(ToReal(p.ParameterType, $"a[{i}]"));
        }
    }
    return (aPrologue.ToString(), string.Join(", ", anArgs), string.Join(", ", anOuts));
}

void Constructor(Type theType, ConstructorInfo theCtor)
{
    ParameterInfo[] aParams = theCtor.GetParameters();
    string aSig = Signature(theType, ".ctor", aParams);
    string anArgs = string.Concat(aParams.Select(p => ", " + Arg(p)));
    aFacade.Append(CultureInfo.InvariantCulture, $"    public {theType.Name}({Params(aParams)}) : base(Tape.New(\"{aSig}\"{anArgs})) {{ }}\n");
    (string aPrologue, string aCall, _) = RealCall(aParams);
    aRecord.Append(CultureInfo.InvariantCulture, $"        r[\"{aSig}\"] = (s, a) => {{ {aPrologue}return [new {RealName(theType)}({aCall})]; }};\n");
}

void Method(Type theType, MethodInfo theMethod)
{
    if (theMethod.IsGenericMethod)
    {
        throw new NotSupportedException($"{theType.Name}.{theMethod.Name}: generic");
    }
    ParameterInfo[] aParams = theMethod.GetParameters();
    string aSig = Signature(theType, theMethod.Name, aParams);
    bool isVoid = theMethod.ReturnType == typeof(void);
    string aStatic = theMethod.IsStatic ? "static " : "";
    string aNew = Hides(theType, theMethod.Name, aParams) ? "new " : "";
    string aSelf = theMethod.IsStatic ? "null" : "this";
    string anArgs = string.Concat(aParams.Select(p => ", " + Arg(p)));
    string aReturn = Facade(theMethod.ReturnType, aNull.Create(theMethod.ReturnParameter));
    var aBody = new StringBuilder();
    aBody.Append(CultureInfo.InvariantCulture, $"var r = Tape.Call({aSelf}, \"{aSig}\"{anArgs}); ");
    int k = isVoid ? 0 : 1;
    foreach (ParameterInfo p in aParams.Where(p => p.ParameterType.IsByRef && !p.IsIn))
    {
        aBody.Append(CultureInfo.InvariantCulture, $"{Id(p.Name!)} = {FromTape(p.ParameterType, aNull.Create(p), $"r[{k++}]")}; ");
    }
    if (!isVoid)
    {
        aBody.Append(CultureInfo.InvariantCulture, $"return {FromTape(theMethod.ReturnType, aNull.Create(theMethod.ReturnParameter), "r[0]")}; ");
    }
    aFacade.Append(CultureInfo.InvariantCulture, $"    public {aNew}{aStatic}{aReturn} {theMethod.Name}({Params(aParams)}) {{ {aBody}}}\n");

    (string aPrologue, string aCall, string anOuts) = RealCall(aParams);
    string aTarget = theMethod.IsStatic ? RealName(theType) : $"(({RealName(theType)})s)";
    string anInvoke = $"{aTarget}.{theMethod.Name}({aCall})";
    if (theMethod.Name == "GetEnumerator" && aParams.Length == 0 && Enumerated(theType).FirstOrDefault() is Type anElement)
    {
        // enumerated once, as an array
        anInvoke = $"System.Linq.Enumerable.ToArray((System.Collections.Generic.IEnumerable<{RealName(anElement)}>)s)";
    }
    string aResults = isVoid ? $"[{anOuts}]" : $"[__r{(anOuts.Length > 0 ? ", " + anOuts : "")}]";
    aRecord.Append(
        isVoid ? $"        r[\"{aSig}\"] = (s, a) => {{ {aPrologue}{anInvoke}; return {aResults}; }};\n"
               : $"        r[\"{aSig}\"] = (s, a) => {{ {aPrologue}var __r = {anInvoke}; return {aResults}; }};\n");
}

void Property(Type theType, PropertyInfo theProperty, List<MethodInfo> theAccessors)
{
    bool isStatic = (theProperty.GetMethod ?? theProperty.SetMethod)!.IsStatic;
    ParameterInfo[] anIndex = theProperty.GetIndexParameters();
    if (anIndex.Length > 0)
    {
        throw new NotSupportedException($"{theType.Name}: indexers aren't in the facade yet");
    }
    string aNew = Hides(theType, theProperty.Name, null) ? "new " : "";
    string aType = Facade(theProperty.PropertyType, aNull.Create(theProperty));
    string aSelf = isStatic ? "null" : "this";
    string aTarget = isStatic ? RealName(theType) : $"(({RealName(theType)})s)";
    var aText = new StringBuilder();
    aText.Append(CultureInfo.InvariantCulture, $"    public {aNew}{(isStatic ? "static " : "")}{aType} {theProperty.Name} {{ ");
    foreach (MethodInfo anAccessor in theAccessors.OrderBy(a => a.Name, StringComparer.Ordinal))
    {
        string aSig = $"{theType.Name}.{anAccessor.Name}";
        if (anAccessor.Name.StartsWith("get_", StringComparison.Ordinal))
        {
            aText.Append(CultureInfo.InvariantCulture, $"get => {FromTape(theProperty.PropertyType, aNull.Create(theProperty), $"Tape.Call({aSelf}, \"{aSig}\")[0]")}; ");
            aRecord.Append(CultureInfo.InvariantCulture, $"        r[\"{aSig}\"] = (s, a) => [{aTarget}.{theProperty.Name}];\n");
        }
        else
        {
            aText.Append(CultureInfo.InvariantCulture, $"set => Tape.Call({aSelf}, \"{aSig}\", value); ");
