using System.Text;
using System.Text.RegularExpressions;

namespace StepGen;

internal sealed class ClassResult
{
    public string Name = "";
    public string Package = "";
    public string Text = "";
    public List<string> Problems = [];
    public List<string> Notes = [];
    public int Lines;
    /// <summary>OCCT declares locals it doesn't use (CS0219 silenced in the file).</summary>
    public bool UnusedLocals;
}

internal sealed class Emitter
{
    private readonly Db myDb;
    private readonly string myOcctSrc;
    private readonly Overrides myOverrides;

    public Emitter(Db theDb, string theOcctSrc, Overrides theOverrides)
    {
        myDb = theDb;
        myOcctSrc = theOcctSrc;
        myOverrides = theOverrides;
    }

    public const string GeneratedLine = "// Generated by tools/stepgen from OCCT's C++ (decision 1208): regenerate rather than edit.";

    private static string Rel(string theRoot, string thePath) => Path.GetRelativePath(theRoot, thePath).Replace('\\', '/');

    private string Copyright(string theHeaderPath)
    {
        string aText = File.ReadAllText(Path.Combine(myOcctSrc, theHeaderPath));
        var aMatra = Regex.Match(aText, @"Copyright \(c\) (\d{4})(?:-(\d{4}))? Matra Datavision");
        var anOcc = Regex.Match(aText, @"Copyright \(c\) (\d{4})(?:-\d{4})? OPEN CASCADE SAS");
        string anOccFirst = anOcc.Success ? anOcc.Groups[1].Value : "1999";
        if (aMatra.Success)
        {
            string aMatraYears = aMatra.Groups[2].Success ? aMatra.Groups[1].Value + "-" + aMatra.Groups[2].Value : aMatra.Groups[1].Value;
            return $"// Open CASCADE Technology V8_0_1 (b8f597c6). Copyright (c) {aMatraYears} Matra Datavision; {anOccFirst}-2026 OPEN CASCADE SAS.";
        }

        return $"// Open CASCADE Technology V8_0_1 (b8f597c6). Copyright (c) {anOccFirst}-2026 OPEN CASCADE SAS.";
    }

    private static string Xml(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private static void Doc(StringBuilder sb, List<string> theDoc, string theIndent)
    {
        var aLines = theDoc.Select(d => d.Trim()).ToList();
        while (aLines.Count > 0 && aLines[^1].Length == 0)
        {
            aLines.RemoveAt(aLines.Count - 1);
        }

        while (aLines.Count > 0 && aLines[0].Length == 0)
        {
            aLines.RemoveAt(0);
        }

        if (aLines.Count == 0)
        {
            return;
        }

        sb.Append(theIndent).Append("/// <summary>\n");
        foreach (string l in aLines)
        {
            sb.Append(theIndent).Append("/// ").Append(Xml(l)).Append('\n');
        }

        sb.Append(theIndent).Append("/// </summary>\n");
    }

    private static string Fix(string theText) => Regex.Replace(theText, @"[ \t]+\n", "\n");

    // ------------------------------------------------------------------ enums

    public ClassResult EmitEnum(CppEnum theEnum, string theHeader, string thePackage)
    {
        var r = new ClassResult { Name = theEnum.Name, Package = thePackage };
        var sb = new StringBuilder();
        sb.Append("// Port of: ").Append(theHeader).Append('\n');
        sb.Append(Copyright(theHeader)).Append('\n');
        sb.Append("// Copyright (c) 2026 The OCCT.NET Contributors. LGPL 2.1 with the Open CASCADE exception (see LICENSE).\n");
        sb.Append(GeneratedLine).Append("\n\nnamespace Occt;\n\n");
        Doc(sb, theEnum.Doc, "");
        sb.Append("/// <remarks>An unscoped enum in C++; ported code imports it with <c>using static Occt.").Append(theEnum.Name).Append(";</c>.</remarks>\n");
        sb.Append("public enum ").Append(theEnum.Name).Append("\n{\n");
        var aTr = new Translator(myDb, new FnCtx { Cls = new CppClass { Name = theEnum.Name } }, 1);
        foreach (var m in theEnum.Members)
        {
            Doc(sb, m.Doc, "    ");
            sb.Append("    ").Append(m.Name);
            if (m.Value != null)
            {
                sb.Append(" = ").Append(aTr.Emit(new ExprParser(m.Value, 0, m.Value.Count, aTr.IsTypeName).ParseFull(), true));
            }

            sb.Append(",\n");
        }

        sb.Append("}\n");
        r.Text = Fix(sb.ToString());
        return r;
    }

    // ------------------------------------------------------------------ classes

    private sealed class Member
    {
        public CppMethod Decl = null!;
        public CppMethod? Def;
    }

    public ClassResult EmitClass(CppClass cls, List<Parser.SourceFunction> theDefs, List<CppField> theFileConstants)
    {
        var r = new ClassResult { Name = cls.Name, Package = cls.Package };
        if (myOverrides.WholeClass(cls.Name) is { } aWhole)
        {
            r.Text = aWhole;
            r.Notes.Add("written by hand (tools/stepgen/overrides)");
            return r;
        }

        r.Problems.AddRange(cls.Problems);

        bool isRwTool = cls.Package.StartsWith("RW", StringComparison.Ordinal) && !cls.IsNamespace;
        bool isValue = myDb.ValueClasses.Contains(cls.Name);
        bool isSelect = myDb.DerivesFrom(cls.Name, "StepData_SelectType");

        // pair declarations with definitions
        var aMembers = new List<Member>();
        var aUsedDefs = new HashSet<Parser.SourceFunction>();
        foreach (var d in cls.Methods)
        {
            if (d.IsDtor || d.IsDeleted)
            {
                continue;
            }

            var m = new Member { Decl = d };
            if (d.Body != null)
            {
                m.Def = d;
            }
            else
            {
                var aDef = theDefs.FirstOrDefault(f => !aUsedDefs.Contains(f) && f.ClassName == cls.Name && f.Method.Name == d.Name
                                                       && f.Method.Params.Count == d.Params.Count && SameParams(f.Method, d));
                aDef ??= theDefs.FirstOrDefault(f => !aUsedDefs.Contains(f) && f.ClassName == cls.Name && f.Method.Name == d.Name
                                                     && f.Method.Params.Count == d.Params.Count);
                if (aDef != null)
                {
                    aUsedDefs.Add(aDef);
                    m.Def = aDef.Method;
                }
            }

            aMembers.Add(m);
        }

        foreach (var f in theDefs)
        {
            if (!aUsedDefs.Contains(f) && f.ClassName == cls.Name && !cls.Methods.Contains(f.Method))
            {
                r.Problems.Add($"defined but not declared: {f.Method.Name}");
            }
        }

        var aHelpers = theDefs.Where(f => f.ClassName == null).Select(f => f.Method).ToList();

        var body = new StringBuilder();
        string I1 = "    ";

        // constants of the source file; its other statics (process-wide state) written by hand when an override has them
        string? aStatics = myOverrides.Statics(cls.Name);
        foreach (var f in theFileConstants)
        {
            string aField = FieldText(cls, f, true, aHelpers, theFileConstants, r);
            if (aStatics != null && !aField.StartsWith("private const ", StringComparison.Ordinal))
            {
                continue;
            }

            body.Append(I1).Append(aField).Append('\n');
        }

        if (aStatics != null)
        {
            r.Notes.Add("the source file's statics written by hand");
            body.Append(aStatics.TrimEnd('\n')).Append('\n');
        }

        if (theFileConstants.Count > 0 || aStatics != null)
        {
            body.Append('\n');
        }

        // fields
        var aMethodNames = new HashSet<string>(cls.Methods.Select(m => m.Name));
        foreach (var f in cls.Fields)
        {
            if (aMethodNames.Contains(f.Name))
            {
                r.Problems.Add($"field {f.Name} has a method's name");
            }

            Doc(body, f.Doc, I1);
            body.Append(I1).Append(FieldText(cls, f, false, aHelpers, theFileConstants, r)).Append('\n');
        }

        if (cls.Fields.Count > 0)
        {
            body.Append('\n');
        }

        bool hasDefaultCtor = cls.Methods.Any(m => m.IsCtor && m.Params.Count == 0);
        bool hasCopyCtor = cls.Methods.Any(m => m.IsCtor && m.Params.Count == 1 && m.Params[0].Type.Name == cls.Name);
        bool aNeedsCopy = isValue && !hasCopyCtor;
        if (aNeedsCopy && !hasDefaultCtor && !cls.Methods.Any(m => m.IsCtor))
        {
            body.Append(I1).Append("public ").Append(cls.Name).Append("()\n").Append(I1).Append("{\n").Append(I1).Append("}\n\n");
        }

        var aSignatures = new HashSet<string>();
        foreach (var m in aMembers)
        {
            var d = m.Decl;
            string aKey = d.SignatureKey(t => myDb.ParamModifier(t) + myDb.Map(t));
            if (!aSignatures.Add(aKey))
            {
                r.Problems.Add($"two C++ overloads map to one C# signature: {aKey}; the second left out");
                continue;
            }

            if (myOverrides.Method(cls.Name, d.Name, d.Params.Count) is { } aHand)
            {
                body.Append(aHand.TrimEnd('\n')).Append("\n\n");
                r.Notes.Add($"{d.Name}: written by hand");
                continue;
            }

            if (m.Def == null && !d.IsPure)
            {
                if (d.IsDefault && d.IsCtor)
                {
                    m.Def = new CppMethod { Name = d.Name, IsCtor = true, Params = d.Params, Body = [] };
                }
                else
                {
                    r.Problems.Add($"declared but not defined in OCCT (left out): {d.Origin}");
                    continue;
                }
            }

            if (d.IsCtor && d.Params.Count == 0 && m.Def?.Body is { } aCtorBody && OnceInit(aCtorBody, theFileConstants) is int aRest)
            {
                // "if (THE_init) return; THE_init = 1; ...": process-wide state set up once, by C#'s static constructor
                // (once and thread-safe, decision 1215); the instance constructor is empty
                var aStaticDef = new CppMethod { Name = d.Name, IsCtor = true, Params = [], Body = aCtorBody.GetRange(aRest, aCtorBody.Count - aRest) };
                body.Append(MethodText(cls, m.Decl, new CppMethod { Name = d.Name, IsCtor = true, Params = [], Body = [] }, aHelpers, theFileConstants, r, isRwTool));
                body.Append('\n');
                body.Append(MethodText(cls, m.Decl, aStaticDef, aHelpers, theFileConstants, r, isRwTool, theIsStaticCtor: true));
                body.Append('\n');
                r.Notes.Add("the constructor's one-time initialisation is a static constructor");
                continue;
            }

            body.Append(MethodText(cls, m.Decl, m.Def, aHelpers, theFileConstants, r, isRwTool));
            body.Append('\n');
            if ((d.IsVirtual || d.IsOverride) && myDb.QualifiedCalls.Contains(cls.Name + "::" + d.Name))
            {
                // obj->Class::Method() elsewhere: a non-virtual twin (decision 1211)
                body.Append(MethodText(cls, m.Decl, m.Def, aHelpers, theFileConstants, r, isRwTool, theTwinName: cls.Name + "_" + d.Name));
                body.Append('\n');
            }
        }

        if (aNeedsCopy)
        {
            body.Append(I1).Append("/// <summary>A copy: C++ holds this type by value and copies it (decision 1210).</summary>\n");
            body.Append(I1).Append("public ").Append(cls.Name).Append('(').Append(cls.Name).Append(" theOther)\n");
            body.Append(I1).Append("{\n");
            if (isSelect)
            {
                body.Append(I1).Append(I1).Append("SetFrom(theOther);\n");
            }
            else
            {
                foreach (var f in cls.Fields.Where(f => !f.IsStatic))
                {
                    string aValue = "theOther." + Db.Id(f.Name);
                    if (myDb.IsValueClass(f.Type))
                    {
                        aValue = "new " + myDb.Map(f.Type) + "(" + aValue + ")";
                    }
                    else if (f.ArraySize != null || f.Type.Name == "std::array")
                    {
                        aValue = "(" + myDb.Map(f.Type) + (f.ArraySize != null ? "[]" : "") + ")" + aValue + ".Clone()";
                    }

                    body.Append(I1).Append(I1).Append(Db.Id(f.Name)).Append(" = ").Append(aValue).Append(";\n");
                }
            }

            body.Append(I1).Append("}\n\n");
        }

        // file-level helpers
        foreach (var h in aHelpers)
        {
            if (myOverrides.Method(cls.Name, h.Name, h.Params.Count) is { } aHandHelper)
            {
                body.Append(aHandHelper.TrimEnd('\n')).Append("\n\n");
                r.Notes.Add($"{h.Name}: written by hand");
                continue;
            }

            body.Append(MethodText(cls, h, h, aHelpers, theFileConstants, r, isRwTool, theIsHelper: true));
            body.Append('\n');
        }

        // nested enums
        foreach (var e in cls.Enums)
        {
            Doc(body, e.Doc, I1);
            body.Append(I1).Append("public enum ").Append(e.Name).Append("\n").Append(I1).Append("{\n");
            foreach (var em in e.Members)
            {
                body.Append(I1).Append(I1).Append(em.Name).Append(",\n");
            }

            body.Append(I1).Append("}\n\n");
        }

        // the file
        var sb = new StringBuilder();
        sb.Append("// Port of: ").Append(cls.Header).Append('\n');
        foreach (string s in cls.Sources)
        {
            sb.Append("// Port of: ").Append(s).Append('\n');
        }

        sb.Append(Copyright(cls.Header)).Append('\n');
        sb.Append("// Copyright (c) 2026 The OCCT.NET Contributors. LGPL 2.1 with the Open CASCADE exception (see LICENSE).\n");
        sb.Append(GeneratedLine).Append("\n\n");
        sb.Append("#nullable disable warnings\n");
        if (r.UnusedLocals)
        {
            sb.Append("#pragma warning disable CS0219 // OCCT declares locals it doesn't use\n");
        }

        string aBodyText = body.ToString().TrimEnd('\n') + "\n";
        var aUsings = UsingStatics(aBodyText, cls);
        if (aUsings.Count > 0)
        {
            sb.Append('\n');
            foreach (string u in aUsings)
            {
                sb.Append("using static Occt.").Append(u).Append(";\n");
            }
        }

        sb.Append("\nnamespace Occt;\n\n");
        Doc(sb, cls.Doc, "");
        string anAccess = isRwTool || cls.IsNamespace ? "internal" : "public";
        bool isAbstract = aMembers.Any(m => m.Decl.IsPure) || (!cls.IsNamespace && cls.Methods.Any(m => m.IsCtor) && cls.Methods.Where(m => m.IsCtor).All(m => m.Access == "protected") && false);
        sb.Append(anAccess).Append(cls.IsNamespace ? " static" : isAbstract ? " abstract" : "").Append(" class ").Append(cls.Name);
        string? aBase = cls.Base;
        if (aBase != null)
        {
            sb.Append(" : ").Append(aBase.Replace("::", "."));
        }

        if (cls.OtherBases.Count > 0)
        {
            r.Problems.Add("several base classes: " + string.Join(", ", cls.OtherBases));
        }

        sb.Append("\n{\n");
        sb.Append(aBodyText.TrimEnd('\n').Length > 0 ? aBodyText : "");
        sb.Append("}\n");
        r.Text = Fix(sb.ToString());
        foreach (string p in r.Problems.ToList())
        {
            _ = p;
        }

        return r;
    }

    /// <summary>
    /// The C++ idiom of a constructor that sets up process-wide state once: "if (FLAG) return; FLAG = 1;" on a
    /// file-level static. Returns the index of the body's first token after it, or null.
    /// </summary>
    private static int? OnceInit(List<Token> theBody, List<CppField> theFileConstants)
    {
        var aIdx = Enumerable.Range(0, theBody.Count).Where(k => !theBody[k].IsComment).ToList();
        string Tok(int n) => n < aIdx.Count ? theBody[aIdx[n]].Text : "";
        if (Tok(0) != "if" || Tok(1) != "(" || Tok(3) != ")")
        {
            return null;
        }

        string aFlag = Tok(2);
        if (!theFileConstants.Any(f => f.Name == aFlag && f.IsStatic && f.Type.Name is "int" or "bool" or "Standard_Integer" or "Standard_Boolean"))
        {
            return null;
        }

        int n = 4;
        if (Tok(n) == "{" && Tok(n + 1) == "return" && Tok(n + 2) == ";" && Tok(n + 3) == "}")
        {
            n += 4;
        }
        else if (Tok(n) == "return" && Tok(n + 1) == ";")
        {
            n += 2;
        }
        else
        {
            return null;
        }

        if (Tok(n) != aFlag || Tok(n + 1) != "=" || Tok(n + 3) != ";")
        {
            return null;
        }

        return aIdx[n + 3] + 1;
    }

    private bool SameParams(CppMethod a, CppMethod b)
    {
        for (int k = 0; k < a.Params.Count; k++)
        {
            if (myDb.Map(a.Params[k].Type) != myDb.Map(b.Params[k].Type))
            {
                return false;
            }
        }

        return true;
    }

    private List<string> UsingStatics(string theText, CppClass cls)
    {
        var aResult = new SortedSet<string>(StringComparer.Ordinal);
        // identifiers outside strings and comments
        string aCode = Regex.Replace(theText, "\"(?:[^\"\\\\]|\\\\.)*\"|//[^\n]*", " ");
        foreach (Match m in Regex.Matches(aCode, @"(?<![\w.])([A-Za-z_]\w*)"))
        {
            if (myDb.EnumOfMember.TryGetValue(m.Groups[1].Value, out string? anEnum) && anEnum != cls.Name)
            {
                // a nested enum of a class is reached through its class
                if (myDb.Enums.ContainsKey(anEnum))
                {
                    aResult.Add(anEnum);
                }
            }
        }

        return aResult.ToList();
    }

    private string FieldText(CppClass cls, CppField f, bool theFileLevel, List<CppMethod> theHelpers, List<CppField> theConsts, ClassResult r)
    {
        var aTr = new Translator(myDb, new FnCtx { Cls = cls, Helpers = theHelpers, FileConstants = theConsts }, 1);
        string anAccess = theFileLevel ? "private" : cls.IsNamespace ? "public" : f.Access;
        bool isCString = (f.Type.Name == "char" && f.ArraySize != null) || f.Type.IsCString || f.Type.Name == "std::string_view";
        if (f.Init is { Count: > 0 } && f.Init[0].Is("(") && f.IsStatic)
        {
            // "static T name(args)": a constant, or a static object built once
            var anArgs = new ExprParser(f.Init, 1, f.Init.Count - 1, aTr.IsTypeName).ParseComma();
            if (isCString || (Db.BuiltinMap.ContainsKey(f.Type.Name) && f.IsConstexpr))
            {
                return $"{anAccess} const {(isCString ? "string" : myDb.Map(f.Type.Bare()))} {Db.Id(f.Name)} = {aTr.Emit(anArgs, true)};";
            }

            return $"{anAccess} static readonly {myDb.Map(f.Type.Bare())} {Db.Id(f.Name)} = new {myDb.Map(f.Type.Bare())}({aTr.Emit(anArgs, true)});";
        }

        if ((f.IsConstexpr || (f.IsStatic && f.Type.IsConst)) && (isCString || Db.BuiltinMap.ContainsKey(f.Type.Name)) && f.Init != null)
        {
            string aType = isCString ? "string" : myDb.Map(f.Type.Bare());
            string aValue = aTr.Emit(new ExprParser(f.Init, 0, f.Init.Count, aTr.IsTypeName).ParseFull(), true);
            if (aValue.StartsWith('(') && aValue.EndsWith(')') && aValue.Count(ch => ch == '(') == 1)
            {
                aValue = aValue[1..^1];
            }

            return $"{anAccess} const {aType} {Db.Id(f.Name)} = {aValue};";
        }

        string aStatic = f.IsStatic ? "static " : "";
        string aCsType = myDb.Map(f.Type.Bare());
        if (f.ArraySize != null)
        {
            aCsType += "[]";
        }

        string anInit = "";
        if (f.Init != null && f.Init.Count > 0)
        {
            var e = new ExprParser(f.Init, 0, f.Init.Count, aTr.IsTypeName).ParseFull();
            string v = aTr.InitFrom(f.Type.Bare(), e);
            if (!(v is "null" or "0" or "0.0" or "false" or "default"))
            {
                anInit = " = " + v;
            }
        }
        else if (f.ArraySize != null)
        {
            anInit = " = new " + myDb.Map(f.Type.Bare()) + "[" + f.ArraySize + "]";
        }
        else if (f.Type.Name == "std::array")
        {
            anInit = " = " + aTr.DefaultValue(f.Type);
        }
        else if (myDb.IsClassByValue(f.Type) && !f.Type.IsRef)
        {
            anInit = " = new " + aCsType + "()";
        }
        else if (aCsType == "string" && f.Type.Name is "TCollection_AsciiString")
        {
            anInit = " = \"\"";
        }

        _ = r;
        return $"{anAccess} {aStatic}{aCsType} {Db.Id(f.Name)}{anInit};";
    }

    private bool HasVirtualInAncestors(CppClass cls, string theKey, out bool theNonVirtualHidden)
    {
        theNonVirtualHidden = false;
        foreach (var a in myDb.Ancestors(cls.Name, false))
        {
            foreach (var m in a.Methods)
            {
                if (!m.IsCtor && m.SignatureKey(myDb.Map) == theKey)
                {
                    if (m.IsVirtual || m.IsOverride || m.IsPure)
                    {
                        return true;
                    }

                    theNonVirtualHidden = true;
                }
            }
        }

        return false;
    }

    private string MethodText(CppClass cls, CppMethod d, CppMethod? def, List<CppMethod> theHelpers, List<CppField> theConsts, ClassResult r,
                              bool theIsRwTool, bool theIsHelper = false, string? theTwinName = null, bool theIsStaticCtor = false)
    {
        var sb = new StringBuilder();
        string I1 = "    ";
        var ctx = new FnCtx { Cls = cls, Method = d, Helpers = theHelpers, FileConstants = theConsts };
        foreach (string tp in d.TemplateParams)
        {
            ctx.TemplateParams.Add(tp);
        }

        // parameter names: the definition's, else the declaration's
        var aNames = new List<string>();
        for (int k = 0; k < d.Params.Count; k++)
        {
            string? n = def != null && k < def.Params.Count ? def.Params[k].Name : null;
            n ??= d.Params[k].Name;
            n ??= "theArg" + (k + 1);
            aNames.Add(n);
            var aType = d.Params[k].Type.Bare();
            if (d.Params[k].IsArray)
            {
                aType = new CppType { Name = "std::array", Args = [aType] };
            }

            ctx.Locals[n] = aType;
        }

        var aTr = new Translator(myDb, ctx, 2);

        // modifiers
        string anAccess = theIsHelper ? "private" : cls.IsNamespace ? "public" : theTwinName != null ? "internal" : d.Access;
        var aMods = new List<string> { anAccess };
        if (theIsStaticCtor)
        {
            aMods = ["static"];
        }
        else if (theTwinName != null)
        {
        }
        else if (d.IsStatic || theIsHelper || cls.IsNamespace)
        {
            aMods.Add("static");
        }
        else if (!d.IsCtor)
        {
            string aKey = d.SignatureKey(myDb.Map);
            bool anOverridesVirtual = HasVirtualInAncestors(cls, aKey, out bool aHides);
            if (d.IsPure)
            {
                aMods.Add(anOverridesVirtual ? "abstract override" : "abstract");
            }
            else if (d.IsOverride || (d.IsVirtual && anOverridesVirtual) || anOverridesVirtual)
            {
                aMods.Add("override");
            }
            else if (d.IsVirtual)
            {
                aMods.Add(aHides ? "new virtual" : "virtual");
            }
            else if (aHides)
            {
                aMods.Add("new");
            }
        }

        // signature
        var aParams = new List<string>();
        (int Index, string Modifier)? aBaseMod = null;
        if (!d.IsCtor && !d.IsStatic && !theIsHelper && Db.BaseModifiers.TryGetValue((d.Name, d.Params.Count), out var aBm)
            && myDb.Ancestors(cls.Name, false).Any(a => !myDb.Generated.Contains(a.Name)))
        {
            aBaseMod = aBm;
        }

        for (int k = 0; k < d.Params.Count; k++)
        {
            var p = d.Params[k];
            string aType = p.Type.Name == "std::array" && p.Type.IsConst && p.Type.IsRef ? "ReadOnlySpan<" + myDb.Map(p.Type.Args[0]) + ">" : myDb.Map(p.Type);
            if (p.IsArray)
            {
                aType += "[]";
            }

            string s = (aBaseMod?.Index == k ? aBaseMod.Value.Modifier : myDb.ParamModifier(p.Type)) + aType + " " + Db.Id(aNames[k]);
            if (p.Default != null)
            {
                var e = new ExprParser(p.Default, 0, p.Default.Count, aTr.IsTypeName).ParseFull();
                string v = aTr.Emit(e, true);
                if (e is TypeCallExpr or InitListExpr || v.StartsWith("new ", StringComparison.Ordinal))
                {
                    r.Problems.Add($"default argument that isn't a constant: {d.Name}({aNames[k]} = {v})");
                    v = "default";
                }

                s += " = " + v;
            }

            aParams.Add(s);
        }

        if (theTwinName != null)
        {
            Doc(sb, ["The non-virtual " + d.Name + " of " + cls.Name + " (C++ calls it as " + cls.Name + "::" + d.Name + "; decision 1211)."], I1);
        }
        else if (!theIsStaticCtor)
        {
            Doc(sb, d.Doc, I1);
        }

        string aRet = d.IsCtor ? "" : MapReturn(d.Return!) + " ";
        string aName = d.IsCtor ? cls.Name : theTwinName ?? Db.Id(d.Name);
        string aGeneric = d.TemplateParams.Count > 0 ? "<" + string.Join(", ", d.TemplateParams) + ">" : "";
        sb.Append(I1).Append(string.Join(" ", aMods)).Append(' ').Append(aRet).Append(aName).Append(aGeneric)
          .Append('(').Append(string.Join(", ", aParams)).Append(')');

        // constructor initialisers
        var aInitStatements = new List<string>();
        if (d.IsCtor && def?.InitList is { Count: > 0 } aList)
        {
            int i = 0;
            while (i < aList.Count)
            {
                if (aList[i].Is(","))
                {
                    i++;
                    continue;
                }

                int j = i;
                var aWho = Parser.ParseType(aList, ref j);
                if (aWho == null || j >= aList.Count || !(aList[j].Is("(") || aList[j].Is("{")))
                {
                    r.Problems.Add("cannot read the initialiser list of " + d.Name);
                    break;
                }

                int anEnd = Parser.Match(aList, j);
                var anArgs = new List<Expr>();
                if (anEnd > j + 1)
                {
                    var e = new ExprParser(aList, j + 1, anEnd, aTr.IsTypeName).ParseComma();
                    anArgs = Flatten(e);
                }

                if (myDb.DerivesFrom(cls.Name, aWho.Name) && aWho.Name != cls.Name)
                {
                    sb.Append(" : base(").Append(string.Join(", ", anArgs.Select(a => aTr.Emit(a, true)))).Append(')');
                }
                else
                {
                    var f = cls.Fields.FirstOrDefault(x => x.Name == aWho.Name);
                    if (f == null)
                    {
                        r.Problems.Add($"initialiser of an unknown member {aWho.Name}");
                    }
                    else
                    {
                        string v = anArgs.Count == 1 ? aTr.InitFrom(f.Type.Bare(), anArgs[0])
                                   : anArgs.Count == 0 ? aTr.DefaultValue(f.Type.Bare())
                                   : "new " + myDb.Map(f.Type.Bare()) + "(" + string.Join(", ", anArgs.Select(a => aTr.Emit(a, true))) + ")";
                        aInitStatements.Add(Db.Id(f.Name) + " = " + v + ";");
                    }
                }

                i = anEnd + 1;
            }
        }

        if (d.TemplateParams.Count > 0)
        {
            // a template over handled types: constrain to Standard_Transient
            foreach (string tp in d.TemplateParams)
            {
                sb.Append(" where ").Append(tp).Append(" : Standard_Transient");
            }
        }

        if (d.IsPure)
        {
            sb.Append(";\n");
            return sb.ToString();
        }

        sb.Append('\n').Append(I1).Append("{\n");
        foreach (string s in aInitStatements)
        {
            sb.Append(I1).Append(I1).Append(s).Append('\n');
        }

        if (aBaseMod is { Modifier: "out " } anOut && def?.Body != null)
        {
            // C# requires an out parameter assigned on every path; C++ leaves the handle as it was (null)
            sb.Append(I1).Append(I1).Append(Db.Id(aNames[anOut.Index])).Append(" = null;\n");
        }

        if (def?.Body is { } aBody)
        {
            aTr.Block(aBody, 0, aBody.Count);
            var aRenames = aTr.ShadowRenames(aNames);
            if (aRenames.Count > 0)
            {
                // C++ shadows an enclosing local: a second pass with the inner ones renamed
                var ctx2 = new FnCtx { Cls = cls, Method = d, Helpers = theHelpers, FileConstants = theConsts };
                foreach (string tp in d.TemplateParams)
                {
                    ctx2.TemplateParams.Add(tp);
                }

                foreach (var kv in ctx.Locals.Where(x => aNames.Contains(x.Key)))
                {
                    ctx2.Locals[kv.Key] = kv.Value;
                }

                ctx.Problems.Clear();
                ctx = ctx2;
                aTr = new Translator(myDb, ctx2, 2) { PlannedRenames = aRenames };
                aTr.Block(aBody, 0, aBody.Count);
                r.Notes.Add($"{d.Name}: renamed shadowing locals " + string.Join(", ", aRenames.Select(x => x.Key.Item2 + "->" + x.Value)));
            }

            if (aTr.Declared.Any(n => aTr.Uses.GetValueOrDefault(n) == 0))
            {
                r.UnusedLocals = true;
            }

            var aLines = aTr.Lines;
            // trim leading/trailing blank lines
            while (aLines.Count > 0 && aLines[0].Trim().Length == 0)
            {
                aLines.RemoveAt(0);
            }

            while (aLines.Count > 0 && aLines[^1].Trim().Length == 0)
            {
                aLines.RemoveAt(aLines.Count - 1);
            }

            foreach (string l in aLines)
            {
                sb.Append(l).Append('\n');
            }
        }

        sb.Append(I1).Append("}\n");
        foreach (string p in ctx.Problems)
        {
            r.Problems.Add($"{d.Name}: {p}");
        }

        return sb.ToString();
    }

    private static List<Expr> Flatten(Expr e)
    {
        var l = new List<Expr>();
        while (e is BinaryExpr { Op: "," } b)
        {
            l.Insert(0, b.R);
            e = b.L;
        }

        l.Insert(0, e);
        return l;
    }

    private string MapReturn(CppType t)
    {
        if (t.Name == "std::array" && t.IsConst && t.IsRef)
        {
            // a const reference to an array member: read-only (decision 1210)
            return "ReadOnlySpan<" + myDb.Map(t.Args[0]) + ">";
        }

        if (t.IsRef && !t.IsConst && myDb.IsRefKind(t.Bare()))
        {
            return "ref " + myDb.Map(t);
        }

        return myDb.Map(t);
    }
