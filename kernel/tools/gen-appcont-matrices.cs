// Generates src/OcctNet.ModelingData/AppCont/AppCont_ContMatrices_{BB,InvM,IBP,IBT,VB}.cs from OCCT's
// AppCont_ContMatrices_*.pxx: the constant tables of AppCont's Bernstein least squares (decision 77). Every literal
// is copied as written, except that C's "1." and "1.e5" become "1.0" and "1.0e5", which C# requires.
//
//   dotnet run tools/gen-appcont-matrices.cs [OCCT source root, default .deps/occt-src]

using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

string aRoot = FindRoot(Directory.GetCurrentDirectory())
               ?? throw new InvalidOperationException("Run from inside the OCCT.NET repository.");
string anOcctSrc = args.Length > 0 ? args[0] : Path.Combine(aRoot, ".deps", "occt-src");
string aSrcDir = Path.Combine(anOcctSrc, "src", "ModelingData", "TKGeomBase", "AppCont");
string anOutDir = Path.Combine(aRoot, "src", "OcctNet.ModelingData", "AppCont");
if (!Directory.Exists(aSrcDir))
{
    Console.Error.WriteLine($"No OCCT source at {aSrcDir}: run tools/get-occt.ps1");
    return 1;
}
Directory.CreateDirectory(anOutDir);

// (file suffix, C++ array name, expected size, what it holds)
var aTables = new (string File, string Name, int Size, string Summary)[]
{
    // classe 2..26, classe * classe values each: sum of i^2 for i = 2..26
    ("BB", "THE_BBMATRIX_DATA", 6200, "The Bernstein mass matrices M for classe 2 to 26, classe × classe each, row by row."),
    ("InvM", "THE_INV_MMATRIX_DATA", 6200, "The inverses of the Bernstein mass matrices for classe 2 to 26, classe × classe each, row by row."),
    // classe 3..26, (classe - 2)^2 values each
    ("IBP", "THE_IBPMATRIX_DATA", 4900, "The inverses of MPᵀ·MP (pass-point constraints) for classe 3 to 26, (classe - 2)² values each."),
    // classe 5..26, (classe - 4)^2 values each
    ("IBT", "THE_IBTMATRIX_DATA", 3795, "The inverses of MTᵀ·MT (tangency constraints) for classe 5 to 26, (classe - 4)² values each."),
    // classe 2..26 and nbpoints 2..24: the offset formula of VBernstein for classe 26 and 24 points, plus 26 * 24
    ("VB", "THE_VBMATRIX_DATA", 105000, "The Bernstein polynomials at the Gauss points for classe 2 to 26 and 2 to 24 points (offsets: VBernstein)."),
};

foreach (var aTable in aTables)
{
    string aText = File.ReadAllText(Path.Combine(aSrcDir, $"AppCont_ContMatrices_{aTable.File}.pxx"));
    Match anArray = Regex.Match(aText, @"static const double (\w+)\[\] = \{(.*?)\};", RegexOptions.Singleline);
    if (!anArray.Success || anArray.Groups[1].Value != aTable.Name)
    {
        throw new InvalidOperationException($"{aTable.File}: table {aTable.Name} not found");
    }
    List<string> aValues = Literals(anArray.Groups[2].Value);
    if (aValues.Count != aTable.Size)
    {
        throw new InvalidOperationException($"{aTable.File}: {aValues.Count} literals, expected {aTable.Size}");
    }

    var anOut = new StringBuilder();
    anOut.Append($$"""
        // Port of: src/ModelingData/TKGeomBase/AppCont/AppCont_ContMatrices_{{aTable.File}}.pxx
        // Open CASCADE Technology V8_0_1 (b8f597c6). Copyright (c) 1991-1999 Matra Datavision; 1999-2026 OPEN CASCADE SAS.
        // Copyright (c) 2026 The OCCT.NET Contributors. LGPL 2.1 with the Open CASCADE exception (see LICENSE).

        // Generated by tools/gen-appcont-matrices.cs from OCCT's AppCont_ContMatrices_{{aTable.File}}.pxx, with every literal
        // copied as written (decision 77). Properties returning a ReadOnlySpan over a constant array are stored in the
        // assembly's data section: reading them allocates nothing. Don't edit: regenerate.

        namespace Occt;

        internal static partial class AppCont_ContMatrices
        {
            /// <summary>{{aTable.Summary}} {{aTable.Size}} values.</summary>
            internal static ReadOnlySpan<double> {{aTable.Name}} => [

        """);
    for (int i = 0; i < aValues.Count; i += 4)
    {
        anOut.Append("        ");
        anOut.AppendJoin(", ", aValues.Skip(i).Take(4));
        anOut.Append(",\n");
    }
    anOut.Append("    ];\n}\n");
    string aName = $"AppCont_ContMatrices_{aTable.File}.cs";
    File.WriteAllText(Path.Combine(anOutDir, aName), anOut.ToString().Replace("\r\n", "\n"));
    Console.WriteLine($"Wrote {aName} ({aValues.Count.ToString(CultureInfo.InvariantCulture)} values)");
}
return 0;

// The comma-separated literals of a C initialiser list, in C# syntax.
static List<string> Literals(string theList)
{
    var aResult = new List<string>();
    foreach (string aRaw in theList.Split(','))
    {
        string aLiteral = Regex.Replace(aRaw.Trim(), @"\s+", " ");
        if (aLiteral.Length == 0)
        {
            continue;
        }
        // One literal, or (once, in the IBP table) a constant expression "a - b", which C++ and C# both fold at
        // compile time with the same IEEE rounding.
        const string aNumber = @"\d+\.?\d*(?:[eE][-+]?\d+)?";
        if (!Regex.IsMatch(aLiteral, $@"^[-+]?{aNumber}(?: [-+] {aNumber})*$"))
        {
            throw new InvalidOperationException($"Unexpected literal '{aLiteral}'");
        }
        // "1." -> "1.0", "1.e5" -> "1.0e5"; C# needs a digit after the point.
        aLiteral = Regex.Replace(aLiteral, @"(\d)\.(?=$|[eE ])", "$1.0");
        aResult.Add(aLiteral);
    }
    return aResult;
}

static string? FindRoot(string theStart)
{
    for (var aDir = new DirectoryInfo(theStart); aDir != null; aDir = aDir.Parent)
    {
        if (File.Exists(Path.Combine(aDir.FullName, "occt-version.json")))
        {
            return aDir.FullName;
        }
    }
    return null;
}
