# Writes src/OcctNet.Foundation/Standard/OcctTypeNames.g.cs from docs/api/kerf.map (unit 10E): for every type the map
# renames, its new full name and its OCCT name, so the names OCCT prints and looks up (DynamicType()->Name(): message
# keys, STEP's type signatures, exceptions' types) stay OCCT's.
#
#   python tools/occt-type-names.py        (from kernel/)

import re

types = []
for line in open('docs/api/kerf.map', encoding='utf-8'):
    m = re.match(r'^type T:(\S+) (\S+)', line)
    if m:
        old, new = m.groups()
        arity = '`' + old.split('`')[1] if '`' in old else ''
        occt = old.split('`')[0].rsplit('.', 1)[1] + arity
        if new.rsplit('.', 1)[1] + arity != occt or not old.startswith('T:Occt.'):
            types.append((new + arity, occt))

types.sort()
body = '\n'.join(f'{new} {occt}' for new, occt in types)
out = f'''// <auto-generated>
// Generated by tools/occt-type-names.py from docs/api/kerf.map: each renamed type's full name and its OCCT name.
// </auto-generated>

namespace Kerf.Engine.Foundation;

public static partial class OcctTypeNames
{{
    private const string Table = """
{body}
""";
}}
'''
open('src/OcctNet.Foundation/Standard/OcctTypeNames.g.cs', 'w', encoding='utf-8', newline='\n').write(out)
print(len(types), 'types')
