# Writes src/Kerf.Kernel.Foundation/Standard/OcctTypeNames.g.cs from docs/api/kerf.map (unit 10E): for every type and enum
# member the map renames, its new full name and its OCCT name, so the names OCCT prints and looks up
# (DynamicType()->Name(): message keys, STEP's type signatures, exceptions' types) and the enum values the kernel's
# tests compare with native OCCT's recordings stay OCCT's.
#
#   python tools/occt-type-names.py        (from kernel/)

import re

lines = open('docs/api/kerf.map', encoding='utf-8').read().split('\n')
types = []
new_type = {}
for line in lines:
    m = re.match(r'^type T:(\S+) (\S+)', line)
    if m:
        old, new = m.groups()
        new_type[old] = new
        arity = '`' + old.split('`')[1] if '`' in old else ''
        occt = old.split('`')[0].rsplit('.', 1)[1] + arity
        if new.rsplit('.', 1)[1] + arity != occt or not old.startswith('Occt.'):
            types.append((new + arity, occt))

# Fields the map renames (enum members among them), under their type's new full name
members = []
for line in lines:
    m = re.match(r'^member F:(\S+)\.(\w+) (\w+)', line)
    if m and m.group(2) != m.group(3):
        owner = new_type.get(m.group(1), m.group(1))
        members.append((owner + '.' + m.group(3), m.group(2)))

types.sort()
members.sort()
body = '\n'.join(f'{new} {occt}' for new, occt in types)
member_body = '\n'.join(f'{new} {occt}' for new, occt in members)
out = f'''// <auto-generated>
// Generated by tools/occt-type-names.py from docs/api/kerf.map: each renamed type's and enum member's full name and its
// OCCT name.
// </auto-generated>

namespace Kerf.Engine.Foundation;

public static partial class OcctTypeNames
{{
    private const string Table = """
{body}
""";

    private const string MemberTable = """
{member_body}
""";
}}
'''
open('src/Kerf.Kernel.Foundation/Standard/OcctTypeNames.g.cs', 'w', encoding='utf-8', newline='\n').write(out)
print(len(types), 'types,', len(members), 'members')
