/// <summary>
/// Unit 5S1's BRepFill_Pipe and BRepOffsetAPI_MakePipe (decisions 909-911). The topological sweep (BRepFill_Sweep)
/// is unit 5S2's (decision 924). These tests check pipes of every kind of profile against their measures, what Perform
/// does before it sweeps (the location law, the placement of the profile, the first and last shapes, the solid check),
/// and that frozen inputs are never written.
/// </summary>
public class BRepFill_PipeTests
{
    private static Wire Polyline(params Point3D[] thePoints)
    {
        MakePolygon aP = new();
        foreach (Point3D aQ in thePoints)
        {
            aP.Add(aQ);
        }
        return aP.Wire();
    }

    private static Wire Circle(double theRadius)
    {
        Edge anEdge = new MakeEdge(new Circle3D(new Frame3D(), theRadius)).Edge();
        return new MakeWire(anEdge).Wire();
    }

    private static string Text(in Shape theShape)
    {
        using StringWriter aW = new();
        BrepTools.Write(theShape, aW);
        return aW.ToString();
    }

    private static List<Point3D> Points(in Shape theShape)
    {
        List<Point3D> aPoints = [];
        for (Explorer anExp = new(theShape, ShapeType.Vertex); anExp.More(); anExp.Next())
        {
            aPoints.Add(Tool.Pnt(ShapeCasts.Vertex(anExp.Current())));
        }
        return aPoints;
    }

    /// <summary>
    /// The edge generated by a spine edge and a vertex profile: BRepFill_Pipe::Edge read the profile's edges, which a
    /// vertex profile has none of (an access violation natively, a NullReferenceException in the port; occt-issues.md,
    /// unit 5S1's BRepFill_Pipe row; Kerf unit 10K1, decision 1435). A vertex at the spine's start sweeps the spine
    /// itself, so each generated edge joins the ends of its spine edge.
    /// </summary>
    [Fact]
    public void MakePipe_of_a_vertex_generates_an_edge_per_spine_edge()
    {
        Point3D[] aCorners = [new(0, 0, 0), new(0, 0, 10), new(0, 10, 10)];
        Wire aSpine = Polyline(aCorners);
        Vertex aProfile = new MakeVertex(aCorners[0]).Vertex();
        ApiMakePipe aPipe = new(aSpine, aProfile);
        Assert.True(aPipe.IsDone);
        Shape aResult = aPipe.Shape();

        int i = 0;
        for (WireExplorer anExp = new(aSpine); anExp.More(); anExp.Next(), i++)
        {
            Shape aGenerated = aPipe.Generated(anExp.Current(), aProfile);
            Assert.Equal(ShapeType.Edge, aGenerated.ShapeType());
            Assert.True(aGenerated.TShape()!.IsFrozen);
            bool isInResult = false;
            for (Explorer anInResult = new(aResult, ShapeType.Edge); anInResult.More(); anInResult.Next())
            {
                isInResult |= anInResult.Current().IsSame(aGenerated);
            }
            Assert.True(isInResult);
            List<Point3D> anEnds = Points(aGenerated);
            Assert.Contains(anEnds, p => p.Distance(aCorners[i]) < 1e-6);
            Assert.Contains(anEnds, p => p.Distance(aCorners[i + 1]) < 1e-6);
        }
        Assert.Equal(2, i);
    }

    [Fact]
    public void MakePipe_sweeps_every_kind_of_profile_and_leaves_its_inputs_unchanged()
    {
        Wire aSpine = Polyline(new Point3D(0, 0, 0), new Point3D(0, 0, 10));
        (Shape Profile, ShapeType Type, double Measure)[] aCases =
        [
            (Circle(1), ShapeType.Shell, 2 * Math.PI * 10),                                    // lateral area
            (new MakeFace(Circle(2)).Face(), ShapeType.Solid, Math.PI * 4 * 10), // volume
            (new MakeVertex(new Point3D(1, 0, 0)).Vertex(), ShapeType.Edge, 10),  // length
            (Polyline(new Point3D(1, 0, 0), new Point3D(2, 0, 0)), ShapeType.Shell, 10),         // area
        ];
        string aSpineText = Text(aSpine);
        foreach ((Shape aProfile, ShapeType aType, double aMeasure) in aCases)
        {
            Assert.True(aProfile.TShape()!.IsFrozen);
            string aText = Text(aProfile);
            foreach (Trihedron aMode in new[] { Trihedron.IsCorrectedFrenet, Trihedron.IsFrenet, Trihedron.IsDiscreteTrihedron })
            {
                ApiMakePipe aPipe = new(aSpine, aProfile, aMode);
                Assert.True(aPipe.IsDone);
                Shape aResult = aPipe.Shape();
                Assert.True(aResult.TShape()!.IsFrozen);
                Shape aBody = aResult;
                if (aType != ShapeType.Edge)
                {
                    Explorer anExp = new(aResult, aType);
                    Assert.True(anExp.More());
                    aBody = anExp.Current();
                }
                Properties aProps = new();
                switch (aType)
                {
                    case ShapeType.Solid:
                        MassPropertiesBuilder.VolumeProperties(aBody, aProps);
                        break;
                    case ShapeType.Shell:
                        MassPropertiesBuilder.SurfaceProperties(aBody, aProps);
                        break;
                    default:
                        MassPropertiesBuilder.LinearProperties(aBody, aProps);
                        break;
                }
                Assert.Equal(aMeasure, aProps.Mass(), 1e-6 * aMeasure);
                Assert.True(new Analyzer(aResult).IsValid());
                Assert.Equal(aText, Text(aProfile));
            }
            Assert.Equal(aText, Text(aProfile));
        }
        Assert.Equal(aSpineText, Text(aSpine));
    }

    [Fact]
    public void A_solid_profile_is_refused_after_the_first_and_last_shapes_are_placed()
    {
        // Perform places the profile and builds the first and last shapes before MakeShape refuses the solid, as OCCT.
        Shape aBox = new MakeBox(new Point3D(-1, -1, 0), 2, 2, 1).Shape();
        string aBoxText = Text(aBox);
        Wire aSpine = Polyline(new Point3D(0, 0, 0), new Point3D(0, 0, 4), new Point3D(0, 0, 10));

        Pipe aPipe = new();
        var anError = Assert.Throws<DomainErrorException>(() => aPipe.Perform(aSpine, aBox));
        Assert.Contains("profile contains solids", anError.Message, StringComparison.Ordinal);
        Assert.Equal(aBoxText, Text(aBox));

        // Along a straight spine the profile is only translated: the first shape is the box moved along the spine (by
        // the abscissa SectionPlacement found for it), the last one the first moved by the spine's length.
        Shape aFirst = aPipe.FirstShape();
        Shape aLast = aPipe.LastShape();
        Assert.True(aFirst.TShape()!.IsFrozen);
        Assert.Equal(ShapeType.Solid, aFirst.ShapeType());
        Assert.True(aFirst.Location().IsIdentity); // RemoveLocations
        Assert.True(aLast.Location().IsIdentity);
        List<Point3D> aBoxPoints = Points(aBox), aFirstPoints = Points(aFirst), aLastPoints = Points(aLast);
        Assert.Equal(aBoxPoints.Count, aFirstPoints.Count);
        Vector3D aShift = new(aBoxPoints[0], aFirstPoints[0]);
        Assert.True(Math.Abs(aShift.X()) < 1e-9 && Math.Abs(aShift.Y()) < 1e-9);
        for (int i = 0; i < aBoxPoints.Count; i++)
        {
            Assert.True(aBoxPoints[i].Translated(aShift).Distance(aFirstPoints[i]) < 1e-9);
            Assert.True(aFirstPoints[i].Translated(new Vector3D(0, 0, 10)).Distance(aLastPoints[i]) < 1e-9);
        }
        Assert.Equal(aBoxText, Text(aBox));

        // and inside a compound
        BrepBuilder aB = new();
        Compound aCompound = new();
        aB.MakeCompound(ref aCompound);
        aB.Add(aCompound, aBox);
        Assert.Throws<DomainErrorException>(() => new ApiMakePipe(aSpine, aCompound));
        Assert.Equal(aBoxText, Text(aBox));
    }

    [Fact]
    public void Queries_of_an_unbuilt_pipe_throw_as_OCCT_does()
    {
        Shape aBox = new MakeBox(1, 1, 1).Shape();
        Wire aSpine = Polyline(new Point3D(0, 0, 0), new Point3D(0, 0, 3));
        Pipe aPipe = new();
        Assert.Throws<DomainErrorException>(() => aPipe.Perform(aSpine, aBox));
        Assert.True(aPipe.Shape().IsNull);
        Assert.Equal(ShapeType.Wire, aPipe.Spine().ShapeType());

        Edge aSpineEdge = ShapeCasts.Edge(new Explorer(aSpine, ShapeType.Edge).Current());
        Edge aBoxEdge = ShapeCasts.Edge(new Explorer(aBox, ShapeType.Edge).Current());
        // the profile is searched first: a solid profile is refused
        Assert.Throws<DomainErrorException>(() => aPipe.Face(aSpineEdge, aBoxEdge));
        // a vertex not on the spine
        Vertex aV = new MakeVertex(new Point3D(5, 5, 5)).Vertex();
        Assert.Throws<DomainErrorException>(() => aPipe.Section(aV));
        // a spine vertex: OCCT reads the sections the sweep would have made
        Vertex aSpineVertex = Exploration.FirstVertex(aSpineEdge);
        Assert.ThrowsAny<Exception>(() => aPipe.Section(aSpineVertex));
        // PipeLine sweeps a point along the spine (the location law was made before the profile was refused)
        Wire aLine = aPipe.PipeLine(new Point3D(0, 0, 0));
        Assert.Equal(ShapeType.Wire, aLine.ShapeType());
        Assert.True(aLine.TShape()!.IsFrozen);

        NCollection_List<Shape> aList = new();
        aList.Append(aBox);
        aPipe.Generated(aBox, aList);
        Assert.True(aList.IsEmpty());
    }
}
