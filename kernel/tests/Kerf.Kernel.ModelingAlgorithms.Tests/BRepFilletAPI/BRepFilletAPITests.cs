    [Fact]
    public void TheEvolvingRadii()
    {
        Shape aBox = Box();
        Edge E = EdgeOf(aBox, 1);

        MakeFillet aLinear = new(aBox);
        aLinear.Add(1.0, 3.0, E);
        aLinear.Build();
        Assert.True(aLinear.IsDone);
        Assert.False(aLinear.IsConstant(1));

        // with sections nearly circles of radius r(s) in the planes normal to the edge, the fillet removes about
        // (1 - pi/4) * integral of r(s)^2 over the edge: (1 - pi/4) * (3^3 - 1^3) / (3 * 0.2) for r = 1 + 0.2 s
        double aRemoved = (1.0 - Math.PI / 4.0) * (27.0 - 1.0) / 0.6;
        Assert.Equal(1000.0 - aRemoved, ReconComparison.Volume(aLinear.Shape()), 0.5);

        // Unit 15AK: the fillet is the envelope of the balls, which for a radius growing evenly along the edge of two
        // planes is a cone; what it removes is integrated below apart from how it's built (9.17917, where the circles in
        // the planes normal to the edge remove 9.29941)
        aRemoved = ConeRemoved(1.0, 0.2, 10.0);
        Assert.Equal(9.17917, aRemoved, 1.0e-4);

        // SetRadius by a law: OCCT's ChFiDS_FilSpine::SetRadius(Law_Function, IinC) built a composite law, dropped it
        // and cleared the radii, so Build threw on the empty radii (occt-issues, unit 7N3); the law now gives the
        // radius (Kerf unit 10K1, decision 1433)
        MakeFillet aLaw = new(aBox);
        aLaw.Add(E);
        Linear L = new();
        L.Set(0.0, 1.0, aLaw.Length(1), 3.0);
        aLaw.SetRadius(L, 1, 1);
        Assert.False(aLaw.IsConstant(1));
        aLaw.Build();
        Assert.True(aLaw.IsDone);
        Assert.True(new Analyzer(aLaw.Shape()).IsValid());
        Assert.Equal(1000.0 - aRemoved, ReconComparison.Volume(aLaw.Shape()), 1.0e-3);

        // Add(law, edge), the law's range mapped onto the edge's: r = 2 + sin(pi s / 10), from 2 to 3 and back; the
        // removed volume against the integral of r^2, (1 - pi/4) * 10 * (4 + 8/pi + 1/2)
        MakeFillet aSine = new(aBox);
        Interpol aSineLaw = new();
        NCollection_Array1<Point2D> aSamples = new(1, 41);
        for (int i = 0; i <= 40; i++)
        {
            double t = i / 40.0;
            aSamples.SetValue(i + 1, new Point2D(t, 2.0 + Math.Sin(Math.PI * t)));
        }
        aSineLaw.Set(aSamples);
        aSine.Add(aSineLaw, E);
        aSine.Build();
        Assert.True(aSine.IsDone);
        Assert.True(new Analyzer(aSine.Shape()).IsValid());
        Assert.Equal(1000.0 - (1.0 - Math.PI / 4.0) * 10.0 * (4.0 + 8.0 / Math.PI + 0.5), ReconComparison.Volume(aSine.Shape()), 0.5);

        // the radius interpolating (parameter, radius) pairs
        NCollection_Array1<Point2D> UandR = new(1, 3);
        UandR.SetValue(1, new Point2D(0.0, 1.0));
        UandR.SetValue(2, new Point2D(0.5, 2.0));
        UandR.SetValue(3, new Point2D(1.0, 1.0));
        MakeFillet aPairs = new(aBox);
        aPairs.Add(UandR, E);
        aPairs.Build();
        Assert.True(aPairs.IsDone);
        Assert.True(new Analyzer(aPairs.Shape()).IsValid());
    }

    // The volume a ball of radius r0 + k w removes rolling along the edge of two planes at a right angle (x = 0 and y = 0;
    // the ball touches them at z = w, its centre at (r, r, w)) between z = 0 and z = length: a point of the corner is removed
    // if it's outside every ball, on the edge's side. Gauss in z and in the angle about the edge; along each ray from the
    // edge, the first point inside some ball (the least over w of |p - c(w)|^2 - r(w)^2 is a quadratic's).
    private static double ConeRemoved(double r0, double k, double length)
    {
        bool Inside(double x, double y, double z)
        {
            double a = k * k + 1.0;
            double b = -2 * k * (x - r0) - 2 * k * (y - r0) - 2 * z - 2 * k * r0;
            double c = (x - r0) * (x - r0) + (y - r0) * (y - r0) + z * z - r0 * r0;
            double w = -b / (2 * a);
            return a * w * w + b * w + c <= 0.0;
        }

        const int N = 96;
        double[] nodes = new double[N], weights = new double[N];
        for (int i = 0; i < N; i++)
        {
            double x = Math.Cos(Math.PI * (i + 0.75) / (N + 0.5)), dp = 0;
            for (int iter = 0; iter < 100; iter++)
            {
                double p0 = 1.0, p1 = x;
                for (int j = 2; j <= N; j++)
                {
                    (p0, p1) = (p1, ((2 * j - 1) * x * p1 - (j - 1) * p0) / j);
                }

                dp = N * (x * p1 - p0) / (x * x - 1);
                double dx = p1 / dp;
                x -= dx;
                if (Math.Abs(dx) < 1e-15)
                {
                    break;
                }
            }

            nodes[i] = (x + 1) / 2;
            weights[i] = 1.0 / ((1 - x * x) * dp * dp);
        }

        double far = 4 * (r0 + Math.Abs(k) * length + 1), total = 0;
        for (int iz = 0; iz < N; iz++)
        {
            double z = nodes[iz] * length, area = 0;
            for (int it = 0; it < N; it++)
            {
                double angle = nodes[it] * Math.PI / 2, cx = Math.Cos(angle), cy = Math.Sin(angle);
                double lo = 0, hi = 0;
                for (double t = far / 4000; t <= far; t += far / 4000)
                {
                    if (Inside(t * cx, t * cy, z))
                    {
                        hi = t;
                        break;
                    }

                    lo = t;
                }

                Assert.True(hi > 0);
                for (int iter = 0; iter < 60; iter++)
                {
                    double mid = (lo + hi) / 2;
                    if (Inside(mid * cx, mid * cy, z))
                    {
                        hi = mid;
                    }
                    else
                    {
                        lo = mid;
                    }
                }

                area += weights[it] * 0.5 * lo * lo;
            }

            total += weights[iz] * area * Math.PI / 2;
        }

        return total * length;
    }

    [Fact]
    public void ARadiusTooLargeGivesTheDiagnostics()
    {
        Shape aBox = Box(1.0);
        MakeFillet aFillet = new(aBox);
        aFillet.Add(5.0, EdgeOf(aBox, 1));
        aFillet.Build();
        Assert.False(aFillet.IsDone);
        Assert.Equal(1, aFillet.FaultyContourCount);
        Assert.Equal(1, aFillet.FaultyContour(1));
        Assert.NotEqual(ErrorStatus.Ok, aFillet.StripeStatus(1));
        Assert.False(aFillet.HasResult);
        EngineAssert.Throws<NotDoneException>(() => aFillet.Shape());
    }

    [Fact]
    public void AChamferKeepsTheCallersShapeAndGivesItsHistory()
    {
        Shape aBox = Box();
        string aText = Text(aBox);
        Edge E = EdgeOf(aBox, 1);
        IndexedMap<Shape, NCollection_List<Shape>> M = new(ShapeHasher.Instance);
        Exploration.MapShapesAndAncestors(aBox, ShapeType.Edge, ShapeType.Face, M);
        Face F = ShapeCasts.Face(M.GetValue(E).First());

        MakeChamfer aChamfer = new(aBox);
        aChamfer.Add(1.0, 2.0, E, F);
        Assert.True(aChamfer.IsTwoDistances(1));
        double d1 = 0, d2 = 0;
        aChamfer.Dists(1, ref d1, ref d2);
        Assert.Equal((1.0, 2.0), (d1, d2));
        Shape aResult = aChamfer.Shape();
        Assert.True(new Analyzer(aResult).IsValid());
        Assert.Equal(1000.0 - 1.0 * 2.0 / 2.0 * 10.0, ReconComparison.Volume(aResult), 1.0e-6);
        Assert.Equal(aText, Text(aBox));
        Assert.Single(aChamfer.Generated(E));
        Assert.Single(aChamfer.Modified(F));
        Assert.False(aChamfer.IsDeleted(F));
    }

    [Fact]
    public void FilletSurfGivesTheFilletsGeometryWithoutAShape()
    {
        Shape aBox = Box();
        Edge E = EdgeOf(aBox, 1);
        NCollection_List<Shape> L = new();
        L.Append(E);
        SurfaceBuilder aB = new(aBox, L, 2.0);
        Assert.Equal(StatusDone.IsOk, aB.IsDone);
        aB.Perform();
        Assert.Equal(StatusDone.IsOk, aB.IsDone);
        Assert.Equal(1, aB.NbSurface());
        Assert.True(aB.SurfaceFillet(1).IsFrozen);
        Assert.Equal(SurfaceStatusType.TwoExtremityOnEdge, aB.StartSectionStatus());
        Assert.Equal(SurfaceStatusType.TwoExtremityOnEdge, aB.EndSectionStatus());

        // the support faces are the caller's, those of the edge
        IndexedMap<Shape, NCollection_List<Shape>> M = new(ShapeHasher.Instance);
        Exploration.MapShapesAndAncestors(aBox, ShapeType.Edge, ShapeType.Face, M);
        NCollection_List<Shape> aFaces = M.GetValue(E);
        Assert.Contains(aFaces, f => f.IsSame(aB.SupportFace1(1)));
        Assert.Contains(aFaces, f => f.IsSame(aB.SupportFace2(1)));

        // the curves on the faces lie on them, 2 from the edge; the parameters span the edge
        EdgeCurveAdaptor anEdge = new(E);
        foreach (Curve3D C in new[] { aB.CurveOnFace1(1), aB.CurveOnFace2(1) })
        {
            Point3D P = C.Value(0.5 * (C.FirstParameter + C.LastParameter));
            CurvePointExtrema anExt = new(P, anEdge);
            Assert.True(anExt.IsDone && anExt.ExtCount > 0);
            Assert.Equal(2.0, Math.Sqrt(anExt.SquareDistance(1)), 1.0e-4);
        }
        Assert.Equal(anEdge.FirstParameter(), Math.Min(aB.FirstParameter(), aB.LastParameter()), 1.0e-6);
        Assert.Equal(anEdge.LastParameter(), Math.Max(aB.FirstParameter(), aB.LastParameter()), 1.0e-6);
        Assert.Equal(Text(Box()), Text(aBox));

        // simulated: sections, arcs of radius 2
        SurfaceBuilder aS = new(aBox, L, 2.0);
        aS.Simulate();
        Assert.Equal(StatusDone.IsOk, aS.IsDone);
        Assert.True(aS.NbSection(1) > 1);
        TrimmedCurve3D aArc = aS.Section(1, 1);
        Assert.Equal(2.0, ((CircleCurve3D)aArc.BasisCurve!).Radius, 1.0e-9);
    }

