using Kerf.Kernel.DrawLite;
using Xunit.Abstractions;

namespace Kerf.Kernel.DrawLite.Tests;

/// <summary>
/// Unit 7N3's fillet and chamfer commands (BRepTest_FilletCommands.cxx, BRepTest_ChamferCommands.cxx, and the feature
/// commands <c>fillet</c> and <c>bossage</c>, over BRepFilletAPI_MakeFillet and MakeChamfer): on hand-made shapes and
/// on OCCT's corpus: the cases that use them, runnable after the commands and not before, run as OCCT's harness runs
/// them and judged by OCCT's log check.
/// </summary>
public class DrawFilletCorpusTests(ITestOutputHelper output)
{
    private static string TestsDirectory => Path.Combine(DrawResourcesTests.OcctSourceDirectory, "tests");

    /// <summary>The Draw commands unit 7N3 added.</summary>
    internal static readonly string[] Unit7N3Commands =
    [
        "continuityblend", "tolblend", "blend", "checkhist", "mkevol", "updatevol", "buildevol", "bfuseblend",
        "bcutblend", "chamf", "chamf_throat", "chamf_throat_with_penetration", "fillet", "bossage",
    ];

    /// <summary>Draw-lite before unit 7N3: without its commands.</summary>
    internal static void Before7N3(DrawInterpreter theInterpreter)
    {
        foreach (string aCommand in Unit7N3Commands)
        {
            theInterpreter.Eval($"rename {aCommand} {{}}");
        }
    }

    private static DrawInterpreter NewInterpreter()
    {
        var anInterpreter = new DrawInterpreter();
        anInterpreter.LoadDrawResources(DrawResourcesTests.ResourcesDirectory);
        return anInterpreter;
    }

    [Fact]
    public void The_commands_fillet_and_chamfer_as_Draw()
    {
        DrawInterpreter aDI = NewInterpreter();
        aDI.Eval("box b 10 10 10");
        aDI.Eval("explode b e");

        // tolblend: printed by blend, set per interpreter
        Assert.Contains("tolblend 0.01 0.0001 1.0000000000000001e-05 0.001", aDI.Eval("tolblend"), StringComparison.Ordinal);
        aDI.Eval("tolblend 0.01 0.001 1e-05 0.001");
        Assert.Contains("tolerance 3d  : 0.001", aDI.Eval("tolblend"), StringComparison.Ordinal);
        Assert.Contains("tolerance 3d  : 0.0001", NewInterpreter().Eval("tolblend"), StringComparison.Ordinal);

        // blend: a box's edge, r = 1: the volume 1000 - (1 - pi/4) * 10
        aDI.Eval("blend r b 1 b_1");
        Assert.Matches(@"Mass :\s+997\.85", aDI.Eval("vprops r"));
        Assert.Equal("", aDI.Eval("checkshape r").Replace("This shape seems to be valid", "", StringComparison.Ordinal).Trim());
        // checkhist: the fillet's faces generated by the contour's vertices and edge
        Assert.Contains("foreach g", aDI.Eval("checkhist"), StringComparison.Ordinal);
        Assert.Equal("generated_000 generated_001 generated_002", aDI.Eval("lsort [directory generated_*]"));

        // mkevol, updatevol, buildevol: a radius from 1 to 2
        aDI.Eval("mkevol re b");
        aDI.Eval("updatevol b_1 0 1 1 2");
        aDI.Eval("buildevol");
        Assert.Matches(@"Mass :\s+99\d\.", aDI.Eval("vprops re"));

        // chamf by one distance, two distances, a distance and an angle
        aDI.Eval("explode b f");
        aDI.Eval("explode b_1 e"); // b_1_1: an edge of the face b_1
        aDI.Eval("chamf c1 b b_1_1 1");
        Assert.Matches(@"Mass :\s+995\b", aDI.Eval("vprops c1"));
        aDI.Eval("chamf c2 b b_1_1 b_1 1 2");
        Assert.Matches(@"Mass :\s+990\b", aDI.Eval("vprops c2"));
        aDI.Eval("chamf c3 b b_1_1 b_1 A 1 45");
        Assert.Matches(@"Mass :\s+995\b", aDI.Eval("vprops c3"));

        // fillet (the feature command): the edges of a compound
        aDI.Eval("compound b_1_1 b_1_2 ce");
        aDI.Eval("fillet rf b 1 ce");
        Assert.Matches(@"Mass :\s+99\d\.", aDI.Eval("vprops rf"));
    }

    [Fact]
    public void Corpus_cases_using_the_fillet_and_chamfer_commands_of_7N3_run()
    {
        Assert.True(Directory.Exists(TestsDirectory), $"No OCCT source at {TestsDirectory}: run tools/get-occt.ps1");
        var aCorpus = new DrawCorpus(TestsDirectory);
        DrawInterpreter anInterpreter = NewInterpreter();
        DrawInterpreter aBefore = NewInterpreter();
        Before7N3(aBefore);

        List<DrawCaseScan> aScans = aCorpus.Cases().AsParallel().AsOrdered()
                                           .Select(c => aCorpus.Scan(c, anInterpreter))
                                           .Where(s => Unit7N3Commands.Any(s.Commands.Contains))
                                           .ToList();
        List<DrawTestCase> aRunnable = aScans.Where(s => s.IsRunnable).Select(s => s.Case).ToList();
        var aRunnableBefore = new HashSet<string>(aScans.Select(s => s.Case).Where(c => aCorpus.Scan(c, aBefore).IsRunnable)
                                                        .Select(c => c.Id), StringComparer.Ordinal);
        List<DrawTestCase> aNew = aRunnable.Where(c => !aRunnableBefore.Contains(c.Id)).ToList();
        output.WriteLine($"{aScans.Count} cases use the commands of 7N3; runnable before 7N3: {aRunnableBefore.Count}, after: {aRunnable.Count}, newly: {aNew.Count}");

        // OCCTNET_7N3_FILTER: only the cases whose id contains it (and their logs with OCCTNET_7N3_LOG)
        string? aFilter = Environment.GetEnvironmentVariable("OCCTNET_7N3_FILTER");
        bool isFiltered = !string.IsNullOrEmpty(aFilter);
        if (isFiltered)
        {
            aNew = aNew.Where(c => c.Id.Contains(aFilter!, StringComparison.Ordinal)).ToList();
        }

        DrawCaseRun RunOne(DrawTestCase theCase)
            => aCorpus.RunAndCheck(theCase, DrawResourcesTests.ResourcesDirectory, DrawCorpusTests.DataPath,
                                   TimeSpan.FromSeconds(DrawCorpusTests.CorpusTimeLimitSeconds), null);
        List<DrawCaseRun> aRuns = [.. aNew.AsParallel().WithDegreeOfParallelism(Math.Max(1, Environment.ProcessorCount / 2)).Select(RunOne)];
        aRuns.Sort((x, y) => StringComparer.Ordinal.Compare(x.Case.Id, y.Case.Id));
        output.WriteLine("after 7N3: " + string.Join(", ", aRuns.GroupBy(r => r.Status.Split(' ')[0])
                                                               .OrderBy(g => g.Key, StringComparer.Ordinal)
                                                               .Select(g => $"{g.Key} {g.Count()}")));
        output.WriteLine("with data: " + aRuns.Count(r => !r.Status.StartsWith("SKIPPED", StringComparison.Ordinal)));
        foreach (DrawCaseRun aRun in aRuns)
        {
            if (aRun.Status == "OK" || aRun.Status.StartsWith("SKIPPED", StringComparison.Ordinal))
            {
                continue;
            }
            output.WriteLine($"  {aRun.Case.Id}: {aRun.Status}");
            if (!aRun.Passed)
            {
                string[] aLines = aRun.Log.Split('\n');
                string? aLine = aLines.FirstOrDefault(l => l.Contains("rror", StringComparison.Ordinal)
                                                           || l.Contains("xception", StringComparison.Ordinal)
                                                           || l.Contains("Faulty", StringComparison.Ordinal));
                output.WriteLine($"      {aLine ?? aLines.Reverse().Skip(1).FirstOrDefault()}");
                if (Environment.GetEnvironmentVariable("OCCTNET_7N3_LOG") is not null)
                {
                    output.WriteLine(aRun.Log);
                }
            }
        }

        output.WriteLine("Commands the other cases using 7N3's commands miss (cases):");
        foreach (var aGroup in aScans.Where(s => !s.IsRunnable).SelectMany(s => s.Missing).GroupBy(c => c)
                                     .OrderByDescending(g => g.Count()).Take(15))
        {
            output.WriteLine($"  {aGroup.Key,-20} {aGroup.Count()}");
        }

        if (isFiltered)
        {
            return;
        }

        // unit 7N3: 894 cases use the commands, 883 newly runnable (799 with data; none before): OK 712, BAD 34 (OCCT's
        // TODOs), IMPROVEMENT 8, SKIPPED 84 (data not public), FAILED 45 before the two fixes below; the 11 others miss
        // viewer commands and stepread. encoderegularity rebinding the variables (decision 1145): OK 719, FAILED 38.
        // The frozen ConstrainedFilling surface in ChFi3d_Builder_2's PerformSetOfKGen (a port bug, fixed in src by the
        // unit): OK 723, FAILED 34. Unit 7R3's seam band (decision 1155): OK 728, FAILED 29 (buildevol F7, F8, simple K2,
        // K3, bug28828_4 pass). Its points at edge ends, overflowing sections and hole-like fillet loops (11203-11206):
        // OK 736, IMPROVEMENT 10, BAD 33, FAILED 20. Every failure is attributed (KnownFailures). Unit 8F's STEP commands:
        // 884 runnable, OK 737.
        Assert.Equal(894, aScans.Count);
        Assert.Empty(aRunnableBefore);
        Assert.Equal(884, aNew.Count);
        Assert.True(aRuns.Count(r => r.Status == "OK") >= 736, $"{aRuns.Count(r => r.Status == "OK")}");
        Assert.Equal(84, aRuns.Count(r => r.Status.StartsWith("SKIPPED", StringComparison.Ordinal)));
        Assert.All(aRuns, r => Assert.True(!r.Status.StartsWith("FAILED", StringComparison.Ordinal) || KnownFailures.ContainsKey(r.Case.Id),
                                           $"{r.Case.Id}: {r.Status}"));
    }

