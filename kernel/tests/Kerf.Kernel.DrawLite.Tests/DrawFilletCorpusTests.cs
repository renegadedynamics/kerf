    [Fact]
    public void The_commands_fillet_and_chamfer_as_Draw()
    {
        DrawInterpreter aDI = NewInterpreter();
        aDI.Eval("box b 10 10 10");
        aDI.Eval("explode b e");

        // tolblend: printed by blend, set per interpreter
        Assert.Contains("tolblend 0.01 0.0001 1.0000000000000001e-05 0.001", aDI.Eval("tolblend"), StringComparison.Ordinal);
        aDI.Eval("tolblend 0.01 0.001 1e-05 0.001");
        Assert.Contains("tolerance 3d  : 0.001", aDI.Eval("tolblend"), StringComparison.Ordinal);
        Assert.Contains("tolerance 3d  : 0.0001", NewInterpreter().Eval("tolblend"), StringComparison.Ordinal);

        // blend: a box's edge, r = 1: the volume 1000 - (1 - pi/4) * 10
        aDI.Eval("blend r b 1 b_1");
        Assert.Matches(@"Mass :\s+997\.85", aDI.Eval("vprops r"));
        Assert.Equal("", aDI.Eval("checkshape r").Replace("This shape seems to be valid", "", StringComparison.Ordinal).Trim());
        // checkhist: the fillet's faces generated by the contour's vertices and edge
        Assert.Contains("foreach g", aDI.Eval("checkhist"), StringComparison.Ordinal);
        Assert.Equal("generated_000 generated_001 generated_002", aDI.Eval("lsort [directory generated_*]"));

        // mkevol, updatevol, buildevol: a radius from 1 to 2
        aDI.Eval("mkevol re b");
        aDI.Eval("updatevol b_1 0 1 1 2");
        aDI.Eval("buildevol");
        Assert.Matches(@"Mass :\s+99\d\.", aDI.Eval("vprops re"));

        // chamf by one distance, two distances, a distance and an angle
        aDI.Eval("explode b f");
        aDI.Eval("explode b_1 e"); // b_1_1: an edge of the face b_1
        aDI.Eval("chamf c1 b b_1_1 1");
        Assert.Matches(@"Mass :\s+995\b", aDI.Eval("vprops c1"));
        aDI.Eval("chamf c2 b b_1_1 b_1 1 2");
        Assert.Matches(@"Mass :\s+990\b", aDI.Eval("vprops c2"));
        aDI.Eval("chamf c3 b b_1_1 b_1 A 1 45");
        Assert.Matches(@"Mass :\s+995\b", aDI.Eval("vprops c3"));

        // fillet (the feature command): the edges of a compound
        aDI.Eval("compound b_1_1 b_1_2 ce");
        aDI.Eval("fillet rf b 1 ce");
        Assert.Matches(@"Mass :\s+99\d\.", aDI.Eval("vprops rf"));
    }

