using Kerf.Engine.Foundation;
using Kerf.Engine.Topology;
using Kerf.Topology;
using static Kerf.Topology.ShapeType;

namespace Occt;

/// <summary>
/// Builds a pipe: a profile (any shape but a solid) swept along a wire (the spine), keeping the angle the spine makes
/// with the profile. The spine must be G1 continuous.
/// </summary>
/// <remarks>
/// <para>OCCT's pipe sweeps the profile in place and writes into the sub-shapes of it the result shares. A profile
/// holding frozen TShapes (any shape a caller has) is swept as an exact copy, and the result holds the profile's own
/// sub-shapes wherever the sweep left them unchanged, as <see cref="BRepPrimAPI_MakePrism"/> does
/// (<see cref="BRepPrimAPI_MakeSweep"/>, decision 910); the history answers for the caller's sub-shapes, and the
/// profile is never changed.</para>
/// <para>The result, <see cref="BRepPrimAPI_MakeSweep.FirstShape()"/>, <see cref="BRepPrimAPI_MakeSweep.LastShape()"/>
/// and the history are frozen when returned (design 4.2).</para>
/// </remarks>
public class BRepOffsetAPI_MakePipe : BRepPrimAPI_MakeSweep
{
    private readonly BRepFill_Pipe myPipe;

    /// <summary>
    /// The pipe of <paramref name="Profile"/> along <paramref name="Spine"/> (corrected Frenet trihedron).
    /// </summary>
    /// <exception cref="DomainErrorException">The profile is a solid or a composite solid.</exception>
    public BRepOffsetAPI_MakePipe(in Wire Spine, in Shape Profile)
    {
        myPipe = new BRepFill_Pipe(Spine, GeneratingShapeForWrite(Profile));
        Build();
    }

    /// <summary>
    /// The pipe of <paramref name="Profile"/> along <paramref name="Spine"/> with the trihedron
    /// <paramref name="aMode"/> (Frenet, corrected Frenet or discrete), and an attempt at C1 surfaces where a swept
    /// surface is C0 with <paramref name="ForceApproxC1"/>.
    /// </summary>
    public BRepOffsetAPI_MakePipe(in Wire Spine,
                                  in Shape Profile,
                                  GeomFill_Trihedron aMode,
                                  bool ForceApproxC1 = false)
    {
        myPipe = new BRepFill_Pipe(Spine, GeneratingShapeForWrite(Profile), aMode, ForceApproxC1);
        Build();
    }

    /// <summary>The internal pipe algorithm (on the copy of a frozen profile).</summary>
    internal BRepFill_Pipe Pipe() => myPipe;

    /// <summary>Builds the resulting shape (redefined from MakeShape).</summary>
    public override void Build(ProgressRange theRange = default)
    {
        myShape = myPipe.InternalShape();
        KeepUnchangedGenerating(ref myShape);
        // Check for emptiness of result
        NCollection_IndexedMap<Shape> theMap = new(ShapeHasher.Instance);
        Exploration.MapShapes(myShape, theMap);
        if (theMap.Extent() == 1)
        {
            NotDone();
        }
        else
        {
            Done();
        }
    }

    internal override Shape InternalFirstShape() => FromSwept(myPipe.InternalFirstShape());

    internal override Shape InternalLastShape() => FromSwept(myPipe.InternalLastShape());

    /// <summary>The list of shapes generated from the shape <paramref name="S"/>, of the profile or the spine.</summary>
    internal override NCollection_List<Shape> InternalGenerated(in Shape S)
    {
        NCollection_List<Shape> aList = new();
        myPipe.InternalGenerated(ToSwept(S), aList);
        myGenerated.Clear();
        for (NCollection_List<Shape>.Iterator anIt = new(aList); anIt.More(); anIt.Next())
        {
            myGenerated.Append(FromSwept(anIt.Value()));
        }
        return myGenerated;
    }

    /// <summary>
    /// The face generated by an edge of the spine and an edge of the profile, or the edge generated by an edge of the
    /// spine and a vertex of the profile (frozen; null for other shapes).
    /// </summary>
    public Shape Generated(in Shape SSpine, in Shape SProfile) => Published(InternalGenerated(SSpine, SProfile));

    /// <summary><see cref="Generated(in Shape, in Shape)"/> without freezing.</summary>
    internal Shape InternalGenerated(in Shape SSpine, in Shape SProfile)
    {
        if (SProfile.ShapeType() == ShapeType.Edge)
        {
            return FromSwept(myPipe.InternalFace(ShapeCasts.Edge(SSpine), ShapeCasts.Edge(ToSwept(SProfile))));
        }
        else if (SProfile.ShapeType() == ShapeType.Vertex)
        {
            return FromSwept(myPipe.InternalEdge(ShapeCasts.Edge(SSpine), ShapeCasts.Vertex(ToSwept(SProfile))));
        }

        // POP pour NT
        Shape bid = new();
        return bid;
    }

    /// <summary>The approximation error of the swept surfaces.</summary>
    public double ErrorOnSurface() => myPipe.ErrorOnSurface();
}
