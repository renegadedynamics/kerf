using Kerf.Engine.Topology;
using Kerf.Engine.Topology.Adaptors;
using Kerf.Engine.Topology.Brep;
using Kerf.Geometry;
using Kerf.Topology;
using static Kerf.Geometry.Continuity;
using static Kerf.Topology.ShapeType;

namespace Occt;

/// <summary>
/// A sweep by a transformation (a translation or a rotation): without copy, the shapes of the first directing vertex
/// are the generating shape's own sub-shapes, and those of the last are them moved by the location.
/// </summary>
internal abstract class BRepSweep_Trsf : BRepSweep_NumLinearRegularSweep
{
    protected readonly Placement myLocation;
    protected readonly bool myCopy;

    protected BRepSweep_Trsf(BrepBuilder aBuilder, in Shape aGenShape, in Sweep_NumShape aDirWire,
                             in Placement aLocation, bool aCopy)
        : base(new BRepSweep_Builder(aBuilder), aGenShape, aDirWire)
    {
        myLocation = aLocation;
        myCopy = aCopy;
    }

    /// <summary>Without copy, binds the generating shape's sub-shapes (moved for the last vertex) to the directing vertices.</summary>
    public void Init()
    {
        if (!myCopy)
        {
            var It = new Sweep_NumShapeIterator();
            for (It.Init(myDirWire); It.More(); It.Next())
            {
                Process(myGenShape, It.Value());
            }
        }
    }

    /// <summary>
    /// Binds the shapes of [aGenS,aDirV] when they are not changed by the transformation; true if a sub-shape is
    /// invariant (so aGenS must be built).
    /// </summary>
    public bool Process(in Shape aGenS, in Sweep_NumShape aDirV)
    {
        bool dotrsf = (aDirV.Index() == 2 && !myDirWire.Closed());
        int iD = myDirShapeTool.Index(aDirV);
        int iG = myGenShapeTool.Index(aGenS);
        if (IsInvariant(aGenS))
        {
            myShapes[iG, iD] = aGenS;
            myBuiltShapes[iG, iD] = true;
            return true;
        }
        else
        {
            var Jt = new BRepSweep_Iterator();
            bool touch = false;
            for (Jt.Init(aGenS); Jt.More(); Jt.Next())
            {
                if (Process(Jt.Value(), aDirV))
                {
                    touch = true;
                }
            }
            if (!touch || !dotrsf)
            {
                Shape newShape = aGenS;
                if (dotrsf)
                {
                    newShape.Move(myLocation);
                }
                myShapes[iG, iD] = newShape;
                myBuiltShapes[iG, iD] = true;
            }
            return touch;
        }
    }

    /// <summary>Sets the continuity of the new edges between the faces generated by edges and vertices of aGenS.</summary>
    public override void SetContinuity(in Shape aGenS, in Sweep_NumShape aDirS)
    {
        double tl = global::Kerf.Engine.Foundation.Precision.Confusion();
        // angular etant un peu severe pour les contours sketches.
        double ta = 0.00175; // environ 0.1 degre
        Continuity cont;
        BrepBuilder B = myBuilder.Builder();
        if (aGenS.ShapeType() == ShapeType.Edge)
        {
            if (HasShape(aGenS, aDirS))
            {
                Edge E = ShapeCasts.Edge(aGenS);
                var e = new EdgeCurveAdaptor();
                double ud, uf;
                Exploration.Vertices(E, out Vertex d, out Vertex f);
                if (d.IsSame(f))
                {
                    //	tol3d = std::max(tl,BRep_Tool::Tolerance(d));
                    double tol3d = Max(tl, 2.0 * Tool.Tolerance(d)); // IFV 24.05.00 buc60684
                    e.Initialize(E);
                    ud = Tool.Parameter(d, ShapeCasts.Edge(aGenS));
                    uf = Tool.Parameter(f, ShapeCasts.Edge(aGenS));
                    cont = global::Kerf.Engine.Topology.Properties.BRepLProp.Continuity(e, e, ud, uf, tol3d, ta);
                    if (cont >= G1)
                    {
                        Shape s_wnt = Shape(d, aDirS);
                        Edge e_wnt = ShapeCasts.Edge(s_wnt);
                        s_wnt = Shape(aGenS, aDirS);
                        Face f_wnt = ShapeCasts.Face(s_wnt);
                        B.Continuity(e_wnt, f_wnt, f_wnt, cont);
                    }
                }
                if (aDirS.Closed())
                {
                    Sweep_NumShape dirv = myDirShapeTool.Shape(2);
                    if (GDDShapeIsToAdd(Shape(aGenS, aDirS), Shape(aGenS, dirv), aGenS, aDirS, dirv))
                    {
                        cont = Tool.Curve(E, out Placement _, out double _, out double _)!.Continuity();
                        if (cont >= G1)
                        {
                            Shape s_wnt = Shape(aGenS, dirv);
                            Edge e_wnt = ShapeCasts.Edge(s_wnt);
                            s_wnt = Shape(aGenS, aDirS);
                            Face f_wnt = ShapeCasts.Face(s_wnt);
                            B.Continuity(e_wnt, f_wnt, f_wnt, cont);
                        }
                    }
                }
            }
        }
        else if (aGenS.ShapeType() == ShapeType.Wire)
        {
            Edge E1, E2;
            var e1 = new EdgeCurveAdaptor();
            var e2 = new EdgeCurveAdaptor();
            double u1, u2;
            var M = new NCollection_IndexedDataMap<Shape, NCollection_List<Shape>>(ShapeHasher.Instance);
            Exploration.MapShapesAndAncestors(aGenS, ShapeType.Vertex, ShapeType.Edge, M);
            var It = new NCollection_List<Shape>.Iterator();
            var Jt = new NCollection_List<Shape>.Iterator();
            for (int i = 1; i <= M.Extent(); i++)
            {
                Vertex V = ShapeCasts.Vertex(M.FindKey(i));
                int j = 1;
                for (It.Initialize(M.FindFromIndex(i)); It.More(); It.Next(), j++)
                {
                    Jt.Initialize(M.FindFromIndex(i));
                    for (int k = 1; k <= j; k++)
                    {
                        Jt.Next();
                    }
                    for (; Jt.More(); Jt.Next())
                    {
                        E1 = ShapeCasts.Edge(It.Value());
                        E2 = ShapeCasts.Edge(Jt.Value());
                        if (!E1.IsSame(E2) && HasShape(E1, aDirS) && HasShape(E2, aDirS))
                        {
                            u1 = Tool.Parameter(V, E1);
                            u2 = Tool.Parameter(V, E2);
                            //	    tol3d = std::max(tl,BRep_Tool::Tolerance(V));
                            double tol3d = Max(tl, 2.0 * Tool.Tolerance(V)); // IFV 24.05.00 buc60684
                            e1.Initialize(E1);
                            e2.Initialize(E2);
                            cont = global::Kerf.Engine.Topology.Properties.BRepLProp.Continuity(e1, e2, u1, u2, tol3d, ta);
                            if (cont >= G1)
                            {
                                Shape s_wnt = Shape(V, aDirS);
                                Edge e_wnt = ShapeCasts.Edge(s_wnt);
                                s_wnt = Shape(E1, aDirS);
                                Face f1_wnt = ShapeCasts.Face(s_wnt);
                                s_wnt = Shape(E2, aDirS);
                                Face f2_wnt = ShapeCasts.Face(s_wnt);
                                B.Continuity(e_wnt, f1_wnt, f2_wnt, cont);
                            }
                        }
                    }
                }
            }
        }
    }
}
