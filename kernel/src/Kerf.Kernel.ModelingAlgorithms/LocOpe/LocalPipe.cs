/// <summary>
/// The pipe of a profile along a spine for a feature: the faces generated by the profile's connecting edges are left
/// out and the coplanar faces generated by an edge are fused; the faces generated by the profile's edges and vertices,
/// and the curves along the pipe through given points.
/// </summary>
/// <remarks>
/// <para>
/// BRepFill_Pipe sweeps the profile in place, as OCCT does, and writes into the sub-shapes the pipe shares with it: a
/// frozen profile (or spine) is swept in a working overlay (unit 10H5), and the result holds new TShapes only for the
/// caller's sub-shapes that changed (decisions 910, 1014). <see cref="Shapes"/> answers for the caller's edges and vertices. The shapes it hands
/// out are frozen; ported callers (BRepFeat_MakePipe) read the <c>Internal</c> forms.
/// </para>
/// <para>
/// OCCT groups the planar faces generated by an edge from a map keyed by the faces' addresses: the face taken as
/// reference first depends on the run natively; the port takes them in the order they are generated.
/// </para>
/// </remarks>
internal sealed class LocalPipe
{
    private readonly Pipe _pipe;
    private readonly Dictionary<Shape, NCollection_List<Shape>> _map = new(ShapeHasher.Instance);
    private Shape _res = new();
    private NCollection_List<Shape> _gShap = new();
    private readonly NCollection_Sequence<Curve3D?> _crvs = new();
    private readonly Wire _spine;
    private readonly Shape _profile;
    private readonly WorkingShapes _work = new();

    public LocalPipe(in Wire spine, in Shape profile)
    {
        _spine = spine;
        _profile = profile;
        // Kerf: the pipe writes into the profile it shares (decisions 910, 1014): in the working overlay (unit 10H5)
        using WorkingOverlay.Scope scope = _work.Enter();
        _pipe = new Pipe(spine, profile);

        Shape result = _pipe.InternalShape();

        // On enleve les faces generees par les edges de connexite du profile,
        // et on fusionne les plans si possible

        IndexedMap<Shape, NCollection_List<Shape>> theEFMap = new(ShapeHasher.Instance);
        Exploration.MapShapesAndAncestors(profile, ShapeType.Edge, ShapeType.Face, theEFMap);
        Explorer exp = new();
        NCollection_List<Shape>.Iterator it = new();

        NCollection_List<Shape> goodfaces = new();

        for (int i = 0; i < theEFMap.Count; i++)
        {
            Edge edgpr = ShapeCasts.Edge(theEFMap.KeyAt(i));
            _map[edgpr] = new NCollection_List<Shape>();
            if (theEFMap.ValueAt(i).Extent() >= 2)
            {
                // on ne prend pas les faces generees
            }
            else
            {
                // on mappe les plans generes par cet edge (in the order they are generated: see the remarks)
                IndexedSet<Shape> mapFac = new(ShapeHasher.Instance);
                for (exp.Init(spine, ShapeType.Edge); exp.More(); exp.Next())
                {
                    Edge edgsp = ShapeCasts.Edge(exp.Current());
                    Face resfac = _pipe.InternalFace(edgsp, edgpr);
                    if (!resfac.IsNull)
                    {
                        Surface p0 = Tool.Surface(resfac)!;
                        if (p0.GetType() == typeof(TrimmedSurface))
                        {
                            p0 = ((TrimmedSurface)p0).BasisSurface;
                        }
                        if (p0.GetType() == typeof(PlaneSurface))
                        {
                            mapFac.Add(resfac);
                        }
                        else
                        {
                            _map.GetValue(edgpr).Append(resfac);
                            goodfaces.Append(resfac);
                        }
                    }
                }

                // Chercher les composantes connexes sur cet ensemble de faces., avec meme
                // support geometrique

                if (mapFac.Count <= 1)
                { // un seul plan. Rien a faire
                    if (mapFac.Count == 1)
                    {
                        _map.GetValue(edgpr).Append(mapFac[0]);
                        goodfaces.Append(mapFac[0]);
                    }
                    continue;
                }

                while (mapFac.Count >= 2)
                {
                    NCollection_List<Shape> facFuse = new();
                    Face faceRef = ShapeCasts.Face(mapFac[0]);
                    facFuse.Append(faceRef);
                    Surface p = Tool.Surface(faceRef)!;
                    if (p.GetType() == typeof(TrimmedSurface))
                    {
                        p = ((TrimmedSurface)p).BasisSurface;
                    }
                    Plane3D plref = ((PlaneSurface)p).Plane;

                    for (int itm = 2; itm <= mapFac.Count; itm++)
                    {
                        p = Tool.Surface(ShapeCasts.Face(mapFac[itm - 1]))!;
                        if (p.GetType() == typeof(TrimmedSurface))
                        {
                            p = ((TrimmedSurface)p).BasisSurface;
                        }
                        Plane3D pl0 = ((PlaneSurface)p).Plane;
                        if (pl0.Axis.IsParallel(plref.Axis, global::Kerf.Engine.Foundation.Precision.Angular())
                            && plref.Contains(pl0.Location, global::Kerf.Engine.Foundation.Precision.Confusion()))
                        {
                            facFuse.Append(mapFac[itm - 1]);
                        }
                    }

                    // FacFuse contient des faces de meme support. Il faut en faire
                    // des composantes connexes

                    while (facFuse.Extent() >= 2)
                    {
                        faceRef = ShapeCasts.Face(facFuse.First());
                        // Recuperer l'orientation
                        Orientation orref = Orientation(faceRef, result);
                        p = Tool.Surface(faceRef)!;
                        if (p.GetType() == typeof(TrimmedSurface))
                        {
                            p = ((TrimmedSurface)p).BasisSurface;
                        }
                        plref = ((PlaneSurface)p).Plane;
                        Direction3D dirref = plref.Axis.Direction;
                        if ((plref.IsDirect && orref == Reversed) || (!plref.IsDirect && orref == Forward))
                        {
                            dirref = dirref.Reversed();
                        }

                        // OCCT iterates this map (keyed by the edges' addresses) to build the fused face's wire: the
                        // order of its edges depends on the run natively; the port keeps them in the order they come
                        IndexedSet<Shape> mapEd = new(ShapeHasher.Instance);
                        for (exp.Init(faceRef.Oriented(Forward), ShapeType.Edge); exp.More(); exp.Next())
                        {
                            mapEd.Add(exp.Current());
                        }

                        mapFac.Remove(faceRef);
                        facFuse.RemoveFirst(); // on enleve FaceRef
                        bool faceToFuse = false;
                        bool moreFound;

                        do
                        {
                            moreFound = false;
                            for (it.Initialize(facFuse); it.More(); it.Next())
                            {
                                for (exp.Init(it.Value(), ShapeType.Edge); exp.More(); exp.Next())
                                {
                                    if (mapEd.Contains(exp.Current()))
                                    {
                                        faceToFuse = true;
                                        moreFound = true;
                                        break;
                                    }
                                }
                                if (exp.More())
                                {
                                    break;
                                }
                            }
                            if (moreFound)
                            {
                                Face fac = ShapeCasts.Face(it.Value());
                                Orientation orrelat = Orientation(fac, result);
                                Surface otherP = Tool.Surface(fac)!;
                                if (otherP.GetType() == typeof(TrimmedSurface))
                                {
                                    otherP = ((TrimmedSurface)otherP).BasisSurface;
                                }
                                Plane3D pl = ((PlaneSurface)otherP).Plane;
                                Direction3D dirpl = pl.Axis.Direction;
                                // OCCT: the second test reads the reference plane's Direct (occt-issues.md)
                                if ((pl.IsDirect && orrelat == Reversed) || (!plref.IsDirect && orrelat == Forward))
                                {
                                    dirpl = dirpl.Reversed();
                                }
                                if (dirpl.Dot(dirref) > 0)
                                {
                                    orrelat = Forward;
                                }
                                else
                                {
                                    orrelat = Reversed;
                                }
                                for (exp.Init(fac.Oriented(orrelat), ShapeType.Edge); exp.More(); exp.Next())
                                {
                                    if (mapEd.Contains(exp.Current()))
                                    {
                                        mapEd.Remove(exp.Current());
                                    }
                                    else
                                    {
                                        mapEd.Add(exp.Current());
                                    }
                                }
                                mapFac.Remove(fac);
                                facFuse.Remove(it);
                            }
                        } while (moreFound);

                        if (faceToFuse)
                        {
                            Face newFace = new();
                            BrepBuilder b = new();
                            b.MakeFace(ref newFace, p, Tool.Tolerance(faceRef));
                            Wire newWire = new();
                            b.MakeWire(ref newWire);
                            for (int itm2 = 0; itm2 < mapEd.Count; itm2++)
                            {
                                b.Add(newWire, mapEd[itm2]);
                            }
                            exp.Init(faceRef.Oriented(Forward), ShapeType.Wire);
                            newWire.Orient(exp.Current().Orientation);
                            b.Add(newFace, newWire);
                            _map.GetValue(edgpr).Append(newFace);
                            goodfaces.Append(newFace);
                        }
                    }
                    if (facFuse.Extent() == 1)
                    {
                        mapFac.Remove(facFuse.First());
                        _map.GetValue(edgpr).Append(facFuse.First());
                        goodfaces.Append(facFuse.First());
                    }
                }
            }
        }

        for (exp.Init(_pipe.InternalFirstShape(), ShapeType.Face); exp.More(); exp.Next())
        {
            goodfaces.Append(exp.Current());
        }
        for (exp.Init(_pipe.InternalLastShape(), ShapeType.Face); exp.More(); exp.Next())
        {
            goodfaces.Append(exp.Current());
        }

        BuildShape bs = new(goodfaces);
        _res = bs.InternalShape();

        // Kerf: the end of the working overlay: new TShapes for the caller's sub-shapes changed (unit 10H5)
        if (_work.IsWritten)
        {
            var shapes = new List<Shape> { _res, _pipe.InternalShape(), _pipe.InternalFirstShape(), _pipe.InternalLastShape() };
            foreach (KeyValuePair<Shape, NCollection_List<Shape>> item in _map)
            {
                shapes.AddRange(item.Value);
            }
            _work.Finish(shapes);
            _res = _work.Final(_res);
            foreach (Shape key in _map.Keys.ToList())
            {
                _map.GetValueRef(key) = _work.Final(_map.GetValue(key));
            }
        }
    }

    /// <summary>The spine (the caller's).</summary>
    public Shape Spine() => _spine;

    /// <summary>The profile (the caller's).</summary>
    public Shape Profile() => _profile;

    /// <summary>The profile's image at the start of the pipe (frozen).</summary>
    public Shape FirstShape() => WorkingShapes.Published(InternalFirstShape());

    /// <summary><see cref="FirstShape"/> without freezing, for ported code.</summary>
    internal Shape InternalFirstShape() => _work.Final(_pipe.InternalFirstShape());

    /// <summary>The profile's image at the end of the pipe (frozen).</summary>
    public Shape LastShape() => WorkingShapes.Published(InternalLastShape());

    /// <summary><see cref="LastShape"/> without freezing, for ported code.</summary>
    internal Shape InternalLastShape() => _work.Final(_pipe.InternalLastShape());

    /// <summary>The pipe (frozen).</summary>
    public Shape Shape() => WorkingShapes.Published(_res);

    /// <summary><see cref="Shape"/> without freezing, for ported code.</summary>
    internal Shape InternalShape() => _res;

    /// <summary>
    /// The faces generated by the edge <paramref name="s"/> of the profile, or the edges generated by its vertex
    /// (frozen).
    /// </summary>
    public NCollection_List<Shape> Shapes(in Shape s) => WorkingShapes.Published(InternalShapes(s));

    /// <summary><see cref="Shapes"/> without freezing, for ported code.</summary>
    internal NCollection_List<Shape> InternalShapes(in Shape s0)
    {
        Shape s = s0;
        ShapeType typS = s.Type;
        if (typS != ShapeType.Edge && typS != ShapeType.Vertex)
        {
            throw new DomainErrorException();
        }
        Explorer exp = new(_profile, typS);
        for (; exp.More(); exp.Next())
        {
            if (exp.Current().IsSame(s))
            {
                break;
            }
        }
        if (!exp.More())
        {
            throw new NoSuchObjectException();
        }

        _gShap = new NCollection_List<Shape>(); // OCCT clears the list it returned before
        if (typS == ShapeType.Vertex)
        {
            Vertex vProfile = ShapeCasts.Vertex(s);
            for (exp.Init(_spine, ShapeType.Edge); exp.More(); exp.Next())
            {
                Edge edsp = ShapeCasts.Edge(exp.Current());
                Edge resed = _pipe.InternalEdge(edsp, vProfile);
                if (!resed.IsNull)
                {
                    _gShap.Append(_work.Final(resed));
                }
            }
            return _gShap;
        }
        // TopAbs_EDGE
        Edge eProfile = ShapeCasts.Edge(s);
        return _map.GetValue(eProfile);
    }

    // Kerf: OCCT segments and re-knots the converted curve in place; a frozen one is changed on a copy
    private static BSplineCurve3D Writable(BSplineCurve3D curve) =>
        curve.IsFrozen ? (BSplineCurve3D)curve.Copy() : curve;

    /// <summary>The curves along the pipe through the points <paramref name="spt"/> (one per point, null if none).</summary>
    public NCollection_Sequence<Curve3D?> Curves(NCollection_Sequence<Point3D> spt)
    {
        _crvs.Clear();

        int i, j, k, nbpnt = spt.Length();

        for (i = 1; i <= nbpnt; i++)
        {
            Point3D P1 = spt[i];
            int maxDeg = 0;
            NCollection_Sequence<Curve3D> seq = new();
            Wire w = _pipe.InternalPipeLine(P1);

            Explorer ex = new(w, ShapeType.Edge);
            for (; ex.More(); ex.Next())
            {
                Curve3D c1 = Tool.Curve(ShapeCasts.Edge(ex.Current()), out double p1, out double p2)!;
                BSplineCurve3D? c0 = global::Kerf.Engine.Geometry.Conversion.GeomConvert.CurveToBSplineCurve(c1);
                if (c0 is null)
                {
                    continue;
                }
                BSplineCurve3D c = Writable(c0);
                maxDeg = Max(maxDeg, c.Degree);
                P1 = c.Value(p2);
                if (p1 != c.FirstParameter || p2 != c.LastParameter)
                {
                    c.Segment(p1, p2);
                }
                NCollection_Array1<double> tkn = new(c.InternalKnots());
                global::Kerf.Engine.Geometry.Splines.BSplCLib.Reparametrize(seq.Length(), seq.Length() + 1, tkn);
                c.SetKnots(tkn);
                seq.Append(c);
            }

            Curve3D? newC = null;
            int nbkn = 0, nbp = 0;
            int nbcurv = seq.Length();
            if (nbcurv == 0)
            {
                _crvs.Append(newC);
                continue;
            }

            BSplineCurve3D bsp;
            for (j = 1; j <= nbcurv; j++)
            {
                bsp = (BSplineCurve3D)seq[j];
                bsp.IncreaseDegree(maxDeg);
                nbp += bsp.PoleCount;
                nbkn += bsp.KnotCount;
            }
            nbp -= nbcurv - 1;
            nbkn -= nbcurv - 1;
            NCollection_Array1<double> tkn2 = new(1, nbkn);
            NCollection_Array1<int> tmu = new(1, nbkn);
            NCollection_Array1<Point3D> tpol = new(1, nbp);
            int ik = 0, ip = 0;

            bsp = (BSplineCurve3D)seq[1];
            for (k = 1; k <= bsp.PoleCount; k++)
            {
                ip++;
                tpol[ip] = bsp.Pole(k);
            }
            for (k = 1; k <= bsp.KnotCount; k++)
            {
                ik++;
                tkn2[ik] = bsp.Knot(k);
                tmu[ik] = bsp.Multiplicity(k);
            }
            tmu[ik]--;

            for (j = 2; j <= nbcurv; j++)
            {
                bsp = (BSplineCurve3D)seq[j];
                for (k = 2; k <= bsp.PoleCount; k++)
                {
                    ip++;
                    tpol[ip] = bsp.Pole(k);
                }
                for (k = 2; k <= bsp.KnotCount; k++)
                {
                    ik++;
                    tkn2[ik] = bsp.Knot(k);
                    tmu[ik] = bsp.Multiplicity(k);
                }
                tmu[ik]--;
            }
            tmu[ik]++;
            newC = new BSplineCurve3D(tpol, tkn2, tmu, maxDeg);
            _crvs.Append(newC);
        }

        return _crvs;
    }

    private static Orientation Orientation(in Shape sub, in Shape s)
    {
        Explorer exp = new();
        for (exp.Init(s, sub.Type); exp.More(); exp.Next())
        {
            if (exp.Current().IsSame(sub))
            {
                return exp.Current().Orientation;
            }
        }
        throw new NoSuchObjectException();
    }

    /// <summary>The curve along the pipe through the barycentre of the first shape's sample points.</summary>
    public Curve3D BarycCurve()
    {
        int j, k;

        NCollection_Sequence<Point3D> spt = new();
        Shape Base = InternalFirstShape();
        global::Kerf.Engine.Features.Local.LocOpe.SampleEdges(Base, spt);
        Xyz aBar = new(0.0, 0.0, 0.0);
        for (int jj = 1; jj <= spt.Length(); jj++)
        {
            Point3D pvt = spt[jj];
            aBar += pvt.XYZ();
        }
        aBar.Divide(spt.Length());
        Point3D bar = new(aBar);

        Point3D P1 = bar;

        int maxDeg = 0;
        NCollection_Sequence<Curve3D> seq = new();
        Wire w = _pipe.InternalPipeLine(P1);

        Explorer ex = new(w, ShapeType.Edge);
        for (; ex.More(); ex.Next())
        {
            Curve3D c1 = Tool.Curve(ShapeCasts.Edge(ex.Current()), out double p1, out double p2)!;
            BSplineCurve3D? c0 = global::Kerf.Engine.Geometry.Conversion.GeomConvert.CurveToBSplineCurve(c1);

            if (c0 is null)
            {
                continue;
            }
            BSplineCurve3D c = Writable(c0);
            maxDeg = Max(maxDeg, c.Degree);
            P1 = c.Value(p2);
            if (p1 != c.FirstParameter || p2 != c.LastParameter)
            {
                c.Segment(p1, p2);
            }
            NCollection_Array1<double> tkn0 = new(c.InternalKnots());
            global::Kerf.Engine.Geometry.Splines.BSplCLib.Reparametrize(seq.Length(), seq.Length() + 1, tkn0);
            c.SetKnots(tkn0);
            seq.Append(c);
        }
        Curve3D? newC = null;
        int nbkn = 0, nbp = 0;
        int nbcurv = seq.Length();
        if (nbcurv == 0)
        {
            _crvs.Append(newC); // OCCT: and goes on, to throw reading the first curve below
        }
        BSplineCurve3D bsp;
        for (j = 1; j <= nbcurv; j++)
        {
            bsp = (BSplineCurve3D)seq[j];
            bsp.IncreaseDegree(maxDeg);
            nbp += bsp.PoleCount;
            nbkn += bsp.KnotCount;
        }
        nbp -= nbcurv - 1;
        nbkn -= nbcurv - 1;
        NCollection_Array1<double> tkn = new(1, nbkn);
        NCollection_Array1<int> tmu = new(1, nbkn);
        NCollection_Array1<Point3D> tpol = new(1, nbp);
        int ik = 0, ip = 0;

        bsp = (BSplineCurve3D)seq[1];
        for (k = 1; k <= bsp.PoleCount; k++)
        {
            ip++;
            tpol[ip] = bsp.Pole(k);
        }
        for (k = 1; k <= bsp.KnotCount; k++)
        {
            ik++;
            tkn[ik] = bsp.Knot(k);
            tmu[ik] = bsp.Multiplicity(k);
        }
        tmu[ik]--;

        for (j = 2; j <= nbcurv; j++)
        {
            bsp = (BSplineCurve3D)seq[j];
            for (k = 2; k <= bsp.PoleCount; k++)
            {
                ip++;
                tpol[ip] = bsp.Pole(k);
            }
            for (k = 2; k <= bsp.KnotCount; k++)
            {
                ik++;
                tkn[ik] = bsp.Knot(k);
                tmu[ik] = bsp.Multiplicity(k);
            }
            tmu[ik]--;
        }
        tmu[ik]++;
        newC = new BSplineCurve3D(tpol, tkn, tmu, maxDeg);

        return newC;
    }
