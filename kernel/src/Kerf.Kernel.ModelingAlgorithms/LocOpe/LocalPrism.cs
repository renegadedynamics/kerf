namespace Kerf.Engine.Features.Local;

/// <summary>
/// The prism of a base (a face, or faces and edges) along a vector, possibly translated first: the shape, its first and
/// last shapes, the faces generated by the base's edges, and curves to intersect with the solid it is glued on.
/// </summary>
/// <remarks>
/// As BRepPrimAPI_MakePrism (decision 468), it sweeps the base in place, as OCCT does, which writes into the base's
/// sub-shapes the prism shares: a frozen base is swept as a working copy, and the caller's sub-shapes left unchanged
/// come back in the result (decision 1014). <see cref="Shapes"/> answers for the caller's edges. The shapes it hands
/// out are frozen; ported callers (BRepFeat) read the <c>Internal</c> forms.
/// </remarks>
public sealed class LocalPrism
{
    private Shape _base = new();
    private Vector3D _vec = new();
    private Vector3D _tra = new();
    private bool _isTrans;
    private bool _done;
    private Shape _res = new();
    private Shape _firstShape = new();
    private Shape _lastShape = new();
    private readonly Dictionary<Shape, NCollection_List<Shape>> _map = new(ShapeHasher.Instance);
    private WorkingShapes _work = new();

    public LocalPrism()
    {
        _isTrans = false;
        _done = false;
    }

    public LocalPrism(in Shape Base, in Vector3D v)
    {
        _base = Base;
        _vec = v;
        _isTrans = false;
        IntPerf();
    }

    public LocalPrism(in Shape Base, in Vector3D v, in Vector3D vtra)
    {
        _base = Base;
        _vec = v;
        _tra = vtra;
        _isTrans = true;
        IntPerf();
    }

    public void Perform(in Shape Base, in Vector3D v)
    {
        _map.Clear();
        _firstShape.Nullify();
        _lastShape.Nullify();
        _base.Nullify();
        _res.Nullify();

        _base = Base;
        _vec = v;
        _isTrans = false;
        IntPerf();
    }

    public void Perform(in Shape Base, in Vector3D v, in Vector3D vtra)
    {
        _map.Clear();
        _firstShape.Nullify();
        _lastShape.Nullify();
        _base.Nullify();
        _res.Nullify();

        _base = Base;
        _vec = v;
        _tra = vtra;
        _isTrans = true;
        IntPerf();
    }

    private void IntPerf()
    {
        Shape theBase = _base;
        Modifier modif = new();
        if (_isTrans)
        {
            Transform3D t = new Transform3D().WithTranslation(_tra);
            TrsfModification modbase = new(t);
            modif.Init(theBase);
            modif.Perform(modbase);
            theBase = modif.InternalModifiedShape(theBase);
        }

        // OCCT.NET: the sweep writes into the base it shares (decision 1014)
        _work = new WorkingShapes();
        theBase = _work.Working(theBase);

        Prism thePrism = new(theBase, _vec);

        _firstShape = thePrism.FirstShape();
        _lastShape = thePrism.LastShape();

        Explorer exp = new();
        if (theBase.ShapeType() == ShapeType.Face)
        {
            for (exp.Init(theBase, ShapeType.Edge); exp.More(); exp.Next())
            {
                Edge edg = ShapeCasts.Edge(exp.Current());
                if (!_map.ContainsKey(edg))
                {
                    NCollection_List<Shape> thelist = new();
                    _map[edg] = thelist;
                    Shape desc = thePrism.Shape(edg);
                    if (!desc.IsNull)
                    {
                        _map.GetValue(edg).Append(desc);
                    }
                }
            }
            _res = thePrism.Shape();
        }

        else
        {
            // Cas base != FACE
            NCollection_IndexedDataMap<Shape, NCollection_List<Shape>> theEFMap = new(ShapeHasher.Instance);
            Exploration.MapShapesAndAncestors(theBase, ShapeType.Edge, ShapeType.Face, theEFMap);
            NCollection_List<Shape> lfaces = new();
            bool toremove = false;
            for (int i = 1; i <= theEFMap.Extent(); i++)
            {
                Shape edg = theEFMap.FindKey(i);
                NCollection_List<Shape> thelist1 = new();
                _map[edg] = thelist1;
                Shape desc = thePrism.Shape(edg);
                if (!desc.IsNull)
                {
                    if (theEFMap[i].Extent() >= 2)
                    {
                        toremove = true;
                    }
                    else
                    {
                        _map.GetValue(edg).Append(desc);
                        lfaces.Append(desc);
                    }
                }
            }
            if (toremove)
            {
                // Rajouter les faces de FirstShape et LastShape
                for (exp.Init(_firstShape, ShapeType.Face); exp.More(); exp.Next())
                {
                    lfaces.Append(exp.Current());
                }
                for (exp.Init(_lastShape, ShapeType.Face); exp.More(); exp.Next())
                {
                    lfaces.Append(exp.Current());
                }

                BuildShape bs = new(lfaces);
                _res = bs.InternalShape();
            }
            else
            {
                for (exp.Init(theBase, ShapeType.Edge); exp.More(); exp.Next())
                {
                    Edge edg = ShapeCasts.Edge(exp.Current());
                    if (!_map.ContainsKey(edg))
                    {
                        NCollection_List<Shape> thelist2 = new();
                        _map[edg] = thelist2;
                        Shape desc = thePrism.Shape(edg);
                        if (!desc.IsNull)
                        {
                            _map.GetValue(edg).Append(desc);
                        }
                    }
                }
                _res = thePrism.Shape();
            }
        }

        if (_isTrans)
        {
            // m-a-j des descendants
            Explorer anExp = new();
            for (anExp.Init(_base, ShapeType.Edge); anExp.More(); anExp.Next())
            {
                Edge edg = ShapeCasts.Edge(anExp.Current());
                Edge edgbis = ShapeCasts.Edge(_work.Copied(modif.InternalModifiedShape(edg)));
                if (!edgbis.IsSame(edg) && _map.ContainsKey(edgbis))
                {
                    _map[edg] = _map.GetValue(edgbis);
                    _map.Remove(edgbis);
                }
            }
        }

        // OCCT.NET: the copies left unchanged come back as the caller's sub-shapes
        if (_work.IsCopied)
        {
            var shapes = new List<Shape> { _res, _firstShape, _lastShape };
            foreach (KeyValuePair<Shape, NCollection_List<Shape>> item in _map)
            {
                shapes.AddRange(item.Value);
            }
            _work.Finish(shapes);
            _res = _work.Final(_res);
            _firstShape = _work.Final(_firstShape);
            _lastShape = _work.Final(_lastShape);
            foreach (Shape key in _map.Keys.ToList())
            {
                _map.GetValueRef(key) = _work.Final(_map.GetValue(key));
            }
        }
        _done = true;
    }

    /// <summary>The prism (frozen).</summary>
    public Shape Shape() => WorkingShapes.Published(InternalShape());

    /// <summary><see cref="Shape"/> without freezing, for ported code.</summary>
    internal Shape InternalShape()
    {
        if (!_done)
        {
            throw new NotDoneException();
        }
        return _res;
    }

    /// <summary>The base's image at the start of the prism (frozen).</summary>
    public Shape FirstShape() => WorkingShapes.Published(_firstShape);

    /// <summary><see cref="FirstShape"/> without freezing, for ported code.</summary>
    internal Shape InternalFirstShape() => _firstShape;

    /// <summary>The base's image at the end of the prism (frozen).</summary>
    public Shape LastShape() => WorkingShapes.Published(_lastShape);

    /// <summary><see cref="LastShape"/> without freezing, for ported code.</summary>
    internal Shape InternalLastShape() => _lastShape;

    /// <summary>The faces generated by the edge <paramref name="s"/> of the base (frozen).</summary>
    public NCollection_List<Shape> Shapes(in Shape s) => WorkingShapes.Published(InternalShapes(s));

    /// <summary><see cref="Shapes"/> without freezing, for ported code (of the caller's edge or its working copy).</summary>
    internal NCollection_List<Shape> InternalShapes(in Shape s) => _map.GetValue(_work.Copied(s));

    /// <summary>The lines along the vector through sample points of the first shape's edges, trimmed to ±2 heights.</summary>
    public void Curves(NCollection_Sequence<Curve3D> scurves)
    {
        scurves.Clear();
        NCollection_Sequence<Point3D> spt = new();
        global::Kerf.Engine.Features.Local.LocOpe.SampleEdges(_firstShape, spt);
        double height = Math.Sqrt(_vec.X() * _vec.X() + _vec.Y() * _vec.Y() + _vec.Z() * _vec.Z());
        double u1 = -2 * height;
        double u2 = 2 * height;

        for (int jj = 1; jj <= spt.Length(); jj++)
        {
            Axis3D theAx = new(spt[jj], new Direction3D(_vec));
            LineCurve3D theLin = new(theAx);
            TrimmedCurve3D trlin = new(theLin, u1, u2, true);
            scurves.Append(trlin);
        }
    }

    /// <summary>The line along the vector through the barycentre of the first shape's sample points.</summary>
    public Curve3D BarycCurve()
    {
        Point3D bar = new(0.0, 0.0, 0.0);
        NCollection_Sequence<Point3D> spt = new();
        global::Kerf.Engine.Features.Local.LocOpe.SampleEdges(_firstShape, spt);
        Xyz aBar = bar.XYZ();
        for (int jj = 1; jj <= spt.Length(); jj++)
        {
            Point3D pvt = spt[jj];
            aBar += pvt.XYZ();
        }
        aBar.Divide(spt.Length());
        bar = new Point3D(aBar);
        Axis3D newAx = new(bar, new Direction3D(_vec));
        LineCurve3D theLin = new(newAx);
        return theLin;
    }
}
