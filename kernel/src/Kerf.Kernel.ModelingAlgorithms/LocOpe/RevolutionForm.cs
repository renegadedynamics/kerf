namespace Kerf.Engine.Features.Local;

/// <summary>
/// The revolution of a base around an axis for a revolved rib or groove: the shape, its first and last shapes and the
/// faces generated by the base's edges.
/// </summary>
/// <remarks>
/// As LocOpe_Revol: the base is swept in a working overlay (unit 10H5), and the result holds new TShapes only for the
/// caller's sub-shapes that changed (decision 1014). The shapes it hands out are frozen; ported callers (BRepFeat_MakeRevolutionForm) read
/// the <c>Internal</c> forms. OCCT declares the constructor that takes a base and an axis without defining it, and
/// never sets the rotation of the base it can apply first (myIsTrans stays false); the port leaves the constructor out.
/// </remarks>
public sealed class RevolutionForm
{
    private Shape _base = new();
    private Vector3D _vec = new();
    private Vector3D _tra = new();
    private double _angle;
    private Axis3D _axis = new();
    private double _angTra;
    private bool _done;
    private bool _isTrans;
    private Shape _res = new();
    private Shape _firstShape = new();
    private Shape _lastShape = new();
    private readonly Dictionary<Shape, NCollection_List<Shape>> _map = new(ShapeHasher.Instance);
    private Point3D _pnt1 = new();
    private Point3D _pnt2 = new();
    private WorkingShapes _work = new();

    public RevolutionForm()
    {
        _angle = 0.0;
        _angTra = 0.0;
        _done = false;
        _isTrans = false;
        _ = (_vec, _tra, _pnt1, _pnt2);
    }

    public void Perform(in Shape Base, in Axis3D axis, double angle)
    {
        _map.Clear();
        _firstShape.Nullify();
        _lastShape.Nullify();
        _base.Nullify();
        _res.Nullify();
        _base = Base;
        _angle = angle;
        _axis = axis;
        _angTra = 0.0;
        _isTrans = false;
        IntPerf();
    }

    private void IntPerf()
    {
        Shape theBase = _base;
        Modifier modif = new();
        if (_isTrans)
        {
            Transform3D t = new Transform3D().WithRotation(_axis, _angTra);
            TrsfModification modbase = new(t);
            modif.Init(theBase);
            modif.Perform(modbase);
            theBase = modif.InternalModifiedShape(theBase);
        }

        // OCCT.NET: the sweep writes into the base it shares (decision 1014): in the working overlay (unit 10H5)
        _work = new WorkingShapes();
        using WorkingOverlay.Scope scope = _work.Enter();

        Revol theRevol = new(theBase, _axis, _angle);

        _firstShape = theRevol.FirstShape();
        _lastShape = theRevol.LastShape();

        Explorer exp = new();
        if (theBase.ShapeType() == ShapeType.Face)
        {
            for (exp.Init(theBase, ShapeType.Edge); exp.More(); exp.Next())
            {
                Edge edg = ShapeCasts.Edge(exp.Current());
                if (!_map.ContainsKey(edg))
                {
                    NCollection_List<Shape> thelist = new();
                    _map[edg] = thelist;
                    Shape desc = theRevol.Shape(edg);
                    if (!desc.IsNull)
                    {
                        _map.GetValue(edg).Append(desc);
                    }
                }
            }
            _res = theRevol.Shape();
        }

        else
        {
            // Cas base != FACE
            IndexedMap<Shape, NCollection_List<Shape>> theEFMap = new(ShapeHasher.Instance);
            Exploration.MapShapesAndAncestors(theBase, ShapeType.Edge, ShapeType.Face, theEFMap);
            NCollection_List<Shape> lfaces = new();
            bool toremove = false;
            for (int i = 0; i < theEFMap.Count; i++)
            {
                Shape edg = theEFMap.KeyAt(i);
                NCollection_List<Shape> thelist1 = new();
                _map[edg] = thelist1;
                Shape desc = theRevol.Shape(edg);
                if (!desc.IsNull)
                {
                    if (theEFMap.ValueAt(i).Extent() >= 2)
                    {
                        toremove = true;
                    }
                    else
                    {
                        _map.GetValue(edg).Append(desc);
                        lfaces.Append(desc);
                    }
                }
            }
            if (toremove)
            {
                // Rajouter les faces de FirstShape et LastShape
                for (exp.Init(_firstShape, ShapeType.Face); exp.More(); exp.Next())
                {
                    lfaces.Append(exp.Current());
                }
                for (exp.Init(_lastShape, ShapeType.Face); exp.More(); exp.Next())
                {
                    lfaces.Append(exp.Current());
                }

                BuildShape bs = new(lfaces);
                _res = bs.InternalShape();
            }
            else
            {
                for (exp.Init(theBase, ShapeType.Edge); exp.More(); exp.Next())
                {
                    Edge edg = ShapeCasts.Edge(exp.Current());
                    if (!_map.ContainsKey(edg))
                    {
                        NCollection_List<Shape> thelist2 = new();
                        _map[edg] = thelist2;
                        Shape desc = theRevol.Shape(edg);
                        if (!desc.IsNull)
                        {
                            _map.GetValue(edg).Append(desc);
                        }
                    }
                }
                _res = theRevol.Shape();
            }
        }

        if (_isTrans)
        {
            // m-a-j des descendants
            Explorer anExp = new();
            for (anExp.Init(_base, ShapeType.Edge); anExp.More(); anExp.Next())
            {
                Edge edg = ShapeCasts.Edge(anExp.Current());
                Edge edgbis = ShapeCasts.Edge(modif.InternalModifiedShape(edg));
                if (!edgbis.IsSame(edg) && _map.ContainsKey(edgbis))
                {
                    _map[edg] = _map.GetValue(edgbis);
                    _map.Remove(edgbis);
                }
            }
        }

        // Kerf: the end of the working overlay: new TShapes for the caller's sub-shapes changed (unit 10H5)
        if (_work.IsWritten)
        {
            var shapes = new List<Shape> { _res, _firstShape, _lastShape };
            foreach (KeyValuePair<Shape, NCollection_List<Shape>> item in _map)
            {
                shapes.AddRange(item.Value);
            }
            _work.Finish(shapes);
            _res = _work.Final(_res);
            _firstShape = _work.Final(_firstShape);
            _lastShape = _work.Final(_lastShape);
            foreach (Shape key in _map.Keys.ToList())
            {
                _map.GetValueRef(key) = _work.Final(_map.GetValue(key));
            }
        }
        _done = true;
    }

    /// <summary>The shape (frozen).</summary>
    public Shape Shape() => WorkingShapes.Published(InternalShape());

    /// <summary><see cref="Shape"/> without freezing, for ported code.</summary>
    internal Shape InternalShape()
    {
        if (!_done)
        {
            throw new NotDoneException();
        }
        return _res;
    }

    /// <summary>The base's image at the start (frozen).</summary>
    public Shape FirstShape() => WorkingShapes.Published(_firstShape);

    /// <summary><see cref="FirstShape"/> without freezing, for ported code.</summary>
    internal Shape InternalFirstShape() => _firstShape;

    /// <summary>The base's image at the end (frozen).</summary>
    public Shape LastShape() => WorkingShapes.Published(_lastShape);

    /// <summary><see cref="LastShape"/> without freezing, for ported code.</summary>
    internal Shape InternalLastShape() => _lastShape;

    /// <summary>The faces generated by the edge <paramref name="s"/> of the base (frozen).</summary>
    public NCollection_List<Shape> Shapes(in Shape s) => WorkingShapes.Published(InternalShapes(s));

    /// <summary><see cref="Shapes"/> without freezing, for ported code.</summary>
    internal NCollection_List<Shape> InternalShapes(in Shape s) => _map.GetValue(s);
}
