/// <summary>
/// The drafted prism of a planar face (an evolved shape of the face along a sloped profile): the shape, its first and
/// last shapes, the faces generated by the face's edges, and curves to intersect with the solid it is glued on.
/// </summary>
/// <remarks>
/// The evolved shape shares the spine face's sub-shapes, and OCCT raises their tolerances in place
/// (<c>BRepLib::UpdateTolerances</c> on the result): a frozen spine is written in a working overlay (unit 10H5,
/// <see cref="WorkingShapes"/>), and the result holds new TShapes only for its sub-shapes that changed (decision
/// 1014). The shapes it hands out are frozen; ported
/// callers (BRepFeat_MakeDPrism) read the <c>Internal</c> forms.
/// </remarks>
public sealed class DPrism
{
    private const int Nechant = 7; // voir BRepFeat.cxx

    private readonly Evolved _dPrism = new();
    private Shape _res = new();
    private readonly Face _spine;
    private Wire _profile = new();
    private Edge _profile1 = new();
    private Edge _profile2 = new();
    private Edge _profile3 = new();
    private readonly double _height;
    private Shape _firstShape = new();
    private Shape _lastShape = new();
    private readonly Dictionary<Shape, NCollection_List<Shape>> _map = new(ShapeHasher.Instance);
    private readonly WorkingShapes _work = new();

    public DPrism(in Face spine, double height1, double height2, double angle)
    {
        _spine = spine;
        _height = height1 + height2;
        double y = height1 * Math.Sin(angle);
        double z = height1 * Math.Cos(angle);

        Vertex vert2 = new LibraryMakeVertex(new Point3D(0, y, z)).InternalVertex();

        double y1 = -height2 * Math.Sin(angle);
        double z1 = -height2 * Math.Cos(angle);

        Vertex vert1 = new LibraryMakeVertex(new Point3D(0, y1, z1)).InternalVertex();

        _profile2 = new LibraryMakeEdge(vert1, vert2).InternalEdge();

        double umin, umax, vmin, vmax;
        BrepTools.UVBounds(spine, out umin, out umax, out vmin, out vmax);
        double deltay = Max(umax - umin, vmax - vmin) + Math.Abs(y);
        deltay *= 2;

        Vertex vert3 = new LibraryMakeVertex(new Point3D(0, y + deltay, z)).InternalVertex();
        _profile3 = new LibraryMakeEdge(vert2, vert3).InternalEdge();

        BrepTools.UVBounds(spine, out umin, out umax, out vmin, out vmax);
        double deltay1 = Max(umax - umin, vmax - vmin) + Math.Abs(y1);
        deltay1 *= 2;

        Vertex vert4 = new LibraryMakeVertex(new Point3D(0, y1 + deltay1, z1)).InternalVertex();
        _profile1 = new LibraryMakeEdge(vert4, vert1).InternalEdge();

        _profile = new LibraryMakeWire(_profile1, _profile2, _profile3).InternalWire();

        // OCCT.NET: the evolved shape shares the spine's sub-shapes, whose tolerances are raised below (decision 1014):
        // in the working overlay (unit 10H5)
        using WorkingOverlay.Scope scope = _work.Enter();
        Face aSpine = _spine;
        _dPrism.Perform(aSpine, _profile, new CoordinateSystem(Constants.XOY()));

        if (_dPrism.IsDone)
        {
            BuildShape bs = new();
            BrepBuilder b = new();
            Compound c = new();
            Compound d = new();
            NCollection_List<Shape> lfaces = new(), lcomplete = new();

            b.MakeCompound(ref c);
            NCollection_List<Shape>.Iterator it = new();
            Explorer expS = new(aSpine, ShapeType.Edge);
            HashSet<Shape> view = new(ShapeHasher.Instance);
            for (; expS.More(); expS.Next())
            {
                Shape es = expS.Current();
                NCollection_List<Shape> lffs = _dPrism.InternalGeneratedShapes(es, _profile1);
                for (it.Initialize(lffs); it.More(); it.Next())
                {
                    if (view.Add(it.Value()))
                    {
                        b.Add(c, it.Value());
                    }
                }
            }

            EndFaces(c, lfaces, lcomplete);

            bs.Perform(lfaces);
            _firstShape = bs.InternalShape();

            b.MakeCompound(ref d);

            expS.ReInit();
            view.Clear();

            for (; expS.More(); expS.Next())
            {
                Shape es = expS.Current();
                NCollection_List<Shape> lfls = _dPrism.InternalGeneratedShapes(es, _profile3);
                for (it.Initialize(lfls); it.More(); it.Next())
                {
                    if (view.Add(it.Value()))
                    {
                        b.Add(d, it.Value());
                    }
                }
            }

            lfaces.Clear();
            EndFaces(d, lfaces, lcomplete);
            bs.Perform(lfaces);
            _lastShape = bs.InternalShape();

            view.Clear();

            for (expS.ReInit(); expS.More(); expS.Next())
            {
                Shape es = expS.Current();
                NCollection_List<Shape> lffs = _dPrism.InternalGeneratedShapes(es, _profile2);

                for (it.Initialize(lffs); it.More(); it.Next())
                {
                    if (it.Value().ShapeType() == ShapeType.Edge)
                    {
                        break;
                    }
                }
                if (it.More())
                {
                    Shape removedEdge = it.Value();
                    Face newFace = new();
                    Wire newWire = new();
                    b.MakeWire(ref newWire);
                    Orientation orref = Forward;
                    Explorer exp = new();
                    for (it.Initialize(lffs); it.More(); it.Next())
                    {
                        if (it.Value().ShapeType() == ShapeType.Face)
                        {
                            exp.Init(it.Value().Oriented(Forward), ShapeType.Wire);
                            Shape theWire = exp.Current();
                            if (newFace.IsNull)
                            {
                                Surface s = Tool.Surface(ShapeCasts.Face(it.Value()))!;
                                if (s.GetType() == typeof(TrimmedSurface))
                                {
                                    s = ((TrimmedSurface)s).BasisSurface();
                                }
                                if (s.GetType() != typeof(PlaneSurface))
                                {
                                    break;
                                }

                                b.MakeFace(ref newFace, s, Tool.Tolerance(ShapeCasts.Face(it.Value())));
                                newFace.Orientation(Forward);
                                orref = theWire.Orientation();
                                for (exp.Init(theWire.Oriented(Forward), ShapeType.Edge); exp.More(); exp.Next())
                                {
                                    if (!exp.Current().IsSame(removedEdge))
                                    {
                                        b.Add(newWire, exp.Current());
                                    }
                                }
                            }
                            else
                            {
                                for (exp.Init(theWire.Oriented(Forward), ShapeType.Edge); exp.More(); exp.Next())
                                {
                                    if (!exp.Current().IsSame(removedEdge))
                                    {
                                        if (theWire.Orientation() != orref)
                                        { // Les 2 faces planes ont des normales opposees
                                            b.Add(newWire, exp.Current());
                                        }
                                        else
                                        {
                                            b.Add(newWire, exp.Current().Reversed());
                                        }
                                    }
                                }
                            }
                        }
                    }
                    if (!newFace.IsNull)
                    {
                        b.Add(newFace, newWire.Oriented(orref));
                        lcomplete.Append(newFace);
                        NCollection_List<Shape> thelist = new();
                        _map[es] = thelist;
                        _map.GetValue(es).Append(newFace);
                    }
                    else
                    {
                        for (it.Initialize(lffs); it.More(); it.Next())
                        {
                            if (view.Add(it.Value()) && it.Value().ShapeType() == ShapeType.Face)
                            {
                                lcomplete.Append(it.Value());
                            }
                        }
                    }
                }
                else
                {
                    for (it.Initialize(lffs); it.More(); it.Next())
                    {
                        if (view.Add(it.Value()) && it.Value().ShapeType() == ShapeType.Face)
                        {
                            lcomplete.Append(it.Value());
                        }
                    }
                }

                Explorer expS2 = new();
                for (expS2.Init(es, ShapeType.Vertex); expS2.More(); expS2.Next())
                {
                    NCollection_List<Shape> ls2 = _dPrism.InternalGeneratedShapes(expS2.Current(), _profile2);
                    for (it.Initialize(ls2); it.More(); it.Next())
                    {
                        if (view.Add(it.Value()) && it.Value().ShapeType() == ShapeType.Face)
                        {
                            lcomplete.Append(it.Value());
                        }
                    }
                }
            }

            bs.Perform(lcomplete);
            _res = bs.InternalShape();
            BrepLibrary.UpdateTolerances(_res);
            Finish();
        }
    }

    public DPrism(in Face spine, double height, double angle)
    {
        _spine = spine;
        _height = height;
        double y = height * Math.Sin(angle);
        double z = height * Math.Cos(angle);

        Vertex vert1 = new LibraryMakeVertex(new Point3D(0, 0, 0)).InternalVertex();
        Vertex vert2 = new LibraryMakeVertex(new Point3D(0, y, z)).InternalVertex();
        _profile2 = new LibraryMakeEdge(vert1, vert2).InternalEdge();

        BrepTools.UVBounds(spine, out double umin, out double umax, out double vmin, out double vmax);
        double deltay = Max(umax - umin, vmax - vmin) + Math.Abs(y);
        deltay *= 2;

        Vertex vert3 = new LibraryMakeVertex(new Point3D(0, y + deltay, z)).InternalVertex();
        _profile3 = new LibraryMakeEdge(vert2, vert3).InternalEdge();

        Vertex vert4 = new LibraryMakeVertex(new Point3D(0, deltay, 0)).InternalVertex();
        _profile1 = new LibraryMakeEdge(vert4, vert1).InternalEdge();

        _profile = new LibraryMakeWire(_profile1, _profile2, _profile3).InternalWire();

        // OCCT.NET: the evolved shape shares the spine's sub-shapes, whose tolerances are raised below (decision 1014):
        // in the working overlay (unit 10H5)
        using WorkingOverlay.Scope scope = _work.Enter();
        Face aSpine = _spine;
        _dPrism.Perform(aSpine, _profile, new CoordinateSystem(Constants.XOY()));

        if (_dPrism.IsDone)
        {
            BuildShape bs = new();
            BrepBuilder b = new();
            Compound c = new();
            Compound d = new();
            NCollection_List<Shape> lfaces = new(), lcomplete = new();

            b.MakeCompound(ref c);
            NCollection_List<Shape>.Iterator it = new();
            Explorer expS = new(aSpine, ShapeType.Edge);
            HashSet<Shape> view = new(ShapeHasher.Instance);
            for (; expS.More(); expS.Next())
            {
                Shape es = expS.Current();
                NCollection_List<Shape> lffs = _dPrism.InternalGeneratedShapes(es, _profile1);
                for (it.Initialize(lffs); it.More(); it.Next())
                {
                    if (view.Add(it.Value()))
                    {
                        b.Add(c, it.Value());
                    }
                }
            }

            EndFaces(c, lfaces, lcomplete);

            bs.Perform(lfaces);
            _firstShape = bs.InternalShape();

            b.MakeCompound(ref d);

            expS.ReInit();
            view.Clear();

            for (; expS.More(); expS.Next())
            {
                Shape es = expS.Current();
                NCollection_List<Shape> lfls = _dPrism.InternalGeneratedShapes(es, _profile3);
                for (it.Initialize(lfls); it.More(); it.Next())
                {
                    if (view.Add(it.Value()))
                    {
                        b.Add(d, it.Value());
                    }
                }
            }

            lfaces.Clear();
            EndFaces(d, lfaces, lcomplete);
            bs.Perform(lfaces);
            _lastShape = bs.InternalShape();

            view.Clear();
            for (expS.ReInit(); expS.More(); expS.Next())
            {
                Shape es = expS.Current();
                NCollection_List<Shape> ls = _dPrism.InternalGeneratedShapes(es, _profile2);
                for (it.Initialize(ls); it.More(); it.Next())
                {
                    if (view.Add(it.Value()))
                    {
                        lcomplete.Append(it.Value());
                    }
                }
                Explorer expS2 = new();
                for (expS2.Init(es, ShapeType.Vertex); expS2.More(); expS2.Next())
                {
                    NCollection_List<Shape> ls2 = _dPrism.InternalGeneratedShapes(expS2.Current(), _profile2);
                    for (it.Initialize(ls2); it.More(); it.Next())
                    {
                        if (view.Add(it.Value()) && it.Value().ShapeType() == ShapeType.Face)
                        {
                            lcomplete.Append(it.Value());
                        }
                    }
                }
            }

            bs.Perform(lcomplete);
            _res = bs.InternalShape();
            BrepLibrary.UpdateTolerances(_res);
            Finish();
        }
    }

    // The faces of the compound with a free edge, each rebuilt with the wire holding that edge (OCCT repeats this
    // block for the first and last shapes in both constructors)
    private static void EndFaces(in Compound c, NCollection_List<Shape> lfaces, NCollection_List<Shape> lcomplete)
    {
        BrepBuilder b = new();
        IndexedMap<Shape, NCollection_List<Shape>> theMapEF = new(ShapeHasher.Instance);
        Exploration.MapShapesAndAncestors(c, ShapeType.Edge, ShapeType.Face, theMapEF);
        HashSet<Shape> view = new(ShapeHasher.Instance);

        for (int i = 0; i < theMapEF.Count; i++)
        {
            if (theMapEF.ValueAt(i).Extent() == 1)
            {
                Edge edg = ShapeCasts.Edge(theMapEF.KeyAt(i));
                Face fac = ShapeCasts.Face(theMapEF.ValueAt(i).First());
                if (view.Add(fac))
                {
                    Shape localShape = fac.EmptyCopied();
                    Face newFace = ShapeCasts.Face(localShape);
                    Explorer exp = new();
                    for (exp.Init(fac.Oriented(Forward), ShapeType.Wire); exp.More(); exp.Next())
                    {
                        Explorer exp2 = new(exp.Current(), ShapeType.Edge);
                        for (; exp2.More(); exp2.Next())
                        {
                            if (exp2.Current().IsSame(edg))
                            {
                                b.Add(newFace, exp.Current());
                                lfaces.Append(newFace);
                                lcomplete.Append(newFace);
                                break;
                            }
                        }
                        if (exp2.More())
                        {
                            break;
                        }
                    }
                }
            }
        }
    }

    // Kerf: the end of the working overlay: new TShapes for the spine's sub-shapes changed (unit 10H5)
    private void Finish()
    {
        if (!_work.IsWritten)
        {
            return;
        }
        var shapes = new List<Shape> { _res, _firstShape, _lastShape };
        foreach (KeyValuePair<Shape, NCollection_List<Shape>> item in _map)
        {
            shapes.AddRange(item.Value);
        }
        _work.Finish(shapes);
        _res = _work.Final(_res);
        _firstShape = _work.Final(_firstShape);
        _lastShape = _work.Final(_lastShape);
        foreach (Shape key in _map.Keys.ToList())
        {
            _map.GetValueRef(key) = _work.Final(_map.GetValue(key));
        }
    }

    public bool IsDone => _dPrism.IsDone;

    /// <summary>The drafted prism (frozen).</summary>
    public Shape Shape() => WorkingShapes.Published(InternalShape());

    /// <summary><see cref="Shape"/> without freezing, for ported code.</summary>
    internal Shape InternalShape()
    {
        if (!_dPrism.IsDone)
        {
            throw new NotDoneException();
        }
        return _res;
    }

    /// <summary>The spine (the caller's face).</summary>
    public Shape Spine() => _spine;

    /// <summary>The profile (frozen).</summary>
    public Shape Profile() => WorkingShapes.Published(_profile);

    /// <summary>The faces at the start (frozen).</summary>
    public Shape FirstShape() => WorkingShapes.Published(_firstShape);

    /// <summary><see cref="FirstShape"/> without freezing, for ported code.</summary>
    internal Shape InternalFirstShape() => _firstShape;

    /// <summary>The faces at the end (frozen).</summary>
    public Shape LastShape() => WorkingShapes.Published(_lastShape);

    /// <summary><see cref="LastShape"/> without freezing, for ported code.</summary>
    internal Shape InternalLastShape() => _lastShape;

    /// <summary>The shapes generated by the sub-shape <paramref name="s"/> of the spine (frozen).</summary>
    public NCollection_List<Shape> Shapes(in Shape s) => WorkingShapes.Published(InternalShapes(s));

    /// <summary><see cref="Shapes"/> without freezing, for ported code.</summary>
    internal NCollection_List<Shape> InternalShapes(in Shape s)
    {
        if (!_dPrism.IsDone)
        {
            throw new NotDoneException();
        }
        Shape aS = s;
        if (_map.ContainsKey(aS))
        {
            return _map.GetValue(aS);
        }
        else
        {
            return _work.Final(_dPrism.InternalGeneratedShapes(aS, _profile2));
        }
    }

    /// <summary>Lines along the draft through points sampled on the spine's edges.</summary>
    public void Curves(NCollection_Sequence<Curve3D> scurves)
    {
        // Retrieves dy and dz with myProfile2
        Exploration.Vertices(_profile2, out Vertex v1, out Vertex v2);
        Point3D p1 = Tool.Pnt(v1);
        Point3D p2 = Tool.Pnt(v2);
        double dy = p2.Y() - p1.Y();
        double dz = p2.Z() - p1.Z();
        scurves.Clear();
        Surface s = Tool.Surface(_spine)!;
        if (s.GetType() == typeof(TrimmedSurface))
        {
            s = ((TrimmedSurface)s).BasisSurface();
        }

        PlaneSurface pp = s as PlaneSurface ?? throw new ConstructionErrorException();

        Plane3D p = pp.Pln();
        Direction3D normale = p.Axis().Direction();
        if (!p.Direct())
        {
            normale = normale.Reversed();
        }

        HashSet<Shape> theMap = new(ShapeHasher.Instance);
        Explorer exp = new(_spine.Oriented(Forward), ShapeType.Edge);
        double prm;
        int i;

        for (; exp.More(); exp.Next())
        {
            Edge edg = ShapeCasts.Edge(exp.Current());
            if (!theMap.Add(edg))
            {
                continue;
            }
            if (!Tool.Degenerated(edg))
            {
                Curve3D c = Tool.Curve(edg, out Placement loc, out double f, out double l)!;
                c = (Curve3D)c.Transformed(loc.Transformation());
                double u1 = -2 * Math.Abs(_height);
                double u2 = 2 * Math.Abs(_height);

                for (i = 0; i <= Nechant; i++)
                {
                    prm = ((Nechant - i) * f + i * l) / Nechant;
                    c.D1(prm, out Point3D pt, out Vector3D d1);
                    if (exp.Current().Orientation() == Reversed)
                    {
                        d1 = d1.Reversed();
                    }
                    d1 = d1.Normalized();
                    Direction3D locy = normale.Crossed(new Direction3D(d1));
                    Vector3D ldir = new(dy * locy.XYZ() + dz * normale.XYZ());
                    Line3D lin = new(pt, new Direction3D(ldir));
                    LineCurve3D Lin = new(lin);
                    TrimmedCurve3D trlin = new(Lin, u1, u2, true);
                    scurves.Append(trlin);
                }
            }
        }
    }

    /// <summary>The line along the draft through the barycentre of points sampled on the first shape (or the spine).</summary>
    public Curve3D BarycCurve()
    {
        Exploration.Vertices(_profile2, out Vertex v1, out Vertex v2);
        Point3D p1 = Tool.Pnt(v1);
        Point3D p2 = Tool.Pnt(v2);
        double dz = p2.Z() - p1.Z();

        Surface s = Tool.Surface(_spine)!;
        if (s.GetType() == typeof(TrimmedSurface))
        {
            s = ((TrimmedSurface)s).BasisSurface();
        }

        PlaneSurface pp = s as PlaneSurface ?? throw new ConstructionErrorException();

        Plane3D p = pp.Pln();
        Direction3D normale = p.Axis().Direction();
        if (!p.Direct())
        {
            normale = normale.Reversed();
        }
        if (_spine.Orientation() == Reversed)
        {
            // OCCT_DEBUG trace left out
            //    Normale.Reverse();  //cts20871
        }
        Vector3D vec = new(dz * normale.XYZ());

        NCollection_Sequence<Point3D> spt = new();
        if (!_firstShape.IsNull)
        {
            global::Kerf.Engine.Features.Local.LocOpe.SampleEdges(_firstShape, spt);
        }
        else
        {
            global::Kerf.Engine.Features.Local.LocOpe.SampleEdges(_spine, spt);
        }
        Xyz aBar = new(0.0, 0.0, 0.0);
        for (int jj = 1; jj <= spt.Length(); jj++)
        {
            Point3D pvt = spt[jj];
            aBar += pvt.XYZ();
        }
        aBar.Divide(spt.Length());
        Point3D bar = new(aBar);
        Axis3D newAx = new(bar, new Direction3D(vec));
        LineCurve3D theLin = new(newAx);
        return theLin;
    }
}
