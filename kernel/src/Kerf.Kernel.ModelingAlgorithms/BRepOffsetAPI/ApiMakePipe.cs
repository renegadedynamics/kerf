/// <summary>
/// Builds a pipe: a profile (any shape but a solid) swept along a wire (the spine), keeping the angle the spine makes
/// with the profile. The spine must be G1 continuous.
/// </summary>
/// <remarks>
/// <para>OCCT's pipe sweeps the profile in place and writes into the sub-shapes of it the result shares. Kerf sweeps the
/// caller's profile itself in a working overlay, as <see cref="ApiMakePrism"/> does (<see cref="MakeSweep"/>, unit
/// 10H3): the result holds the profile's own sub-shapes wherever the sweep left them unchanged, the history answers
/// for the caller's sub-shapes directly, and the profile is never changed.</para>
/// <para>The result, <see cref="MakeSweep.FirstShape()"/>, <see cref="MakeSweep.LastShape()"/>
/// and the history are frozen when returned (design 4.2).</para>
/// </remarks>
internal class ApiMakePipe : MakeSweep
{
    private readonly Pipe _pipe;

    /// <summary>
    /// The pipe of <paramref name="profile"/> along <paramref name="spine"/> (corrected Frenet trihedron).
    /// </summary>
    /// <exception cref="DomainErrorException">The profile is a solid or a composite solid.</exception>
    public ApiMakePipe(in Wire spine, in Shape profile)
    {
        using WorkingOverlay? overlay = BeginGenerating(profile);
        _pipe = new Pipe(spine, profile);
        Build();
    }

    /// <summary>
    /// The pipe of <paramref name="profile"/> along <paramref name="spine"/> with the trihedron
    /// <paramref name="aMode"/> (Frenet, corrected Frenet or discrete), and an attempt at C1 surfaces where a swept
    /// surface is C0 with <paramref name="forceApproxC1"/>.
    /// </summary>
    public ApiMakePipe(in Wire spine,
                                  in Shape profile,
                                  Trihedron aMode,
                                  bool forceApproxC1 = false)
    {
        using WorkingOverlay? overlay = BeginGenerating(profile);
        _pipe = new Pipe(spine, profile, aMode, forceApproxC1);
        Build();
    }

    /// <summary>The internal pipe algorithm (keyed by the profile's own sub-shapes).</summary>
    internal Pipe Pipe() => _pipe;

    /// <summary>Builds the resulting shape (redefined from MakeShape).</summary>
    public override void Build(ProgressRange range = default)
    {
        _shape = _pipe.InternalShape();
        FinishGenerating(ref _shape);
        // Check for emptiness of result
        IndexedSet<Shape> theMap = new(ShapeHasher.Instance);
        Exploration.MapShapes(_shape, theMap);
        if (theMap.Count == 1)
        {
            NotDone();
        }
        else
        {
            Done();
        }
    }

    internal override Shape InternalFirstShape() => FromSwept(_pipe.InternalFirstShape());

    internal override Shape InternalLastShape() => FromSwept(_pipe.InternalLastShape());

    /// <summary>The list of shapes generated from the shape <paramref name="s"/>, of the profile or the spine.</summary>
    internal override NCollection_List<Shape> InternalGenerated(in Shape s)
    {
        NCollection_List<Shape> list = new();
        _pipe.InternalGenerated(s, list);
        _generated.Clear();
        for (NCollection_List<Shape>.Iterator it = new(list); it.More(); it.Next())
        {
            _generated.Append(FromSwept(it.Value()));
        }
        return _generated;
    }

    /// <summary>
    /// The face generated by an edge of the spine and an edge of the profile, or the edge generated by an edge of the
    /// spine and a vertex of the profile (frozen; null for other shapes).
    /// </summary>
    public Shape Generated(in Shape sSpine, in Shape sProfile) => Published(InternalGenerated(sSpine, sProfile));

    /// <summary><see cref="Generated(in Shape, in Shape)"/> without freezing.</summary>
    internal Shape InternalGenerated(in Shape sSpine, in Shape sProfile)
    {
        if (sProfile.Type == ShapeType.Edge)
        {
            return FromSwept(_pipe.InternalFace(ShapeCasts.Edge(sSpine), ShapeCasts.Edge(sProfile)));
        }
        else if (sProfile.Type == ShapeType.Vertex)
        {
            return FromSwept(_pipe.InternalEdge(ShapeCasts.Edge(sSpine), ShapeCasts.Vertex(sProfile)));
        }

        // POP pour NT
        Shape bid = new();
        return bid;
    }

    /// <summary>The approximation error of the swept surfaces.</summary>
    public double ErrorOnSurface() => _pipe.ErrorOnSurface();
}
